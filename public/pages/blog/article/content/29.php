<section>
    <h2>Свет — главный дизайнер интерьера</h2>
    <p>Хороший свет делает дешёвый ремонт дорогим, плохой — дорогой ремонт дешёвым. В 2026 году стандарт — многоуровневое освещение по сценариям: «Утро», «Работа», «Вечер», «Гости», «Ночник», «Кино». Ниже — по комнатам: какие приборы, где монтировать, как управлять.</p>
</section>

<section>
    <h2>Спальня: режим «Сон» и «Пробуждение»</h2>
    <ul>
        <li><strong>Общий свет:</strong> Потолковый светильник 3000K, 15–20 Вт/м², диммируемый. Или магнитный трек с 2–3 спотами (по 8–10 Вт каждый) — регулируете направление.</li>
        <li><strong>Чтение у кровати:</strong> Стенные бра / подвески по бокам кровати 2700K, 3–5 Вт, узкий луч (24–36°). Высота 30–40 см от подушки. Управление: пульт / сенсор на бра / умная лампа.</li>
        <li><strong>Туалетный столик:</strong> LED-профиль в зеркале (контурный) или 2 бра по бокам зеркала 4000K, CRI>90 — для макияжа.</li>
        <li><strong>Ночник:</strong> LED-линта под кроватью (датчик движения) или встроена в плинтус — 2000K, 0.5 Вт/м, не бьёт в глаза.</li>
    </ul>
    <p><strong>Сценарий «Сон»:</strong> Один тап — гаснет общий свет, горят только ночники и подсветка зеркала на 10%.</p>
</section>

<section>
    <h2>Гостиная / Кухня-гостиная: зонирование светом</h2>
    <ul>
        <li><strong>Зона дивана (релакс):</strong> Трек/профиль над диваном 3000K, димминг. Споты направлены на стену (отражённый свет) или на пол.</li>
        <li><strong>Столовая зона:</strong> Подвеска над столом 2700–3000K, 40–60 Вт суммарно, CRI>90. Высота 70–80 см от столешницы. Диммер обязателен.</li>
        <li><strong>Рабочая зона / барная стойка:</strong> Направленный свет (трек/споты) 4000K на столешницу/поверхность.</li>
        <li><strong>Декор:</strong> LED-профиля в нишах, за телевизором (bias lighting 6500K — снимает усталость глаз), в плинтусе по периметру (ночной режим).</li>
    </ul>
</section>

<section>
    <h2>Кухня: функциональность превыше всего</h2>
    <ul>
        <li><strong>Общий:</strong> Потолковые светильники / трек 4000K, равномерное освещение 300–400 лк.</li>
        <li><strong>Рабочая зона (фартук):</strong> LED-профиль под верхними шкафами 4000K, CRI>95, 10–15 Вт/м. Включение отдельно от общего света.</li>
        <li><strong>Остров / барная стойка:</strong> Подвески 2700K, узкий луч, высота 75–85 см.</li>
        <li><strong>Внутри шкафов:</strong> Датчики движения — открыл дверь, загорелось.</li>
    </ul>
</section>

<section>
    <h2>Ванная: безопасность и зеркало</h2>
    <ul>
        <li><strong>Зеркало:</strong> Контурная подсветка (LED-профиль по периметру) 4000K, CRI>90 — для бритья/макияжа. Или бра по бокам (не сверху — тени под глазами).</li>
        <li><strong>Общий:</strong> IP44+, 4000K, влагозащищённые споты/плафоны.</li>
        <li><strong>Душ/ванна:</strong> IP65 споты в потолке (если есть ниша) или влагозащищённый плафон.</li>
        <li><strong>Ночник:</strong> Плинтус или под ванной — датчик движения, 2000K.</li>
    </ul>
</section>

<section>
    <h2>Прихожая: первое впечатление</h2>
    <ul>
        <li>Яркий общий свет 4000K (одеваешься, проверяешь вид).</li>
        <li>Зеркало с подсветкой (как в ванной).</li>
        <li>Подсветка обуви внизу шкафа / плинтус — удобно ночью.</li>
        <li>Датчик движения — свет загорается при входе, гаснет через 2 мин.</li>
    </ul>
</section>

