<section id="stage5">
    <h2>Этап 5: 5 ошибок при выборе и установке</h2>
    <div data-type="compare">
        <h3>Ошибка vs Правильно</h3>
        <article data-variant="bad">
            <h4>Ошибка</h4>
            <p>1. Окно без учёта стороны света — перегрев летом на южной стороне;<br>
            2. Экономия на фурнитуре — ручка отвалится через год;<br>
            3. Входная дверь без терморазрыва — конденсат и обледенение;<br>
            4. Межкомнатная дверь в ванную без влагостойкого полотна — разбухнет;<br>
            5. Пена без откосов — разрушится за сезон.</p>
        </article>
        <article data-variant="good">
            <h4>Правильно</h4>
            <p>Мультифункциональное стекло на южной стороне, качественная фурнитура (Roto, Siegenia), терморазрыв на входной двери, влагостойкие полотна в санузел, откосы сразу после монтажа.</p>
        </article>
    </div>
