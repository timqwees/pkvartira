<section id="stage3">
    <h2>Этап 3: Этапы установки окон и дверей</h2>
    <p><strong>Окна:</strong> замер → демонтаж старых → подготовка проема → установка блока → монтажная пена → отлив и откосы → подоконник → регулировка фурнитуры (1 день на окно).</p>
    <p><strong>Двери:</strong> замер → демонтаж → установка коробки → подвешивание полотна → установка наличников и фурнитуры → регулировка (2-3 часа на дверь).</p>
    <div data-type="box" data-color="gray">
        <h3>Важно</h3>
        <p>Монтажную пену закрывают откосами сразу — на солнце она разлагается за 2 недели. Шов между коробкой и стеной замазывается акриловым герметиком.</p>
    </div>
