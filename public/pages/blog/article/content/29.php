<section>
    <h2>Ошибки, которые портят свет</h2>
    <ol>
        <li><strong>Один люстр на всю комнату</strong> — тени в углах, слепящий блик, никакого зонирования.</li>
        <li><strong>Холодный белый (6000K) в спальне/гостиной</strong> — больничный вид, подавляет мелатонин, плохой сон.</li>
        <li><strong>Свет сверху зеркала в ванной</strong> — тени под глазами, носом, щёками. Только по бокам или контур.</li>
        <li><strong>Нет диммеров</strong> — не можете адаптировать свет под задачу.</li>
        <li><strong>Пульсация дешёвых LED</strong> — усталость глаз, головная боль. Проверяйте камерой телефона (нет полос = хорошо).</li>
        <li><strong>Провода на вид / розетки для напольных торшеров</strong> — быт, тревожность. Закладывайте в штукатурке/потолке.</li>
        <li><strong>Игнорирование CRI</strong> — дешёвые лампы CRI<80 искажают цвета (еда бледная, кожа сероватая). Минимум CRI>90, лучше >95.</li>
    </ol>
</section>

