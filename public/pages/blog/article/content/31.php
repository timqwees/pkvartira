<section>
    <h2>Что делает квартиру «арендодательной» (чек-лист)</h2>
    <ol>
        <li><strong>Чистая входная группа:</strong> Металлическая дверь с 2 замками (цилиндровый + сувалдный), домофон с камерой, коврик, крючки, зеркало, подсветка.</li>
        <li><strong>Рабочее место:</strong> Стол 120×60 см, эргономичный стул, розетки (2×220В + USB-C), хороший свет 4000K.</li>
        <li><strong>Сон:</strong> Ортопедический матрас (не пена!), 2 подушки разной жёсткости, блэкаут-шторы / ролики.</li>
        <li><strong>Кухня:</strong> Плита (индукция/газ), ПММ, вытяжка (мощность 300+ м³/ч), микроволновка, посуда для 4 человек, базовые специи/масла.</li>
        <li><strong>Ванная:</strong> Дuschная кабина / ванна + душ, стиральная машина (встроенная/колонна), полотенцесушитель (водяной — бесплатно от ЦО), полотенца (2 на гостя).</li>
        <li><strong>Климат:</strong> Кондиционер (инверторный, тихий), бризер/клапан на окне (свежий воздух без сквозняка).</li>
        <li><strong>Хранение:</strong> Гардеробная / прихожая с системой, ящики для белья, полка для обуви.</li>
        <li><strong>Технологичность:</strong> Умный замок / кодовый замок (удалённый доступ для гостей), Wi-Fi 5 ГГц (роутер в открытую), розетки USB-C в каждой зоне.</li>
    </ol>
</section>

