        <li><strong>4. Пол</strong> — ламинат или линолеум, плинтусы (2-3 дня);</li>
        <li><strong>5. Двери и фурнитура</strong> — установка или перекраска (1-2 дня);</li>
        <li><strong>6. Сантехника и электрика</strong> — ремонт течи, новые розетки (1-2 дня);</li>
        <li><strong>7. Генеральная уборка</strong> — включая окна и подъезд (1 день).</li>
    </ul>
