<section>
    <h2>Ремонт под сдачу — это математика, а не творчество</h2>
    <p>Сдача квартиры — бизнес. Ремонт здесь — капитальные вложения (CapEx), которые должны вернуть себя за 18–24 месяца и генерировать кэшфлоу. В 2026 году спрос на качественный жилой фонд в Москве растёт: арендаторы платят за удобство, техническое состояние, эстетику «из коробки». Но есть тонкая грань: перебор с дизайном/материалами не окупается, экономия на инженерии — приводит к авариям и плохим отзывам. Формула рентового ремонта: бюджет 300–500 тыс. ₽, материалы класса «практичный премиум», сроки 3–4 недели.</p>
</section>

<section>
    <h2>Целевой портрет арендатора в Москве 2026</h2>
    <ul>
        <li><strong>Молодые специалисты (23–30 лет):</strong> ИТ, финансы, маркетинг. Бюджет 50–80 тыс. ₽/мес. Ценят: быстрый Wi-Fi, рабочее место, стирку, плиту, кондиционер, современный сантехник, парковку/метро шаговой доступностью.</li>
        <li><strong>Семьи с детьми (30–40 лет):</strong> Бюджет 80–120 тыс. ₽/мес. Ценят: 2+ санузла, лоджия, кухня-гостиная, безопасность (замки, домофон), детская площадка во дворе, школа/сад рядом.</li>
        <li><strong>Релокация / экспаты:</strong> Бюджет 100–200 тыс. ₽/мес. Краткосрочно (6–12 мес.). Ценят: полная меблировка, посуда, бельё, уборка раз в неделю, консьерж, безопасность.</li>
    </ul>
</section>

