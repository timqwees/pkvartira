<section>
    <h2>Ошибки новичка (как потерять деньги)</h2>
    <ul>
        <li><strong>Дизайнерский ремонт под сдачу</strong> — арендатор не платит за авторскую керамику и итальянский паркет. Переплаты не возвращаются.</li>
        <li><strong>Экономия на инженерии</strong> — дешёвые трубы/провода = протечка/короткое замыкание через год = ремонт за счёт аренды + споры с арендатором.</li>
        <li><strong>Мебель «на вырост»</strong> — огромный диван в 30-метровке съедает всю гостиную. Арендатору тесно.</li>
        <li><strong>Нет кондиционера / бризера</strong> — летом арендатор уезжает или требует скидку 30%.</li>
        <li><strong>Сдача «как есть» после косметического ремонта</strong> — фото в объявлении не соответствуют реальности = негативные отзывы, простои.</li>
        <li><strong>Игнорирование страховки</strong> — страховка ответственности перед соседями (3–5 тыс. ₽/год) спасает от миллионных претензий при протечке.</li>
    </ul>
</section>

<section>
    <h2>Юридическая безопасность</h2>
    <ul>
        <li>Договор найма на 11 месяцев (продление автоматически) — не требует нотариуса/Ростреестра.</li>
        <li>Залог = 1 месяц аренды (зафиксирован в договоре, возврат за 7 дней после выезда).</li>
        <li>Акт приёмки-передачи с фото каждого угла + показания счётчиков — подписывают обе стороны.</li>
        <li>Страховка титула / ответственности перед соседями — 3–8 тыс. ₽/год.</li>
        <li>Налог: самозанятость 4% от дохода (проще всего) или НДФЛ 13% (если не самозанятый).</li>
    </ul>
</section>