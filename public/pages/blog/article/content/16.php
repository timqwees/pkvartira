<section id="windows">
    <h2>Окна и входная дверь — 7 проверок</h2>
    <p>Самые дорогие косяки. Замена окна — от 25 000 ₽, двери — от 40 000 ₽.</p>
    <div data-type="box" data-color="gray">
        <h3>Чек-лист окон</h3>
        <p>1. Открывание/закрывание — створка не цепляет раму, ручка поворачивается без усилия<br>
        2. Прижим — лист А4 между рамой и створкой должен вытаскиваться с усилием при закрытом окне<br>
        3. Стеклопакет — без царапин, сколов, конденсата внутри<br>
        4. Монтажный шов — пена не торчит, заклеена пароизоляцией<br>
        5. Откосы и подоконник — без трещин, подоконник не прогибается<br>
        6. Продувание — свеча у стыка не колышется<br>
        7. Фурнитура — все ручки, заглушки на месте</p>
    </div>
    <div data-type="box" data-color="red">
        <h3>Дефект: продувание</h3>
        <p>Зимой 2025-26 в ЖК на Люберцах 40% квартир имели продувание из-за экономии на уплотнителе. Требуйте регулировку фурнитуры и замену уплотнителя — это гарантийный случай, не «особенность дома».</p>
    </div>
    <p><strong>Дверь:</strong> проверьте глазок, замки (2 оборота без заедания), уплотнитель по периметру, отсутствие вмятин. Дверь не должна самопроизвольно открываться/закрываться — проверьте уровнем.</p>
</section>

