<section id="stage1">
    <h2>Этап 1: Что взять на приемку: документы и инструменты</h2>
    <p>Без подготовки приемка превращается в 5-минутный обход «все ок, подписывайте». Берите:</p>
    <ul>
        <li><strong>Документы:</strong> паспорт, ДДУ, допсоглашения, план БТИ/ПИК;</li>
        <li><strong>Инструменты:</strong> рулетка 5м + лазерный дальномер, уровень 1м, фонарик, зажигалка/свеча (для вентиляции), индикаторная отвертка, мел/малярный скотч (отмечать дефекты), телефон с камерой;</li>
        <li><strong>Шаблон акта:</strong> скачайте бланк акта приемки заранее, чтобы не писать от руки на коленке.</li>
    </ul>
    <div data-type="box" data-color="yellow">
        <h3>Важно 2026</h3>
        <p>С 2024 года действует мораторий на неустойки, но <strong>дефекты застройщик обязан исправить по гарантии 3 года</strong>. Фиксируйте всё в акте — устные обещания не работают. Фото каждого дефекта + общий план с отметками.</p>
    </div>
</section>

<section id="stage2">
    <h2>Этап 2: Окна и входная дверь — 7 проверок</h2>
    <p>Самые дорогие косяки. Замена окна — от 25 000 ₽, двери — от 40 000 ₽.</p>
    <div data-type="box" data-color="gray">
        <h3>Чек-лист окон</h3>
        <p>1. Открывание/закрывание — створка не цепляет раму, ручка поворачивается без усилия;<br>
        2. Прижим — лист А4 между рамой и створкой должен вытаскиваться с усилием при закрытом окне;<br>
        3. Стеклопакет — без царапин, сколов, конденсата внутри;<br>
        4. Монтажный шов — пена не торчит, заклеена пароизоляцией;<br>
        5. Откосы и подоконник — без трещин, подоконник не прогибается;<br>
        6. Продувание — свеча у стыка не колышется;<br>
        7. Фурнитура — все ручки, заглушки на месте.</p>
    </div>
    <div data-type="box" data-color="red">
        <h3>Дефект: продувание</h3>
        <p>Зимой 2025-26 в ЖК на Люберцах 40% квартир имели продувание из-за экономии на уплотнителе. Требуйте регулировку фурнитуры и замену уплотнителя — это гарантийный случай, не «особенность дома».</p>
    </div>
    <p><strong>Дверь:</strong> проверьте глазок, замки (2 оборота без заедания), уплотнитель по периметру, отсутствие вмятин. Дверь не должна самопроизвольно открываться/закрываться — проверьте уровнем.</p>
</section>

<section id="stage3">
    <h2>Этап 3: Стены, пол, потолок — 8 проверок</h2>
    <div data-type="compare">
        <h3>Что считать дефектом, а что нормой</h3>
        <article data-variant="good">
            <h4>Норма</h4>
            <p>Отклонение стены от вертикали до 10 мм на 3 м. Трещины до 0,2 мм (усадочные). Стяжка с перепадом до 10 мм на 2 м.</p>
        </article>
        <article data-variant="bad">
            <h4>Дефект — в акт</h4>
            <p>Перепад 15+ мм, бухтящая штукатурка (стучите — глухой звук), трещины &gt;2 мм, пустоты под стяжкой, следы протечек.</p>
        </article>
    </div>
    <ul>
        <li><strong>Стены:</strong> правилом 2м + уровень — приложите к стене, просвет не должен быть &gt;5 мм. Простучите — бухтит = отслоение;</li>
        <li><strong>Пол:</strong> стяжка без трещин &gt;1 мм, не бухтит, перепад лазером — до 10 мм. Гидроизоляция в санузлах — порожек 15 мм;</li>
        <li><strong>Потолок:</strong> без перепадов, стыки плит без рустов &gt;10 мм;</li>
        <li><strong>Площадь:</strong> замерьте рулеткой и сравните с ДДУ — отклонение &gt;5% = перерасчет цены.</li>
    </ul>
</section>

<section id="stage4">
    <h2>Этап 4: Электрика и сантехника — 6 проверок</h2>
    <div data-type="box" data-color="green">
        <h3>Электрика</h3>
        <p>1. Щиток — автоматы подписаны, УЗО тестируется кнопкой «Т»;<br>
        2. Розетки — индикаторная отвертка + зарядка телефона в каждой;<br>
        3. Выключатели — свет включается без мерцания;<br>
        4. Слаботочка — интернет/ТВ розетки на месте.</p>
    </div>
    <div data-type="box" data-color="blue">
        <h3>Сантехника</h3>
        <p>1. Трубы — без подтеков, счетчики опломбированы;<br>
        2. Канализация — вылейте бутылку воды, уходит без бульканья;<br>
        3. Гидроизоляция — в санузле порожек и гидроизоляция есть.</p>
    </div>
    <p>Все проверки займут 15 минут, но сэкономят до 150 000 ₽ на переделке. Наши инженеры на замере проверяют это бесплатно.</p>
</section>

<section id="stage5">
    <h2>Этап 5: Вентиляция и отопление</h2>
    <ul>
        <li><strong>Вентиляция:</strong> лист А4 к решетке — должен прилипнуть. Свеча — пламя тянет в канал. Нет тяги — вентканал забит, требуйте прочистку;</li>
        <li><strong>Отопление:</strong> батареи без вмятин, крепления 3 точки, кран Маевского крутится. Пятна ржавчины — будущая течь;</li>
        <li><strong>Окна vs вентиляция:</strong> при закрытых окнах тяга слабее — это норма. Проверяйте с микропроветриванием.</li>
    </ul>
</section>

<section id="stage6">
    <h2>Этап 6: Как составить акт с дефектами: бланк и фразы</h2>
    <p>Не подписывайте акт приемки-передачи, пока не составите <strong>акт осмотра с замечаниями</strong>. Фразы:</p>
    <div data-type="box" data-color="dark">
        <h3>Шаблон записи</h3>
        <p>«Комната 2, стена северная, перепад 18 мм на 2м (фото №4). Требую выравнивание по СНиП 3.04.01-87».<br>
        «Окно спальня, продувание по нижнему шву (свеча, видео). Требую регулировку и замену уплотнителя».<br>
        «Санузел, отсутствие гидроизоляции порожка 15 мм — нарушение СП 29.13330».</p>
    </div>
    <p>Акт в 2 экземплярах, подпись представителя застройщика, дата, срок устранения — 45 дней по закону. Один экземпляр вам. Без акта — устное «исправим» забудется.</p>
    <div data-type="box" data-color="blue">
        <h3>Нужен бланк?</h3>
        <p>Скачайте образец акта приемки в нашем разделе документов или возьмите инженера Проект Квартира на приемку — составим акт за вас.</p>
    </div>
</section>

<section id="stage7">
    <h2>Этап 7: 5 ошибок, из-за которых теряют гарантию</h2>
    <ul>
        <li><strong>Подписали без замечаний</strong> — потом докажете, что трещина была. Всегда — акт с фото;</li>
        <li><strong>Не замерили площадь</strong> — переплата за 2 м² × 250 000 ₽/м² = 500 000 ₽;</li>
        <li><strong>Пришли без уровня/фонарика</strong> — глаз не видит перепад 12 мм;</li>
        <li><strong>Поверили «это усадка»</strong> — усадка — трещины до 0,2 мм, а не дыра в пене;</li>
        <li><strong>Не проверили зимой</strong> — летом продувание не заметите. Берите тепловизор (аренда 1500 ₽/день).</li>
    </ul>
</section>

<section id="stage8">
    <h2>Этап 8: Реновация — ремонт после сдачи дома</h2>
    <p>Реновация — комплексный ремонт жилого фонда, когда застройщик или город переделывает старый дом «под ключ». Если ваша квартира попадает под программу реновации, порядок приёма такой же, как у застройщика: проверяете геометрию, коммуникации, окна, двери — и фиксируете дефекты в акте. Разница: застройщик — это ДДУ, в реновации — договор с городом/фондом, но гарантия на скрытые работы тоже 3 года.</p>
    <div data-type="box" data-color="blue">
        <h3>Что проверять при реновации</h3>
        <ul>
            <li>Соответствие фактической площади проекту (допустимое отклонение — до 2% в меньшую сторону)</li>
            <li>Работа вентиляции — тяга в санузле и на кухне</li>
            <li>Электрика — автоматы, розетки, заземление</li>
            <li>Отопление — радиаторы греются равномерно, без воздуха в системе</li>
            <li>Гидроизоляция санузла — нет протечек к соседям снизу</li>
        </ul>
    </div>
</section>

<div data-type="box" data-color="gray">
    <h3>Что должен содержать акт приёмки</h3>
    <p>Акт без деталей — не защищает. Обязательные реквизиты:</p>
    <ul>
        <li><strong>Дата и место</strong> приёмки, номера ДДУ и объекта;</li>
        <li><strong>Стороны:</strong> застройщик (или фонд реновации) и собственник с паспортными данными;</li>
        <li><strong>Перечень проверенных узлов:</strong> окна, двери, стены, пол, потолок, электрика, сантехника, вентиляция, отопление;</li>
        <li><strong>Список дефектов с описанием и фото:</strong> «на стене кухни трещина длиной 15 см, фото прилагается» — не «всё неидеально»;</li>
        <li><strong>Сроки устранения:</strong> застройщик обязан указать дату исправления каждого дефекта;</li>
        <li><strong>Подписи обеих сторон</strong> — без подписи застройщика акт не имеет силы.</li>
    </ul>
    <p class="text-sm text-gray-500">Если застройщик отказывается подписывать акт с замечаниями — вызывайте представителя с полномочиями или фиксируйте отказ письмому (заказное письмо с уведомлением).</p>
