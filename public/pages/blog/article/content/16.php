<section id="vent">
    <h2>Вентиляция и отопление</h2>
    <ul>
        <li><strong>Вентиляция:</strong> лист А4 к решетке — должен прилипнуть. Свеча — пламя тянет в канал. Нет тяги — вентканал забит, требуйте прочистку.</li>
        <li><strong>Отопление:</strong> батареи без вмятин, крепления 3 точки, кран Маевского крутится. Пятна ржавчины — будущая течь.</li>
        <li><strong>Окна vs вентиляция:</strong> при закрытых окнах тяга слабее — это норма. Проверяйте с микропроветриванием.</li>
    </ul>
</section>

