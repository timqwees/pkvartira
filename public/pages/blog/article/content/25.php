    <h2>Как остановить рост: 4 правила договора</h2>
    <ol>
        <li><strong>Позиционная смета с количествами.</strong> Каждый вид работ — строкой с объёмом и ценой. Тогда любое изменение обсуждается по конкретной позиции, а не «в целом по квартире».</li>
        <li><strong>Фиксированная цена в договоре.</strong> Не «ориентировочно», не «от». Сумма, которая не меняется при выполнении согласованного объёма работ.</li>
        <li><strong>Порядок принятия скрытых работ.</strong> Прописано: подрядчик останавливается, показывает, предлагает варианты со стоимостью, и продолжает только после письменного согласования. Устных «давайте сделаем» не существует.</li>
        <li><strong>Отдельный счёт за инициативу заказчика.</strong> Работы, которых не было в смете, оформляются допсоглашением с ценой и сроком. Это снимает главный конфликт: «вы сами передумали, но платите вы — и переплачиваете вы». Нет — вы платите ровно оговорённую сумму, и она утверждена до начала работ.</li>
    </ol>
    <div data-type="box" data-color="dark">
