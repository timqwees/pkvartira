<section id="stage3">
    <h2>Этап 3: Этапы монтажа</h2>
    <p><strong>Электрический (маты под плитку):</strong> утеплитель → нагревательные маты → клей → плитка. Подключение через термостат к отдельной линии.</p>
    <p><strong>Водяной (в стяжке):</strong> утеплитель → фольгированный теплоотражатель → трубы в змейке → стяжка 50-70 мм → чистовый пол. Коллектор с термостатами в separate короб.</p>
    <div data-type="box" data-color="gray">
        <h3>Важно</h3>
        <p>Тёплый пол нельзя класть под холодильник, шкаф, стиральную машину — техника перегреется. Обогреваемая зона — не более 60% площади комнаты.</p>
    </div>
</section>

<section id="stage4">
    <h2>Этап 4: Чек-лист приёмки тёплого пола</h2>
    <ul>
        <li>☐ Система испытана под давлением (водяной) или проверена тестером (электрическая) до укладки стяжки/плитки;</li>
        <li>☐ Термостат установлен, показывает температуру, регулирует нагрев;</li>
        <li>☐ Датчик температуры в гофре, доступен для замены;</li>
        <li>№ Стяжка высохла 28 дней перед включением (водяной пол);</li>
        <li>☐ Первый запуск — поincrement 5 °C в день, не сразу на максимум;</li>
        <li>☐ Температура пола 24-27 °C, не выше (комфорт и безопасность).</li>
    </ul>
</section>

<section id="stage5">
    <h2>Этап 5: 5 ошибок, которые ведут к поломке</h2>
    <div data-type="compare">
        <h3>Ошибка vs Правильно</h3>
        <article data-variant="bad">
            <h4>Ошибка</h4>
            <p>1. Тёплый под шкафом и холодильником — перегрев техники;<br>
            2. Включение сразу на максимум после стяжки — трещины в стяжке;<br>
            3. Нет датчика в гофре — нельзя заменить без разбивки пола;<br>
            4. Электрический пол без отдельного УЗО — риск замыкания;<br>
            5. Водяной пол без согласования с УК — штраф и требование демонтировать.</p>
        </article>
        <article data-variant="good">
            <h4>Правильно</h4>
            <p>Только в зоне ходьбы, постепенный прогрев, датчик в гофре, отдельное УЗО, согласование водяного пола с УК.</p>
        </article>
    </div>
