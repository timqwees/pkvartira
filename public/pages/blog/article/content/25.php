    <h2>Этап 1: Электрический vs водяной тёплый пол — сравнение</h2>
    <div data-type="compare">
        <h3>Электрический vs Водяной</h3>
        <article data-variant="bad">
            <h4>Электрический тёплый пол</h4>
            <p>Кабель или маты под стяжку или плитку. Монтаж 1-2 дня, не нужно согласовывать с УК. Минус — высокие счета за электричество, не для всей квартиры.</p>
