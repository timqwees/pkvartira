<section id="faq">
    <h2>FAQ</h2>
    <div data-type="box" data-color="gray">
        <h3>Почему смета может вырасти на 10–20%?</h3>
        <p>Скрытый объём (штукатурка под обоями, старые коммуникации), уточнение по материалам после демонтажа и работы по инициативе заказчика. Нормальный рабочий диапазон — до 10%. Рост выше 20% без объяснений — повод остановиться и пересчитать смету.</p>
    </div>
    <div data-type="box" data-color="gray">
        <h3>Можно ли получить смету и не заплатить за неё?</h3>
        <p>Да. Замер и смета бесплатны, условие — заказ ремонта у нас. Смета сама по себе не обязывает вас что-то делать.</p>
    </div>
    <div data-type="box" data-color="gray">
        <h3>Сколько действует фиксированная цена?</h3>
        <p>Весь срок работ по договору. Цена не меняется из-за роста цен на материалы, сезона или того, что работы выполняются дольше, чем планировалось.</p>
    </div>
    <div data-type="box" data-color="gray">
        <h3>Что считается «скрытыми работами»?</h3>
        <p>Объём, который нельзя оценить без вскрытия: демонтаж отделки, старые штукатурка и стяжка, заложенные коммуникации, реальная геометрия стен, состояние перекрытий. Они обнаруживаются в процессе и оформляются допсоглашением до выполнения.</p>
    </div>
    <div data-type="box" data-color="gray">
        <h3>Почему смета в калькуляторе отличается от сметы после замера?</h3>
        <p>Калькулятор считает по типовым объёмам для площади. После замера инженер видит реальное состояние: сколько стояков, какая геометрия стен, что под обоями. Разница обычно 5–15% в сторону, которую покажет замер.</p>
