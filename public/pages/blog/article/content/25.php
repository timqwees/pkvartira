<section id="reasons">
    <h2>5 причин, почему смета растёт</h2>

    <article data-variant="bad">
        <h4>1. Объём посчитан по площади, а не по факту</h4>
        <p>Площадь квартиры не равна объёму работ. В санузле 4 м² и в коридоре 4 м² — разный объём: в санузле демонтаж плитки, гидроизоляция, штукатурка, стяжка, плитка, а в коридоре — шпаклёвка и обои. Смета «по метрам» не отражает реального объёма, и разница выходит на замере.</p>
        <p><strong>Что делать:</strong> считать смету по позициям работ, а не по площади. Позиционная смета — это перечень операций с объёмами; площадь в ней есть, но она не единственная цифра.</p>
    </article>

    <article data-variant="bad">
        <h4>2. Не разобран скрытый объём</h4>
        <p>Старая штукатурка с полостями, заложенные коммуникации, несущие стены с нестандартной геометрией, скрытые ниши, уклон старой стяжки. Пока стены не вскрыты — объём неизвестен. Особенно часто это бывает с домами 60–80-х, где стяжку клали «на глаз».</p>
        <p><strong>Что делать:</strong> закладывать в смету отдельную позицию «выявление скрытых работ» с фиксированной стоимостью и сроком, либо разделять договор на два этапа с пересмотром после вскрытия.</p>
    </article>

    <article data-variant="bad">
        <h4>3. Материалы в объёме не совпали с проектом</h4>
        <p>Классика: «посчитали 18 м² плитки, а нужно 24». Причины — раскрой, подрезка, брак, запас на подрезку в углах, разница в толщине клея и подложки. Реже — подрядчик закупил дешевле, чем предполагалось, и не хватило.</p>
        <p><strong>Что делать:</strong> считать материалы с запасом 10% на подрезку и брак, а в смете фиксировать конкретные позиции с количеством и ценой. Тогда вопрос «откуда взялось 6 м² плитки» снимается списком закупки.</p>
    </article>

    <article data-variant="bad">
        <h4>4. Работы, которые менялись по ходу</h4>
        <p>Сантехник не нашёл вывод канализации в стене — перенос санузла на 2 метра. Заказчик решил «раз уж копаем, поменяем и окна». Каждое такое решение — дополнительные работы, и они не входят в первоначальную смету.</p>
        <p><strong>Что делать:</strong> разделять смету на твёрдую часть и «работы по инициативе заказчика». Второе — отдельным дополнительным соглашением, с ценой и сроком, согласованными до начала работ.</p>
    </article>

    <article data-variant="bad">
        <h4>5. Сезон и логистика</h4>
        <p>Зимой дороже доставка и обогрев площадки, в праздники — простои бригад. Загрузка рынка в сезон поднимает цены на 10–20%. Это не рост сметы по существу, но в итоговой сумме видно его.</p>
        <p><strong>Что делать:</strong> фиксировать цену в договоре на момент подписания — тогда сезонный фактор уже учтён и не влияет на итог.</p>
    </article>
