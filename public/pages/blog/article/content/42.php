<section id="stage1">
    <h2>Этап 1: Почему смета растёт — 7 основных причин</h2>
    <ul>
        <li><strong>1. Нет фиксированной сметы:</strong> цена «от» или ориентировочная — открывает дверь к росту;</li>
        <li><strong>2. Допсоглашения в процессе:</strong> заказчик просит добавить работы, которых не было в изначальном плане;</li>
        <li><strong>3. Скрытые дефекты:</strong> после демонтажа находятся гниль, трещины, старые коммуникации;</li>
        <li><strong>4. Замена материалов:</strong> выбранный материал закончился, заменяют на более дорогой;</li>
        <li><strong>5. Изменение проекта:</strong> перепланировка, перенос стен, новая расстановка мебели;</li>
        <li><strong>6. Инфляция материалов:</strong> рост цен на стройматериалы между сметой и закупкой;</li>
        <li><strong>7. Простой бригады:</strong> задержка поставки материалов или доступ к объекту.</li>
    </ul>
    <div data-type="box" data-color="red">
        <h3>Статистика</td>
        <p>У 68% заказчиков без фиксированной сметы цена растёт в среднем на 15-30%. С фиксированной сметои — рост менее 2%.</p>
    </div>
</section>

<section id="stage2">
    <h2>Этап 2: Как зафиксировать цену в договоре</h2>
    <ul>
        <li>Требуйте детальную смету с разбивкой по работам и материалам;</li>
        <li>Обеспечьте фиксацию цены в договоре — без фразы «ориентировочно»;</li>
        <li>Пропишите порядок внесения изменений — только подписанное допсоглашение;</li>
        <li>Требуйте гарантию на работы и материалы не менее 3 лет;</li>
        <li>Укажите сроки начала и окончания работ с штрафами за задержку.</li>
    </ul>
</section>

<section id="stage3">
    <h2>Этап 3: Чек-лист защиты от роста сметы</h2>
    <ul>
        <li>☐ Смета детализирована по работам и материалам с брендами;</li>
        <li>☐ Цена в договоре фиксирована, нет слова «ориентировочно»;</li>
        <li>☐ Есть чёткий порядок внесения изменений (только допсоглашение);</li>
        <li>☐ Материалы закреплены брендом и артикулом;</li>
        <li>☐ Есть гарантия на работы и материалы;</li>
        <li>☐ Есть график платежей по этапам, а не аванс 100%.</li>
    </ul>
</section>

<section id="stage4">
    <h2>Этап 4: Что делать, если смета уже растёт</h2>
    <ol>
        <li>Требуйте обоснования каждой новой строки в смете;</li>
        <li>Проверяйте, относится ли это к скрытым дефектам или к изменению плана;</li>
        <li>Заключайте допсоглашение только после согласования объёма и цены;</li>
        <li>Отказывайтесь от работ, которые не критичны для завершения;</li>
        <li>Привлекайте независимого эксперта для оценки обоснованности роста.</li>
    </ol>
</section>

