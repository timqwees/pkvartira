<section id="stage1">
    <h2>Этап 1: Утепление стен, пола, потолка</h2>
    <p>До 40% тепла уходит через стены и пол. Первым делом — инспекция теплопотерь тепловизором:</p>
    <ul>
        <li><strong>Стены:</strong> минеральная вата или пенополистирол. Оптимальная толщина для Подмосковья — 100–150 мм;</li>
        <li><strong>Пол:</strong> утепление стяжки пенополистиролом экструдированным (XPS), толщина 30–50 мм;</li>
        <li><strong>Потолок:</strong> если сверху холодный чердак — утепление обязательно. В многоквартирном доме менее критично.</li>
    </ul>
    <div data-type="box" data-color="gray">
        <h3>Экономия</h3>
        <p>Комплексное утепление квартиры снижает теплопотери на 40–60%. Срок окупаемости — 2–3 отопительных сезона.</p>
    </div>
</section>

<section id="stage2">
    <h2>Этап 2: Окна и двери — как не терять тепло</h2>
    <p>Через старые окна улетучивается до 30% тепла. Решение:</p>
    <ul>
        <li>Двухкамерные стеклопакеты с i-стеклом и аргоновым заполнением;</li>
        <li>Регулировка фурнитуры раз в год — щели пропускают холод;</li>
        <li>Утепление входной двери — контур уплотнителя по периметру.</li>
    </ul>
    <div data-type="compare">
        <h3>Традиционные окна vs Энергоэффективные</h3>
        <article data-variant="good">
            <h4>Энергоэффективные</h4>
            <p>i-стекло + аргон. Двухкамерные. Профиль с терморазрывом. Коэффициент теплопередачи ≤ 0,7 Вт/м²K.</p>
        </article>
        <article data-variant="bad">
            <h4>Обычные окна</h4>
            <p>Старые советские рамы или дешёвые однокамерные стеклопакеты. Коэффициент ≥ 1,0 — двойные теплопотери.</p>
        </article>
    </div>
</section>

<section id="stage3">
    <h2>Этап 3: Умное отопление и рекуперация</h2>
    <p>Самые эффективные инвестиции в энергосбережение:</p>
    <ul>
        <li><strong>Термостаты с погодным регулированием</strong> — автоматически снижают температуру, когда вас нет дома. Экономия до 30%;</li>
        <li><strong>Рекуператор воздуха</strong> — подогревает приточный воздух за счёт вытяжного. Экономия на отоплении до 40%;</li>
        <li><strong>Тёплый пол с программированием</strong> — работает только в часы присутствия.</li>
    </ul>
    <div data-type="box" data-color="dark">
        <h3>Важно</h3>
        <p>Рекуператор имеет смысл ставить только в герметичных квартирах с хорошими окнами. Иначе эффект нулевой.</p>
    </div>
</section>

<section id="stage4">
    <h2>Этап 4: Энергосберегающее освещение</h2>
    <p>LED-технологии шагнули далеко вперёд. В 2026 году:</p>
    <ul>
        <li>Светодиодные лампы класса A+ потребляют в 10 раз меньше ламп накаливания;</li>
        <li>Умные выключатели с датчиками движения отключают свет в пустых комнатах;</li>
        <li>Диммирование (регулировка яркости) дополнительно экономит энергию.</li>
    </ul>
</section>

