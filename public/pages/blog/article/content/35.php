<section>
    <h2>Еженедельный цикл управления (каждый понедельник — 30 мин)</h2>
    <ol>
        <li><strong>Отчёт прораба (в чате/таблице):</strong>
            <ul>
                <li>Что сделано на прошлой неделе (% по этапам, фото 10–15 шт.)</li>
                <li>Что планируется на этой неделе (конкретные позиции сметы)</li>
                <li>Проблемы/риски (нет материала, брак, просрочка поставки, болезнь мастера)</li>
                <li>Потребность в решениях (выбор цвета, закупка, доп. соглашение)</li>
            </ul>
        </li>
        <li><strong>Приёмка этапов (по чек-листам):</strong> Выезжаете на объект 1 раз в неделю (или прораб присылает видео-тур 15 мин). Подписываете акт скрытых работ (инженерия), акт приёмки этапа (стяжка/штукатурка/чистовик).</li>
        <li><strong>Журнал допсоглашений:</strong> Каждое изменение = доп. соглашение: позиция, причина, сумма, подписи сторон. Никаких устных договорённостей.</li>
        <li><strong>Финансовый контроль:</strong> Платёж по этапам (аванс 10–30% → после демонтажа/инженерии 30% → после черновика 30% → после чистовика 10% → после приёмки 10%). Чеки на материалы — обязательно в облако.</li>
    </ol>
</section>

