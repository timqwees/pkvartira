    <h2>Этап 5: 5 ошибок при ремонте хрущевки</h2>
    <div data-type="compare">
        <h3>Ошибка vs Правильно</h3>
        <article data-variant="bad">
            <h4>Ошибка</h4>
            <p>1. Натяжной потолок — теряем 5 см из 2,5 м;<br>
            2. Снос несущей стены без проекта — штраф и восстановление;<br>
            3. Экономия на электрике — старая алюминиевая проводка сгорает;<br>
            4. Обычная ванна 1,7 м в санузле 3 м² — не встаёт, ставим душ;<br>
            5. Тяжёлая мебель на деревянные перекрытия — прогиб и скрип.</p>
        </article>
        <article data-variant="good">
            <h4>Правильно</h4>
            <p>Штукатурка потолка, техзаключение перед сносом, медная проводка, компактная сантехника, лёгкая мебель.</p>
