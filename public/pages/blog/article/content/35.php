<section id="stage1">
    <h2>Этап 1: Особенности хрущевки — что учитывать</h2>
    <ul>
        <li><strong>Потолки 2,5 м</strong> — не теряйте высоту натяжными потолками, лучше штукатурка;</li>
        <li><strong>Несущие стены</strong> — около 80% перегородок несущие, снос без проекта запрещён;</li>
        <li><strong>Деревянные перекрытия</strong> — пожароопасны, нужна защита и замена при износе;</li>
        <li><strong>Узкая кухня 5-6 м²</strong> — компактная мебель, угловая мойка;</li>
        <li><strong>Совмещённый санузел 3-4 м²</strong> — компактная сантехника, угловая ванна или душ;</li>
        <li><strong>Окна с одинарным стеклом</strong> — заменять на энергосберегающие.</li>
    </ul>
</section>

