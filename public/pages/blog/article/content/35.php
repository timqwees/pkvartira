<section>
    <h2>Работа с допсоглашениями (как не потерять контроль)</h2>
    <ol>
        <li>Любое изменение = доп. соглашение (даже «добавим розетку здесь»).</li>
        <li>Форма: позиция, описание, причина, кол-во, цена за ед., сумма, сроки, подписи Заказчика и Прораба.</li>
        <li>Лимит допсоглашений без вашего подписания — 0. Прораб не имеет права подписывать за вас.</li>
        <li>Сумма всех допсоглашений >10% от договора — повод для аудита сметы.</li>
        <li>Типичные причины: «не уложились в смету» (плохой замер), «заказчик просил» (нет письма), «обнаружили» (плохой осмотр).</li>
    </ol>
</section>

<section>
    <h2>Что делать при срыве сроков</h2>
    <ol>
        <li>Фиксируете факт: дата плана vs факт, причина (материалы, брак, болезнь, погода).</li>
        <li>Письменное уведомление подрядчику: «Срок сдвинут на Х дней, причина Y, требуем план восстановления графика».</li>
        <li>Штрафы за просрочку (0.1–1% от стоимости этапа/дня) — списываете из следующего платежа.</li>
        <li>Если срыв >2 недель и вина подрядчика — претензия, расторжение договора (по п. договора), поиск нового подрядчика на оставшиеся работы.</li>
        <li>План восстановления: доп. бригада / ускоренная технология / работа в 2 смены / перенос некритичных работ на потом.</li>
    </ol>
</section>

