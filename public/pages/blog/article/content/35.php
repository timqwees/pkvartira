<section>
    <h2>Ремонт — проект с бюджетом 1–5 млн ₽, сроком 2–6 месяцев, 10+ подрядчиков</h2>
    <p>Без управления — гарантированные переплаты 20–30% и задержки в 2 раза. В 2026 году доступны простые инструменты: календарный план в Excel/Notion, еженедельные отчёты прораба, приёмка этапов по чек-листам, журнал допсоглашений. Разбираем пошагово: как составить план, на каких этапах быть лично, как читать отчёты, что делать при срыве сроков.</p>
</section>

<section>
    <h2>Этап 0: Подготовка (до подписания договора)</h2>
    <ol>
        <li><strong>Техническое задание (ТЗ):</strong> Список комнат, площадь, тип ремонта (косметический/капитальный/дизайнерский), желаемые материалы, бюджет-вилка, сроки.</li>
        <li><strong>Замеры и сметный расчёт:</strong> Инженер замеряет, считает объёмы работ, материалы, готовит позиционную смету (Excel: позиция, единица, кол-во, цена, сумма).</li>
        <li><strong>Календарный план (Гантт):</strong> Этапы с зависимостями: Демонтаж → Инженерия (электрика/сантехника/вентиляция) → Черновик (стяжка/штукатурка/шпаклёвка) → Чистовик (полы/стены/потолки/двери/сантехника) → Уборка/приёмка. Каждый этап: длительность, начало/конец, ответственный, контрольная точка.</li>
        <li><strong>Договор подряда:</strong> Приложение 1 — Смета (позиционная), Приложение 2 — Календарный план, Приложение 3 — Чек-листы приёмки этапов, Приложение 4 — Порядок изменений (доп. соглашения).</li>
        <li><strong>Выбор подрядчика:</strong> 3–5 собеседований, проверка портфолио (поездка на 2 объекта), отзывы, договор с штрафами за просрочку (0.1–1% в день).</li>
    </ol>
</section>

