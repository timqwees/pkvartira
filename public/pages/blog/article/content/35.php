<section id="stage3">
    <h2>Этап 3: Что можно, а что запрещено перепланировать</h2>
    <div data-type="compare">
        <h3>Можно vs Запрещено</h3>
        <article data-variant="good">
            <h4>Можно</h4>
            <p>Косметический ремонт, замена окон, дверей, сантехники, электрики, утепление стен изнутри, замена перекрытия.</p>
        </article>
        <article data-variant="bad">
            <h4>Запрещено без проекта</h4>
            <p>Снос несущих стен, объединение кухни с газом, перенос мокрых зон, снос перегородок более 10 см толщиной.</p>
        </article>
    </div>
    <div data-type="box" data-color="red">
        <h3>Важно</h3>
        <p>В хрущевках многие «перегородки» — несущие. Снос без техзаключения — штраф и обязательство восстановить за свой счет.</p>
    </div>
</section>

<section id="stage4">
    <h2>Этап 4: Этапы ремонта хрущевки под ключ</h2>
    <ul>
        <li><strong>1. Замер и проект</strong> — учёт несущих стен, ниш, низов потолков (2-3 дня);</li>
        <li><strong>2. Демонтаж</strong> — старые обои, пол, плинтусы, сантехника (1-2 дня);</li>
        <li><strong>3. Электрика</strong> — замена алюминиевой проводки на медную (3-5 дней);</li>
        <li><strong>4. Стены и потолки</strong> — штукатурка, шпаклёвка, покраска (5-7 дней);</li>
        <li><strong>5. Пол</strong> — ламинат или линолеум, плинтусы (2-3 дня);</li>
        <li><strong>6. Сантехника</strong> — замена труб, унитаза, раковины (2-3 дня);</li>
        <li><strong>7. Окна и двери</strong> — установка новых (1-2 дня);</li>
        <li><strong>8. Финальная уборка</strong> (1 день).</li>
    </ul>
    <p>Общий срок: 3-6 недель.</p>
</section>

