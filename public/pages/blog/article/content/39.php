<section id="stage3">
    <h2>Этап 3: Этапы ремонта в новостройке с нуля</h2>
    <ul>
        <li><strong>1. Приёмка у застройщика</strong> — акт дефектов,_photoфиксация (1 день);</li>
        <li><strong>2. Проект и сметы</strong> — планировка, электрика, сантехника (3-7 дней);</li>
        <li><strong>3. Черновые</strong> — стяжка, штукатурка, электрика, сантехника (2-4 недели);</li>
        <li><strong>4. Чистовые</strong> — пол, стены, потолок, двери (2-4 недели);</li>
        <li><strong>5. Финал</strong> — уборка, подключение техники, приёмка (3-5 дней).</li>
    </ul>
    <div data-type="box" data-color="blue">
        <h3>Срок сдачи дома влияет на ремонт</h3>
        <p>Если дом сдан менее года назад, стены могут «вести» — требуется дополнительное время на просушку перед финишной отделкой.</p>
    </div>
