<section id="stage4">
    <h2>Этап 4: Чек-лист приёмки квартиры у застройщика</h2>
    <ul>
        <li>☐ Окна — нет дутья, фурнитура работает, подоконник цел;</li>
        <li>☐ Входная дверь — замок, глазок, уплотнитель;</li>
        <li>☐ Электрика — автоматы в щите, розетки под напряжением;</li>
        <li>☐ Стены и пол — перепад не более 2 мм на метр;</li>
        <li>☐ Санузел — нет течи, унитаз и раковина крепятся прочно;</li>
        <li>☐ Вентиляция — тяга есть, решётка не закрыта;</li>
        <li>☐ Балкон/лоджия — нет трещин в плите, отлив цел.</li>
    </ul>
    <div data-type="box" data-color="red">
        <h3>Красный флаг</h3>
        <p>Влажность стен выше нормы — сушите 2-4 недели перед стяжкой, иначе плитка пойдёт трещинами.</p>
    </div>
</section>

