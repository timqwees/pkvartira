<section id="cosmetic">
    <h2>Косметический ремонт: сроки по этапам</h2>
    <p>Косметический ремонт — самый предсказуемый по срокам: стены и пол уже ровные, работы идут поверх готовых оснований. Возьмём комнату 15 м² с ровными стенами и паркетом, который нужно освежить:</p>

    <div data-type="box" data-color="gray">
        <h3>Этапы косметического ремонта комнаты 15 м²</h3>
        <p><strong>День 1–2:</strong> вынос мебели, защита пола, демонтаж старого покрытия стен (обои, краска), шпаклёвка дефектов.<br>
        <strong>День 2–3:</strong> грунтовка, шпаклёвка под покраску или подготовка стен под обои.<br>
        <strong>День 4:</strong> покраска стен в 2 слоя или оклейка обоями. Одновременно — циклёвка и лакировка пола.<br>
        <strong>День 5:</strong> плинтусы, подрозетники, наличники, выключатели, финальная уборка.</p>
    </div>

    <p>Итого — <strong>5–7 рабочих дней</strong>. Если добавить замену светильников и межкомнатной двери — ещё 2–3 дня. Косметический ремонт можно делать и поэтапно, комнатами, не выезжая из квартиры: одна комната — одна неделя.</p>
</section>

