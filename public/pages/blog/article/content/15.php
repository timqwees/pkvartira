<section id="faq">
    <h2>FAQ</h2>
    <p><strong>Сколько длится косметический ремонт комнаты?</strong> 5–10 дней для комнаты 15–20 м² при готовых стенах и полу. Если нужно выровнять стены и пол — это уже капитальный ремонт.</p>
    <p><strong>Сколько занимает капитальный ремонт комнаты?</strong> 21–35 рабочих дней плюс технологические паузы на просушку. Полный цикл со стяжкой и штукатуркой — 5–7 недель от демонтажа до уборки.</p>
    <p><strong>Можно ли жить в квартире во время ремонта одной комнаты?</strong> Да, если комната не единственная и пыль не критична. Косметический ремонт с защитой мебели и пола — комфортно, капитальный — с пылью, но тоже реально.</p>
    <p><strong>Почему стяжка сохнет 28 дней?</strong> Цементная стяжка набирает прочность постепенно — это свойство цемента. Ускорить можно только быстросохнущими смесями, но класть финишное покрытие раньше срока нельзя.</p>
    <p><strong>Что делать, если бригада срывает сроки?</strong> Сроки должны быть в договоре с фиксацией по этапам. При срыве — акт о задержке, пересчёт и неустойка по договору. Без договора вы не защищены.</p>

