<section id="capital">
    <h2>Капитальный ремонт: сроки по этапам</h2>
    <p>Капитальный ремонт комнаты — это работа с основаниями: новая электрика, ровные стены и пол. Сроки по этапам для комнаты 15 м²:</p>

    <div data-type="box" data-color="dark">
        <h3>Этапы капитального ремонта комнаты 15 м²</h3>
        <p><strong>День 1–2:</strong> демонтаж — старые обои, плинтусы, напольное покрытие, вывоз мусора.<br>
        <strong>День 2–4:</strong> электрика — штробление, проводка, подрозетники, разводка по новой схеме.<br>
        <strong>День 4–6:</strong> штукатурка стен по маякам (2–3 см перепады) — работа + 7–14 дней просушки.<br>
        <strong>День 5–7:</strong> стяжка пола — работа + 28 дней набора прочности.<br>
        <strong>День 14–20:</strong> шпаклёвка стен и потолка (2–3 слоя), грунтовка.<br>
        <strong>День 21–24:</strong> покраска или обои, укладка ламината или паркетной доски.<br>
        <strong>День 25–28:</strong> плинтусы, двери, розетки, выключатели, финальная уборка.</p>
    </div>

    <p>Суммарное рабочее время бригады — <strong>3–4 недели</strong>, но между этапами есть технологические паузы на просушку штукатурки и стяжки. Поэтому общий срок с учётом ожидания — <strong>5–7 недель</strong>.</p>

    <div data-type="box" data-color="yellow">
        <h3>Важно</h3>
        <p>Не наступайте на свежую стяжку, не заколачивайте гвозди в свежую штукатурку и не включайте тёплый пол раньше, чем стяжка набрала прочность. Нарушение сроков просушки — гарантированные трещины и переделка за ваш счёт.</p>
    </div>
</section>

<!-- Секция: Что тормозит -->
<section id="slow">
    <h2>Что тормозит ремонт: типичные задержки</h2>
    <p>90% сорванных сроков — не вина бригады, а организационные ошибки. Вот что чаще всего задерживает сдачу:</p>

    <ul>
        <li><strong>Недокупка материалов.</strong> Середина процесса — и закончился гипс, шпаклёвка или грунт. Пока едет доставка — день простоя.</li>
        <li><strong>Долгая доставка заказных позиций.</strong> Межкомнатные двери, радиаторы и светильники из каталога везут 2–6 недель. Заказывайте их в первый день ремонта, а не в последний.</li>
        <li><strong>Несогласованные изменения.</strong> «А давайте ещё вот тут розетку» — каждая новая точка в процессе — это штроба, проводка и перешпаклёвка уже готовой стены.</li>
        <li><strong>Сезон.</strong> С октября по май штукатурка и шпаклёвка сохнут дольше, чем летом — разница до 30% по времени просушки.</li>
        <li><strong>Бригада, которая ведёт 3 объекта сразу.</strong> Мастер приходит «на пару часов» — и сроки расползаются на месяцы. Проверяйте занятость до подписания договора.</li>
    </ul>

    <div data-type="box" data-color="red">
        <h3>Красный флаг</h3>
        <p>Подрядчик обещает капитальный ремонт комнаты «за 10 дней»? Это либо косметика под видом капитального, либо нарушение технологии просушки. Настоящий капитальный ремонт с сушкой стяжки физически не может уложиться в 2 недели.</p>
    </div>
</section>

