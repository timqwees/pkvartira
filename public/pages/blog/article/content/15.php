<section id="stage1">
    <h2>Этап 1: От чего зависит срок ремонта комнаты</h2>
    <p>Одну и ту же комнату 15 м² одна бригада сдаёт за 10 дней, другая — за 2 месяца. Разница — не в скорости рук, а в объёме работ и организации процесса. Главные факторы:</p>
    <ul>
        <li><strong>Вид ремонта.</strong> Косметический — покраска и обои поверх готовых стен. Капитальный — демонтаж, новая проводка, штукатурка, стяжка, финишная отделка. Разница в сроках — в 3–4 раза;</li>
        <li><strong>Исходное состояние.</strong> Кривые стены с перепадами 3–5 см, старая проводка и трубы, плесень под обоями — всё это добавляет дни и недели;</li>
        <li><strong>Технологические паузы.</strong> Стяжка сохнет 28 дней, штукатурка — 7–14 дней, шпаклёвка — сутки на слой. Их нельзя «ускорить» без риска трещин и плесени;</li>
        <li><strong>Готовность материалов.</strong> Обои закончились, плитки не хватило, межкомнатная дверь едет 3 недели — бригада простаивает, сроки ползут;</li>
        <li><strong>Согласованность этапов.</strong> Электрик должен сделать штробы до штукатурки, а сантехник — до плитки. Один перепутанный порядок — и переделки на неделю.</li>
    </ul>
    <div data-type="box" data-color="gray">
        <h3>Средние ориентиры</h3>
        <p><strong>Косметический ремонт комнаты:</strong> 5–10 дней.<br>
        <strong>Капитальный ремонт комнаты:</strong> 21–35 дней, при полной замене стяжки — до 6–7 недель.<br>
        <strong>Дизайнерский ремонт со сложными решениями:</strong> 6–8 недель.</p>
    </div>
</section>

<section id="stage2">
    <h2>Этап 2: Косметический ремонт — сроки по этапам</h2>
    <p>Косметический ремонт — самый предсказуемый по срокам: стены и пол уже ровные, работы идут поверх готовых оснований. Возьмём комнату 15 м² с ровными стенами и паркетом, который нужно освежить:</p>
    <div data-type="box" data-color="gray">
        <h3>Этапы косметического ремонта комнаты 15 м²</h3>
        <p><strong>День 1–2:</strong> вынос мебели, защита пола, демонтаж старого покрытия стен (обои, краска), шпаклёвка дефектов.<br>
        <strong>День 2–3:</strong> грунтовка, шпаклёвка под покраску или подготовка стен под обои.<br>
        <strong>День 4:</strong> покраска стен в 2 слоя или оклейка обоями. Одновременно — циклёвка и лакировка пола.<br>
        <strong>День 5:</strong> плинтусы, подрозетники, наличники, выключатели, финальная уборка.</p>
    </div>
    <p>Итого — <strong>5–7 рабочих дней</strong>. Если добавить замену светильников и межкомнатной двери — ещё 2–3 дня. Косметический ремонт можно делать и поэтапно, комнатами, не выезжая из квартиры: одна комната — одна неделя.</p>
</section>

<section id="stage3">
    <h2>Этап 3: Капитальный ремонт — сроки по этапам</h2>
    <p>Капитальный ремонт комнаты — это работа с основаниями: новая электрика, ровные стены и пол. Сроки по этапам для комнаты 15 м²:</p>
    <div data-type="box" data-color="dark">
        <h3>Этапы капитального ремонта комнаты 15 м²</h3>
        <p><strong>День 1–2:</strong> демонтаж — старые обои, плинтусы, напольное покрытие, вывоз мусора.<br>
        <strong>День 2–4:</strong> электрика — штробление, проводка, подрозетники, разводка по новой схеме.<br>
        <strong>День 4–6:</strong> штукатурка стен по маякам (2–3 см перепады) — работа + 7–14 дней просушки.<br>
        <strong>День 5–7:</strong> стяжка пола — работа + 28 дней набора прочности.<br>
        <strong>День 14–20:</strong> шпаклёвка стен и потолка (2–3 слоя), грунтовка.<br>
        <strong>День 21–24:</strong> покраска или обои, укладка ламината или паркетной доски.<br>
        <strong>День 25–28:</strong> плинтусы, двери, розетки, выключатели, финальная уборка.</p>
    </div>
    <p>Суммарное рабочее время бригады — <strong>3–4 недели</strong>, но между этапами есть технологические паузы на просушку штукатурки и стяжки. Поэтому общий срок с учётом ожидания — <strong>5–7 недель</strong>.</p>
    <div data-type="box" data-color="yellow">
        <h3>Важно</h3>
        <p>Не наступайте на свежую стяжку, не заколачивайте гвозди в свежую штукатурку и не включайте тёплый пол раньше, чем стяжка набрала прочность. Нарушение сроков просушки — гарантированные трещины и переделка за ваш счёт.</p>
    </div>
</section>

<section id="stage4">
    <h2>Этап 4: Что тормозит ремонт: типичные задержки</h2>
    <p>90% сорванных сроков — не вина бригады, а организационные ошибки. Вот что чаще всего задерживает сдачу:</p>
    <ul>
        <li><strong>Недокупка материалов.</strong> Середина процесса — и закончился гипс, шпаклёвка или грунт. Пока едет доставка — день простоя;</li>
        <li><strong>Долгая доставка заказных позиций.</strong> Межкомнатные двери, радиаторы и светильники из каталога везут 2–6 недель. Заказывайте их в первый день ремонта, а не в последний;</li>
        <li><strong>Несогласованные изменения.</strong> «А давайте ещё вот тут розетку» — каждая новая точка в процессе — это штроба, проводка и перешпаклёвка уже готовой стены;</li>
        <li><strong>Сезон.</strong> С октября по май штукатурка и шпаклёвка сохнут дольше, чем летом — разница до 30% по времени просушки;</li>
        <li><strong>Бригада, которая ведёт 3 объекта сразу.</strong> Мастер приходит «на пару часов» — и сроки расползаются на месяцы. Проверяйте занятость до подписания договора.</li>
    </ul>
    <div data-type="box" data-color="red">
        <h3>Красный флаг</h3>
        <p>Подрядчик обещает капитальный ремонт комнаты «за 10 дней»? Это либо косметика под видом капитального, либо нарушение технологии просушки. Настоящий капитальный ремонт с сушкой стяжки физически не может уложиться в 2 недели.</p>
    </div>
</section>

<section id="stage5">
    <h2>Этап 5: Как ускорить ремонт без потери качества</h2>
    <p>Сократить сроки можно не за счёт технологии, а за счёт организации. Работает это так:</p>
    <ul>
        <li><strong>Закупите всё заранее.</strong> Полный комплект материалов — клей, смеси, плитка, обои, ламинат — до начала работ. Доставка и возврат излишков — после;</li>
        <li><strong>Закажите двери, окна и радиаторы на первом этапе</strong>, пока идёт черновая отделка. К финишу они уже будут на складе;</li>
        <li><strong>Используйте быстросохнущие смеси.</strong> Стяжка «быстрый старт» набирает ходовую прочность за 3–7 дней вместо 28. Дороже, но экономит 3 недели;</li>
        <li><strong>Параллельные работы.</strong> Пока сохнет штукатурка в комнате, бригада делает электрику и черновую отделку в коридоре и на кухне. Это и есть график под ключ;</li>
        <li><strong>Не меняйте решения в процессе.</strong> Каждое «давайте иначе» в середине этапа — это переделка готового и потерянные дни.</li>
    </ul>
</section>

