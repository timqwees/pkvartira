<section id="factors">
    <h2>От чего зависит срок ремонта комнаты</h2>
    <p>Одну и ту же комнату 15 м² одна бригада сдаёт за 10 дней, другая — за 2 месяца. Разница — не в скорости рук, а в объёме работ и организации процесса. Главные факторы:</p>

    <ul>
        <li><strong>Вид ремонта.</strong> Косметический — покраска и обои поверх готовых стен. Капитальный — демонтаж, новая проводка, штукатурка, стяжка, финишная отделка. Разница в сроках — в 3–4 раза.</li>
        <li><strong>Исходное состояние.</strong> Кривые стены с перепадами 3–5 см, старая проводка и трубы, плесень под обоями — всё это добавляет дни и недели.</li>
        <li><strong>Технологические паузы.</strong> Стяжка сохнет 28 дней, штукатурка — 7–14 дней, шпаклёвка — сутки на слой. Их нельзя «ускорить» без риска трещин и плесени.</li>
        <li><strong>Готовность материалов.</strong> Обои закончились, плитки не хватило, межкомнатная дверь едет 3 недели — бригада простаивает, сроки ползут.</li>
        <li><strong>Согласованность этапов.</strong> Электрик должен сделать штробы до штукатурки, а сантехник — до плитки. Один перепутанный порядок — и переделки на неделю.</li>
    </ul>

    <div data-type="box" data-color="gray">
        <h3>Средние ориентиры</h3>
        <p><strong>Косметический ремонт комнаты:</strong> 5–10 дней.<br>
        <strong>Капитальный ремонт комнаты:</strong> 21–35 дней, при полной замене стяжки — до 6–7 недель.<br>
        <strong>Дизайнерский ремонт со сложными решениями:</strong> 6–8 недель.</p>
    </div>
</section>

