<section id="faq">
    <h2>FAQ</h2>

    <p><strong>Как посчитать квадратные метры комнаты формула?</strong> Для прямоугольника: площадь = длина × ширина. Например: 4 м × 3 м = 12 м². Для Г-образной — разбейте на два прямоугольника и сложите площади.</p>

    <p><strong>Как посчитать площадь комнаты с нишей?</strong> Замерьте основную часть как прямоугольник. Замерьте нишу отдельно (если глубина до 1,2 м — прибавьте к общей площади; если более 1,2 м — считайте как отдельное помещение).</p>

    <p><strong>Как посчитать площадь стен?</strong> Периметр комнаты × высота потолка. Периметр = (длина + ширина) × 2. Вычтите площадь дверных и оконных проёмов. Пример: комната 4×3 м, потолок 2,7 м — стены = (4+3)×2×2,7 = 37,8 м².</p>

    <p><strong>Как посчитать площадь пола под ламинат?</strong> Площадь комнаты + запас 5–10% на обрезку. Для Г-образных комнат запас — до 15%. Покупайте с запасом: докупить тот же цвет будет сложно.</p>

    <p><strong>Какая площадь указана в документах БТИ?</strong> БТИ считает общую площадь по наружным стенам. Полезная площадь — внутренняя. Разница — 1–3 м². Для ремонта считайте по внутренним стенам.</p>

