<section id="lshape">
    <h2>Г-образная комната — как разбить на прямоугольники</h2>
    <p>Г-образные комнаты встречаются в сталинках, хрущёвках и новостройках с нестандартной планировкой. Алгоритм простой:</p>

    <div data-type="box" data-color="gray">
        <h3>Пошаговый алгоритм</h3>
        <p><strong>Шаг 1:</strong> Разбейте комнату на 2 прямоугольника (проведите мысленную линию от угла до стены)<br>
        <strong>Шаг 2:</strong> Измерьте длину и ширину каждого прямоугольника<br>
        <strong>Шаг 3:</strong> Посчитайте площадь каждого: S₁ = a₁ × b₁, S₂ = a₂ × b₂<br>
        <strong>Шаг 4:</strong> Сложите: S = S₁ + S₂</p>
    </div>

    <div data-type="box" data-color="green">
        <h3>Пример</h3>
        <p>Г-образная комната:<br>
        Прямоугольник 1: 4 м × 3 м = 12 м²<br>
        Прямоугольник 2: 2 м × 2,5 м = 5 м²<br>
        <strong>Итого: 12 + 5 = 17 м²</strong></p>
    </div>

    <div data-type="box" data-color="yellow">
        <h3>Совет</h3>
        <p>Проведите схему на бумаге с размерами — это поможет не запутаться при расчёте материалов. Особенно важно для пола: ламинат, плитка и линолеум считаются по площади с запасом 5–10%.</p>
    </div>
</section>

