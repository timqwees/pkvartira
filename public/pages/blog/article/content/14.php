<section id="stage1">
    <h2>Этап 1: Прямоугольная комната — формула</h2>
    <p>Если комната имеет форму прямоугольника (или квадрата), формула элементарна:</p>
    <div data-type="box" data-color="green">
        <h3>Формула</h3>
        <p><strong>Площадь = Длина × Ширина</strong><br>
        Пример: комната 5 м × 3,5 м = <strong>17,5 м²</strong></p>
    </div>
    <p>Как замерить:</p>
    <ul>
        <li>Приставьте рулетку к самой длинной стене вдоль плинтуса — это длина;</li>
        <li>Измерьте расстояние от стены до стены перпендикулярно — это ширина;</li>
        <li>Измерьте в трёх точках (у пола, посередине, у потолка) и возьмите среднее — стены бывают неровными.</li>
    </ul>
    <div data-type="box" data-color="yellow">
        <h3>Важно</h3>
        <p>Не вычитайте площадь дверных и оконных проёмов — они входят в общую площадь комнаты по СНиП. Вычитайте только ниши глубиной более 1,2 м и встроенные шкафы до пола.</p>
    </div>
    <p>Не хотите считать вручную? Используйте наш <a href="/kalkulyator-ploshchadi" rel="nofollow">онлайн-калькулятор площади →</a></p>
</section>

<section id="stage2">
    <h2>Этап 2: Г-образная комната — разбиваем на прямоугольники</h2>
    <p>Г-образные комнаты встречаются в сталинках, хрущёвках и новостройках с нестандартной планировкой. Алгоритм:</p>
    <div data-type="box" data-color="gray">
        <h3>Пошаговый алгоритм</h3>
        <p><strong>Шаг 1:</strong> Разбейте комнату на 2 прямоугольника;<br>
        <strong>Шаг 2:</strong> Измерьте длину и ширину каждого;<br>
        <strong>Шаг 3:</strong> Посчитайте площадь каждого: S₁ = a₁ × b₁, S₂ = a₂ × b₂;<br>
        <strong>Шаг 4:</strong> Сложите: S = S₁ + S₂.</p>
    </div>
    <div data-type="box" data-color="green">
        <h3>Пример</h3>
        <p>Г-образная комната:<br>
        Прямоугольник 1: 4 м × 3 м = 12 м²;<br>
        Прямоугольник 2: 2 м × 2,5 м = 5 м²;<br>
        <strong>Итого: 12 + 5 = 17 м²</strong></p>
    </div>
</section>

<section id="stage3">
    <h2>Этап 3: Неправильная форма — треугольник, трапеция, скругления</h2>
    <p>Если комната нестандартной формы, используются формулы геометрии:</p>
    <div data-type="box" data-color="gray">
        <h3>Формулы для разных форм</h3>
        <p><strong>Треугольник:</strong> S = (a × h) / 2, где a — основание, h — высота;<br>
        <strong>Трапеция:</strong> S = ((a + b) × h) / 2, где a и b — основания, h — высота;<br>
        <strong>Скруглённый угол:</strong> вычислите площадь сегмента и вычтите из прямоугольника.</p>
    </div>
    <p>На практике неправильные формы дробят на простые фигуры: прямоугольники, треугольники, трапеции. Считают площадь каждой и складывают.</p>
    <div data-type="box" data-color="dark">
        <h3>Лайфхак</h3>
        <p>Возьмите миллиметровку или лист бумаги в клетку. Нарисуйте план комнаты в масштабе (1 клетка = 10 см). Посчитайте клетки — это и будет площадь в м². Быстро и наглядно.</p>
    </div>
</section>

<section id="stage4">
    <h2>Этап 4: Ниши, колонны, выступы — что вычитать из площади</h2>
    <p>По СНиП 31-01-2003 «Здания жилые многоквартирные» общая площадь квартиры — это сумма площадей всех комнат. Но есть нюансы:</p>
    <div data-type="compare">
        <h3>Что входит в площадь, а что нет</h3>
        <article data-variant="good">
            <h4>Входит в площадь</h4>
            <p>Дверные проёмы. Оконные проёмы. Ниши глубиной до 1,2 м. Выступы (вентиляционные короба, колонны). Балконы и лоджии — но по отдельной формуле (лоджия × 0,5, балкон × 0,3).</p>
        </article>
        <article data-variant="bad">
            <h4>Вычитается</h4>
            <p>Ниши глубиной более 1,2 м (считаются как отдельное помещение). Встроенные шкафы до пола (если по плану БТИ они не учитываются). Лестницы в двухуровневых квартирах.</p>
        </article>
    </div>
    <div data-type="box" data-color="yellow">
        <h3>Важно для ремонта</h3>
        <p>При расчёте материалов (ламинат, плитка, обои) считайте площадь стен и пола. Для стен: периметр × высота. Для пола — площадь комнаты. Не забывайте вычесть дверные проёмы при расчёте обоев.</p>
    </div>
</section>

<section id="stage5">
    <h2>Этап 5: Типичные ошибки при замере площади</h2>
    <ul>
        <li><strong>Замер по плинтусу, а не по стене</strong> — плинтус может отходить от стены на 1–3 мм, что даёт погрешность до 5% на комнату;</li>
        <li><strong>Один замер вместо трёх</strong> — стены бывают неровными. Замер в одном месте может отличаться на 10–15 см от другого;</li>
        <li><strong>Не учли кривизну пола</strong> — если пол неровный, длина рулетки «плавает». Замеряйте строго горизонтально;</li>
        <li><strong>Считают лоджию как комнату</strong> — лоджия учитывается с коэффициентом 0,5, балкон — 0,3;</li>
        <li><strong>Не фотографируют рулетку</strong> — потом не вспомните точные размеры. Фото — ваш доказательный документ.</li>
    </ul>
    <div data-type="box" data-color="red">
        <h3>Чем грозит ошибка</h3>
        <p>Недостаток ламината — докупка с другим батчем (цвет может отличаться). Передоз обоев — лишние 3000–5000 ₽. Неверная смета от подрядчика — переплата до 20%. Всегда перепроверяйте замеры дважды.</p>
    </div>
</section>

<section id="stage6">
    <h2>Этап 6: Чем замерять — рулетка, лазерный дальномер, план БТИ</h2>
    <div data-type="compare">
        <h3>Рулетка vs Лазерный дальномер</h3>
        <article data-variant="good">
            <h4>Лазерный дальномер</h4>
            <p>Точность до 1 мм. Замер в одиночку — не нужен второй человек. Сохраняет историю замеров. Стоимость — от 2000 ₽. Идеален для сложных помещений.</p>
        </article>
        <article data-variant="bad">
            <h4>Рулетка</h4>
            <p>Дешёвая (от 300 ₽). Но нужен второй человек для длинных стен. Погрешность — до 1–2 см. На неровных стенах рулетка «играет». Подходит для простых комнат.</p>
        </article>
    </div>
    <div data-type="box" data-color="gray">
        <h3>План БТИ — самый точный источник</h3>
        <p>Если у вас есть план БТИ (Бюро технической инвентаризации), площадь уже указана. Но учтите: БТИ считает по наружным стенам, а внутренние перегородки могут уменьшить реальную площадь на 1–3 м². Всегда перепроверяйте замером.</p>
    </div>
</section>

