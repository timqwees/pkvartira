<section id="errors">
    <h2>Типичные ошибки при замере площади</h2>
    <p>Даже опытные отделочники иногда допускают ошибки. Вот самые частые:</p>

    <ul>
        <li><strong>Замер по плинтусу, а не по стене</strong> — плинтус может отходить от стены на 1–3 мм, что даёт погрешность до 5% на комнату</li>
        <li><strong>Один замер вместо трёх</strong> — стены бывают неровными. Замер в одном месте может отличаться на 10–15 см от другого</li>
        <li><strong>Не учли кривизну пола</strong> — если пол неровный, длина рулетки «плавает». Замеряйте строго горизонтально</li>
        <li><strong>Считают лоджию как комнату</strong> — лоджия учитывается с коэффициентом 0,5, балкон — 0,3. Это важно для документации</li>
        <li><strong>Не фотографируют рулетку</strong> — потом не вспомните точные размеры. Фото — ваш доказательный документ</li>
    </ul>

    <div data-type="box" data-color="red">
        <h3>Чем грозит ошибка</h3>
        <p>Недостаток ламината — докупка с другим батчем (цвет может отличаться). Передоз обоев — лишние 3000–5000 ₽. Неверная смета от подрядчика — переплата до 20%. Всегда перепроверяйте замеры дважды.</p>
    </div>
</section>

