<section id="simple">
    <h2>Прямоугольная комната — самая простая формула</h2>
    <p>Если комната имеет форму прямоугольника (или квадрата), формула элементарна:</p>

    <div data-type="box" data-color="green">
        <h3>Формула</h3>
        <p><strong>Площадь = Длина × Ширина</strong></p>
        <p>Пример: комната 5 м × 3,5 м = <strong>17,5 м²</strong></p>
    </div>

    <p>Как замерить:</p>
    <ul>
        <li>Приставьте рулетку к самой длинной стене вдоль плинтуса — это <strong>длина</strong></li>
        <li>Измерьте расстояние от стены до стены перпендикулярно — это <strong>ширина</strong></li>
        <li>Измерьте в трёх точках (у пола, посередине, у потолка) и возьмите среднее — стены бывают неровными</li>
    </ul>

    <div data-type="box" data-color="yellow">
        <h3>Важно</h3>
        <p>Не вычитайте площадь дверных и оконных проёмов — они входят в общую площадь комнаты по СНиП. Вычитайте только ниши глубиной более 1,2 м и встроенные шкафы до пола.</p>
    </div>

