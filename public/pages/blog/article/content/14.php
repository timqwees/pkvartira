<section id="irregular">
    <h2>Неправильная форма — треугольник, трапеция, скругления</h2>
    <p>Если комната нестандартной формы, используются формулы геометрии:</p>

    <div data-type="box" data-color="gray">
        <h3>Формулы для разных форм</h3>
        <p><strong>Треугольник:</strong> S = (a × h) / 2, где a — основание, h — высота<br>
        <strong>Трапеция:</strong> S = ((a + b) × h) / 2, где a и b — основания, h — высота<br>
        <strong>Скруглённый угол:</strong> вычислите площадь сегмента и вычтите из прямоугольника</p>
    </div>

    <p>На практике неправильные формы дробят на простые фигуры: прямоугольники, треугольники, трапеции. Считают площадь каждой и складывают.</p>

    <div data-type="box" data-color="dark">
        <h3>Лайфхак</h3>
        <p>Возьмите миллиметровку или лист бумаги в клетку. Нарисуйте план комнаты в масштабе (1 клетка = 10 см). Посчитайте клетки — это и будет площадь в м². Быстро и наглядно.</p>
    </div>
</section>

