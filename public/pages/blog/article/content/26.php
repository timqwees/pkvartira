    <ol>
        <li><strong>Отсчитайте назад от даты сделки</strong> минимум 2 месяца: 1,5–2 месяца на работы и 2–4 недели на очередь в сезон.</li>
        <li><strong>Замер — за 3–4 недели до старта.</strong> После демонтажа объём может уточниться, и в весенний график это уже не влезть.</li>
        <li><strong>Фиксируйте цену в договоре сейчас.</strong> В сезон она действует 30–45 дней — потом пересмотр.</li>
        <li><strong>Делайте в порядке, который видно покупателю.</strong> Кухня и санузел — первыми: это то, что покупатель открывает в первую очередь.</li>
        <li><strong>Оставьте запас на фотосъёмку и клининг</strong> — 1–2 недели и 15 000–30 000 ₽.</li>
    </ol>
