<section id="buy">
    <h2>Покупка квартиры с ремонтом: на что смотреть</h2>
    <p>Обратная сторона сезона — покупки. Квартира «с ремонтом» может оказаться дороже, чем та же квартира без ремонта: продавец вложил в отделку, которую вы переделаете.</p>
    <ul>
        <li><strong>Сравнивайте с аналогами без ремонта.</strong> Разница в цене должна быть заметно меньше, чем стоимость ремонта «как есть».</li>
        <li><strong>Смотрите инженерию, а не отделку.</strong> Алюминий в стенах под красивыми обоями — это мина, которая всплывёт через год.</li>
        <li><strong>Проверяйте геометрию</strong> уровнем и правилом откоса: неровные стены под обоями — прямой торг.</li>
        <li><strong>Уточняйте, что ремонт не менял площадь и не переносил стояки</strong> без согласования — иначе сделку могут не провести.</li>
        <li><strong>Проверяйте документы</strong> на перепланировку: если ремонт менял конфигурацию, проекта может не быть.</li>
    </ul>
