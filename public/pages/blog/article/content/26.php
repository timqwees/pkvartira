<section id="price">
    <h2>Как формируется цена квартиры после ремонта</h2>
    <p>Оценщик считает не «за ремонт», а стоимость квартиры с учётом состояния. В его методике ремонт — это <strong>стартовая цена минус скидка за состояние</strong>.</p>
    <ul>
        <li><strong>Свежий косметический ремонт</strong> — скидка за «ремонт не нужен» почти не применяется.</li>
        <li><strong>Устаревшая отделка, но рабочая инженерия</strong> — скидка 5–8% от стоимости квартиры.</li>
        <li><strong>Ремонт 20+ лет назад, сносанная электрика</strong> — скидка 10–15%.</li>
        <li><strong>Сломанные сантехника, перекошенные полы</strong> — скидка 15–20% и риск торга.</li>
    </ul>
    <p>Отсюда вывод: ремонт, который стоит вам 620 000 ₽, но снижает скидку покупателя только на 150 000 ₽, — это 470 000 ₽ ваших денег, потраченных на улучшение, которое вы не продаёте, а оставляете себе. Если продаёте — вкладывайтесь в то, что оценщик считает: инженерию и геометрию.</p>
</section>

