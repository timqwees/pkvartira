<section id="faq">
    <h2>FAQ</h2>
    <div data-type="box" data-color="gray">
        <h3>Когда лучше начинать ремонт перед продажей?</h3>
        <p>За 2–2,5 месяца до планируемой сделки. В сезон (март–май) добавьте ещё 2–4 недели на очередь.</p>
    </div>
    <div data-type="box" data-color="gray">
        <h3>Окупается ли ремонт перед продажей квартиры?</h3>
        <p>Косметический — да, обычно окупается. Капитальный и дизайнерский — как правило, нет: покупатель оценивает состояние, а не вложения продавца.</p>
    </div>
    <div data-type="box" data-color="gray">
        <h3>Что выгоднее: ремонт или скидка при продаже?</h3>
        <p>Почти всегда выгоднее чистый ремонт: он снимает скидку 10–20% от цены квартиры, тогда как ваши вложения в дизайнерский пакет эту скидку не отработают.</p>
    </div>
    <div data-type="box" data-color="gray">
        <h3>Как понять, что квартира «с ремонтом» стоит своих денег?</h3>
        <p>Сравните с 3–5 аналогами в том же доме и районе без ремонта. Если разница меньше, чем стоимость ремонта, который вы всё равно переделаете, — торгуйтесь.</p>
    </div>
    <div data-type="box" data-color="gray">
        <h3>Что ремонтируют в первую очередь при продаже?</h3>
        <p>Кухню и санузел — их смотрят первыми. Затем — входнуюю группу и окна: продувание и сквозняк бросаются в глаза и стоят дороже всего остального.</p>
    </div>
    <div data-type="box" data-color="gray">
        <h3>Можно ли продать квартиру с ремонтом без согласования перепланировки?</h3>
        <p>Если ремонт менял конфигурацию — рискованно: покупатель и банк могут запросить документы, которых нет. Проверьте наличие проекта до сделки.</p>
    </div>
</section>
