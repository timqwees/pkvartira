<section id="stage1">
    <h2>Этап 1: Натяжной потолок — цены, виды, плюсы и минусы</h2>
    <ul>
        <li><strong>ПВХ-пленка (гладкая/глянцевая/сатин)</strong> — от 900 ₽/м², срок службы 10-15 лет, не боится воды (выдерживает затопление);</li>
        <li><strong>Тканевый потолок</strong> — от 1 400 ₽/м², дышит, можно красить, но боится воды;</li>
        <li><strong>Многоуровневый с подсветкой</strong> — от 2 500 ₽/м², сложный монтаж, визуально делит зону.</li>
    </ul>
    <div data-type="box" data-color="gray">
        <h3>Плюсы</h3>
        <p>Монтаж за 1 день, нет пыли и грязи, скрывает неровности бетонной плиты, защита от затопления сверху.</p>
    </div>
    <div data-type="box" data-color="red">
        <h3>Минусы</h3>
        <p>Снижает высоту комнаты на 3-5 см, можно повредить острым предметом, нельзя перекрасить, при затоплении上面 нужно сливать воду.</p>
    </div>
</section>

<section id="stage2">
    <h2>Этап 2: Штукатурка и покраска — цены, этапы, плюсы и минусы</h2>
    <ul>
        <li><strong>Выравнивание штукатуркой</strong> — от 1 200 ₽/м² (зависит от перепада);</li>
        <li><strong>Шпаклёвка финишная</strong> — от 600 ₽/м²;</li>
        <li><strong>Покраска в 2 слоя</strong> — от 700 ₽/м²;</li>
        <li><strong>Итого</strong> — от 2 500 ₽/м² под ключ.</li>
    </ul>
    <div data-type="box" data-color="gray">
        <h3>Плюсы</h3>
        <p>Не снижает высоту комнаты, можно перекрасить в любой цвет, экологично, срок службы 20+ лет.</p>
    </div>
    <div data-type="box" data-color="red">
        <h3>Минусы</h3>
        <p>Требует идеально ровных оснований, долго сохнет (7-14 дней), много пыли и грязи, не защитит от затопления сверху.</p>
    </div>
</section>

