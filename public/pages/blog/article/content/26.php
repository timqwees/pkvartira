<section id="season">
    <h2>Почему весна — пик ремонтного сезона</h2>
    <p>В марте–мае нагрузка на подрядчиков растёт по трём причинам сразу:</p>
    <ul>
        <li><strong>Годовые бонусы и премии.</strong> Деньги, полученные в феврале–марте, традиционно идут на ремонт.</li>
        <li><strong>Сроки по договору.</strong> Тот, кто начал ремонт осенью, к весне должен закончить, чтобы выставить квартиру на продажу или сдать.</li>
        <li><strong>Сезон сдачи и продаж.</strong> Семьи, переезжающие в новые дома, ремонтируют старые — с фиксированной датой передачи.</li>
    </ul>
    <div data-type="box" data-color="yellow">
        <h3>Следствие для сроков</h3>
        <p>В апреле–мае срок старта работ сдвигается на 2–4 недели. Если ремонт нужен к определённой дате, планировать нужно от неё назад: 60 м² под ключ — 46–68 дней, плюс 2–4 недели на очередь в сезон.</p>
    </div>
</section>

