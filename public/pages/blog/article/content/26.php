<section id="stage4">
    <h2>Этап 4: Что выбрать для комнаты, ванной, кухни</h2>
    <ul>
        <li><strong>Ванная и санузел:</strong> натяжной ПВХ — защита от протечек, не боится влаги;</li>
        <li><strong>Кухня:</strong> натяжной ПВХ или штукатурка моющейся краской — пар и жир;</li>
        <li><strong>Спальня и гостиная:</strong> штукатурка — не снижает высоту, экологично, можно перекрасить;</li>
        <li><strong>Прихожая:</strong> натяжной — практично, легко моется;</li>
        <li><strong>Низкие потолки (до 2,5 м):</strong> натяжной (потеря 3 см критична? нет, штукатурка лучше — не теряем высоту).</li>
    </ul>
</section>

<section id="stage5">
    <h2>Этап 5: 5 ошибок при выборе потолка</h2>
    <div data-type="compare">
        <h3>Ошибка vs Правильно</h3>
        <article data-variant="bad">
            <h4>Ошибка</h4>
            <p>1. Натяжной в спальне с низкими потолками — комната становится ещё ниже;<br>
            2. Штукатурка в ванной без гидроизоляции — отсыреет и отвалится;<br>
            3. Глянцевый натяжной в маленькой комнате — отражает беспорядок;<br>
            4. Экономия на профиле — потолок провиснет через год;<br>
            5. Покраска без выравнивания — все неровности бетона будут видны.</p>
        </article>
        <article data-variant="good">
            <h4>Правильно</h4>
            <p>Штукатурка в жилых комнатах с нормальной высотой, натяжной ПВХ в мокрых зонах, матовое полотно (не глянец), качественный профиль.</p>
        </article>
