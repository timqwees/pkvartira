<section id="stage1">
    <h2>Этап 1: Из чего складывается бюджет ремонта</h2>
    <p>В 2026 году средняя стоимость ремонта в Москве составляет от 8 000 ₽ за м² (kosметический) до 18 000 ₽ за м² (дизайнерский). Но эти цифры — только верхушка айсберга. Структура бюджета:</p>
    <div data-type="box" data-color="gray">
        <h3>Пример раскладки на квартиру 50 м²</h3>
        <p><strong>Черновые материалы:</strong> 180 000–250 000 ₽ (стяжка, штукатурка, гипсокартон, утеплитель);<br>
        <strong>Инженерия:</strong> 100 000–180 000 ₽ (электрика, сантехника, тёплый пол);<br>
        <strong>Чистовые материалы:</strong> 250 000–500 000 ₽ (плитка, ламинат, обои, краска, двери);<br>
        <strong>Работа бригады:</strong> 300 000–600 000 ₽ (зависит от сложности);<br>
        <strong>Мебель и техника:</strong> 400 000–900 000 ₽ (кухня, шкафы, сантехника, освещение);<br>
        <strong>Непредвиденные расходы (резерв 15%):</strong> 120 000–250 000 ₽.</p>
    </div>
    <p>Итоговый бюджет на капитальный ремонт квартиры 50 м² в 2026 году — от 1,5 до 2,8 млн ₽ в зависимости от уровня отделки и материалов.</p>
</section>

<section id="stage2">
    <h2>Этап 2: На чём можно сэкономить</h2>
    <p>Грамотная экономия — это не покупка самого дешёвого, а отказ от лишнего. Пять способов сократить бюджет без ущерба:</p>
    <div data-type="compare">
        <h3>Экономия vs Ложная экономия</h3>
        <article data-variant="good">
            <h4>Разумная экономия</h4>
            <p>Механизированная штукатурка — дешевле ручной на 30% и быстрее в 2 раза. Закупка материалов в строительных гипермаркетах по оптовым картам. Отказ от перепланировки — не нужно согласование. Покраска стен вместо обоев — экономия до 40% на материале.</p>
        </article>
        <article data-variant="bad">
            <h4>Ложная экономия</h4>
            <p>Дешёвая проводка — риск пожара. Экономия на гидроизоляции — затопление соседей снизу. Самостоятельный демонтаж без опыта — повреждение коммуникаций. Самые дешёвые материалы из непроверенных магазинов — подделки и брак.</p>
        </article>
    </div>
</section>

<section id="stage3">
    <h2>Этап 3: Скрытые расходы — о чём молчат в сметах</h2>
    <ul>
        <li><strong>Вывоз мусора</strong> — 15 000–30 000 ₽ за весь ремонт;</li>
        <li><strong>Замена стояков</strong> — если трубы в подъезде старые, от 15 000 ₽;</li>
        <li><strong>Повышение мощности электрики</strong> — для электроплиты или тёплых полов нужен отдельный кабель и автомат;</li>
        <li><strong>Доставка и подъём материалов</strong> — если нет грузового лифта, подъём на этаж платный;</li>
        <li><strong>Дополнительные розетки</strong> — каждая — от 1500 ₽.</li>
    </ul>
    <div data-type="box" data-color="yellow">
        <h3>Совет</h3>
        <p>Закладывайте резерв 15–20% от бюджета на непредвиденные расходы. Если резерв не понадобится — потратите на мебель или декор.</p>
    </div>
</section>

<section id="stage4">
    <h2>Этап 4: Как выбрать подрядчика и не ошибиться</h2>
    <p>Качественный ремонт на 50% зависит от бригады. Чек-лист проверки:</p>
    <ul>
        <li><strong>Договор с фиксированной сметой</strong> — обязательно. Без договора вы не защищены от повышения цены;</li>
        <li><strong>Поэтапная оплата</strong> — платите за выполненный этап, не за работу в целом. Нормально: 30% аванс, остальное по факту;</li>
        <li><strong>Реальные объекты для просмотра</strong> — фото в портфолио могут быть чужими. Попросите адрес текущего объекта;</li>
        <li><strong>Проверенные отзывы</strong> — на Яндекс Картах, Profi.ru и в Telegram-чатах домов;</li>
        <li><strong>Гарантия в договоре</strong> — минимум 1 год на работы, 3 года на скрытые дефекты.</li>
    </ul>
    <div data-type="box" data-color="dark">
        <h3>Красные флаги</h3>
        <p>Назвали цену по телефону без выезда на замер. Просят 100% предоплату. Не показывают договор. Говорят «сделаем дёшево, но неофициально» — в 2026 году это гарантия проблем.</p>
    </div>
</section>

