<section id="hidden">
    <h2>Скрытые расходы: о чём молчат в сметах</h2>
    <p>Даже опытные заказчики сталкиваются с непредвиденными тратами. Вот что чаще всего не включают в первоначальную смету:</p>

    <ul>
        <li><strong>Вывоз мусора</strong> — 15 000–30 000 ₽ за весь ремонт. Контейнер, мешки, погрузка.</li>
        <li><strong>Замена стояков</strong> — если трубы в подъезде старые, УК может потребовать замены. От 15 000 ₽.</li>
        <li><strong>Повышение мощности электрики</strong> — для электроплиты или тёплых полов нужен отдельный кабель и автомат.</li>
        <li><strong>Доставка и подъём материалов</strong> — если нет грузового лифта, подъём на этаж платный.</li>
        <li><strong>Дополнительные розетки</strong> — в процессе понимаете, что нужно ещё 3-4 точки. Каждая — от 1500 ₽.</li>
    </ul>

    <div data-type="box" data-color="yellow">
        <h3>Совет</h3>
        <p>Закладывайте резерв 15–20% от бюджета на непредвиденные расходы. Если резерв не понадобится — потратите на мебель или декор.</p>
    </div>
</section>

