<section id="faq">
    <h2>FAQ</h2>
    <p><strong>Сколько стоит ремонт однокомнатной квартиры в 2026?</strong> Косметический — от 400 000 ₽, капитальный — от 800 000 ₽, дизайнерский — от 1,2 млн ₽. Точная цена зависит от состояния квартиры и региона.</p>
    <p><strong>Что дороже: нанять частную бригаду или компанию?</strong> Частники часто дешевле на 15–20%, но гарантии меньше. Компания дороже, но несёт ответственность по договору. В 2026 году разница в цене сокращается.</p>
    <p><strong>Когда лучше начинать ремонт в 2026?</strong> Сезон затишья — ноябрь–февраль. В это время бригады менее загружены и могут дать скидку 5–10%. Летом — пик, цены выше, а сроки ожидания — до месяца.</p>
    <p><strong>Обязательно ли делать дизайн-проект?</strong> Для косметического ремонта — нет. Для капитального — желательно, чтобы избежать ошибок. Для дизайнерского — обязательно. Стоимость проекта — от 1000 ₽ за м².</p>

