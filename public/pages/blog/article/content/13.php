<section id="contractor">
    <h2>Как выбрать подрядчика и не ошибиться</h2>
    <p>Качественный ремонт на 50% зависит от бригады. В 2026 году рынок перенасыщен частными мастерами и компаниями, но найти надёжного подрядчика всё сложнее. Вот чек-лист проверки:</p>

    <ul>
        <li><strong>Договор с фиксированной сметой</strong> — обязательно. Без договора вы не защищены от повышения цены в процессе.</li>
        <li><strong>Поэтапная оплата</strong> — платите за已完成ный этап, не за работу в целом. Нормально: 30% аванс, остальное по факту.</li>
        <li><strong>Реальные объекты для просмотра</strong> — фото в портфолио могут быть чужими. Попросите адрес текущего объекта.</li>
        <li><strong>Проверенные отзывы</strong> — на Яндекс Картах, Profi.ru и в Telegram-чатах домов. Отзывы на сайте компании могут быть заказными.</li>
        <li><strong>Гарантия в договоре</strong> — минимум 1 год на работы, 3 года на скрытые дефекты.</li>
    </ul>

    <div data-type="box" data-color="dark">
        <h3>Красные флаги</h3>
        <p>Нас спрашивают цену по телефону без выезда на замер. Просят 100% предоплату. Не показывают договор. Говорят «сделаем дёшево, но неофициально» — в 2026 году это гарантия проблем.</p>
    </div>
</section>

