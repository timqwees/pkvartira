<section id="faq">
    <h2>FAQ</h2>
    <div data-type="box" data-color="gray">
        <h3>С чего начать ремонт в новостройке?</h3>
        <p>С замера и решения по пакету работ. Если квартира ещё не получена — организуйте замер заранее, а работы начните сразу после передачи ключей.</p>
    </div>
    <div data-type="box" data-color="gray">
        <h3>Можно ли ремонтировать квартиру поэтапно?</h3>
        <p>Да, и это часто выгоднее по бюджету: черновые работы в один сезон, чистовую отделку — в следующий. Но инженерные системы и стяжку лучше закрыть полностью: переделывать их в обжитой квартире дороже в разы.</p>
    </div>
    <div data-type="box" data-color="gray">
        <h3>Сколько времени занимает ремонт с нуля?</h3>
        <p>46–68 дней на 60 м² полного цикла. Дизайнерский пакет добавляет 15–20 дней на согласование проекта и сложные решения.</p>
    </div>
    <div data-type="box" data-color="gray">
        <h3>Нужно ли согласовывать перепланировку?</h3>
        <p>Если меняете планировку — да, до начала работ. Согласование по проекту перепланировки занимает 2–4 месяца, поэтому в новостройке его запускают сразу после передачи ключей. Что можно делать без согласования — в статье <a href="/blog/pereplanirovka-kvartiry-soglasovanie" style="color:#2563eb;font-weight:600;">«Перепланировка в Москве: что можно без согласования»</a>.</p>
    </div>
    <div data-type="box" data-color="gray">
        <h3>Что делать с отделкой от застройщика?</h3>
        <p>Оцените на замере. Если покрытия нормального качества — косметика поверх них дешевле полного цикла. Если это линолеум на тонком основании и обои без шпаклёвки — капитальный пакет выгоднее, чем «доделка» поверх.</p>
    </div>
    <div data-type="box" data-color="gray">
        <h3>Когда лучше начинать, чтобы успеть к сроку?</h3>
        <p>Стартовать в день передачи ключей. Планируйте обратный отсчёт от даты, к которой нужна готовая квартира, с запасом 2–3 недели на согласование и технические паузы.</p>
    </div>
</section>
