<section id="stage4">
    <h2>Этап 4: Чек-лист приёмки кухни</h2>
    <ul>
        <li>☐ Кухонный гарнитур стоит ровно, зазоры между модулями одинаковые;</li>
        <li>☐ Столешница прилегает к стене без зазоров, шов с фартуком загерметизирован;</li>
        <li>☐ Мойка не течёт, сифон доступен для прочистки;</li>
        <li>☐ Плита и духовка подключены, все режимы работают;</li>
        <li>☐ Вытяжка работает на всех скоростях, воздух выводится в вентиляцию;</li>
        <li>☐ Розетки над столешницей — с защитными шторками, на высоте не менее 15 см от поверхности;</li>
        <li>☐ Ящики и дверцы открываются/закрываются плавно, без скрипа.</li>
    </ul>
</section>

<section id="stage5">
    <h2>Этап 5: 5 ошибок, которые исправляют через год</h2>
    <div data-type="compare">
        <h3>Ошибка vs Правильно</h3>
        <article data-variant="bad">
            <h4>Ошибка</h4>
            <p>1. Нет вытяжки над плитой — жир на мебели;<br>
            2. Розетки над мойкой — опасность замыкания;<br>
            3. Фартук из ламината — разбухает от пара;<br>
            4. Ящики без доводчиков — хлопают, разваливаются;<br>
            5. Неправильная высота столешницы — болит спина.</p>
        </article>
        <article data-variant="good">
            <h4>Правильно</h4>
            <p>Вытяжка 60 см, розетки на защищённом контуре, керамогранитный фартук, доводчики Blum, высота столешницы 85-90 см под рост хозяина.</p>
        </article>
    </div>
