<section id="before">
    <h2>До старта: что решить, пока квартира не получена</h2>
    <p>Пока дом строится, у вас есть время, которое потом не вернуть. Три решения, которые нужно принять до первого рабочего дня:</p>
    <ul>
        <li><strong>Пакет работ.</strong> Косметический или капитальный. От этого зависит, успеете ли вы к сроку сдачи.</li>
        <li><strong>Перепланировка.</strong> Если планируете менять планировку — проектируйте и согласуйте заранее. Перенос санузла, кухни-гостиной или снос перегородки после начала чистовой отделки — это переделка готового.</li>
        <li><strong>Состояние квартиры на старте.</strong> Что уже сделал застройщик: стяжка, штукатурка, электрика. Каждый сделанный этап — это вычтенные из сметы деньги.</li>
    </ul>
    <div data-type="box" data-color="blue">
        <h3>Совет</h3>
        <p>Закажите замер за 1–2 недели до передачи ключей — инженер посмотрит реальное состояние и посчитает объёмы. Подробности: <a href="/services/budushchiy-remont" style="color:#2563eb;font-weight:600;">ремонт к дате получения ключей</a>.</p>
    </div>
</section>

<section id="step1">
    <h2>Этап 1. Демонтаж и вынос мусора</h2>
    <p>Сносим то, что подлежит замене: старые перегородки, покрытия, сантехнику, электрику. Параллельно — разбор, вынос и вывоз мусора.</p>
    <p><strong>Срок:</strong> 3–5 дней на квартиру 60 м². <strong>Что решается здесь:</strong> объём демонтажа влияет на всё дальше. Не сносите перегородку, которая может нести вес, до консультации инженера — иначе придётся усиливать конструкцию, а это отдельный проект и отдельные деньги.</p>
</section>

<section id="step2">
    <h2>Этап 2. Черновая подготовка стен и пола</h2>
    <p>Убираем то, что мешает работать: старые штукатурки, штробы, кривые поверхности. Выравниваем стены — грубо, под дальнейшую финишную отделку.</p>
    <p><strong>Срок:</strong> 5–8 дней. <strong>Важно:</strong> если в квартире неровная геометрия, объём выравнивания считается по факту замера, а не по площади. Вот здесь чаще всего и возникает разница между сметой «по калькулятору» и настоящей сметой.</p>
</section>

<section id="step3">
    <h2>Этап 3. Инженерные системы</h2>
    <p>Прокладываем электрику, сантехнику, вентиляцию, тёплые полы — по проекту, с расчётом нагрузок и количества розеток.</p>
    <p><strong>Срок:</strong> 7–10 дней. <strong>Главное правило этапа:</strong> количество розеток и сценарии их использования определяются до штробления. Перенести розетку после чистовой отделки — значит повторно штробить готовую стену.</p>
    <div data-type="box" data-color="yellow">
        <h3>Не экономьте на инженерии</h3>
        <p>Замена электрики и сантехники в новостройке — самая частая позиция, которую удешевляют, и самая дорогая при переделке. Слабый щит или алюминиевая проводка изначально обрекают квартиру на повторный ремонт стен.</p>
    </div>
</section>

<section id="step4">
    <h2>Этап 4. Стяжка и штукатурка</h2>
    <p>Заливаем стяжку с разуклоном к точкам, штукатури�� стены по маякам. Это основа ровной геометрии под покраску, обои и плитку.</p>
    <p><strong>Срок:</strong> 10–14 дней плюс технологическая пауза на набор прочности. <strong>Почему это ключевой этап:</strong> после стяжки и штукатурки геометрия становится известной — и только теперь можно точно ставить плитку, плинтусы и двери без щелей и зазоров.</p>
</section>

<section id="step5">
    <h2>Этап 5. Черновые работы: электрика, сантехника</h2>
    <p>Ставим розетки и выключатели, прокладываем кабель, монтируем сантехнику, подключаем радиаторы и вентиляцию.</p>
    <p><strong>Срок:</strong> 7–10 дней. На этом этапе принимается вся скрытая часть — то, что потом не видно и не переделать без вскрытия стен. Приёмка по чек-листу с фотоотчётом обязательна.</p>
</section>

<section id="step6">
    <h2>Этап 6. Чистовая отделка</h2>
    <p>Штукатурка под покраску, шпаклёвка, поклейка обоев или покраска, стяжка финишная, ламинат, плитка в санузлах и на кухне.</p>
    <p><strong>Срок:</strong> 10–14 дней. Порядок обязателен: сначала потолок, потом стены, потом пол — так пыль от последующих работ не попадает на готовые поверхности.</p>
</section>

<section id="step7">
    <h2>Этап 7. Двери, плинтусы, свет</h2>
    <p>Устанавливаем межкомнатные и входнуюю двери, плинтусы, карнизы, светильники, зеркала и аксессуары.</p>
    <p><strong>Срок:</strong> 3–5 дней. Мелочь, которая делает квартиру «сданной»: без плинтусов и розеток в нужных местах объект выглядит незавершённым, даже если стены идеальные.</p>
</section>

<section id="step8">
    <h2>Этап 8. Уборка и сдача объекта</h2>
    <p>Генеральная уборка, проверка всей инженерии по чек-листу, фиксация гарантийных обязательств, передача ключей и документации.</p>
    <p><strong>Срок:</strong> 1–2 дня. На этом этапе удобно проверить, что работают все розетки, сливы, радиаторы и освещение, — и подписать акт приёмки этапа.</p>
</section>

