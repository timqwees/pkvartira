<section id="stage2">
    <h2>Этап 2: Этапы работ — от проектирования до приёмки</h2>
    <ul>
        <li><strong>1. Проект кухни</strong> — расстановка мебели, розеток, вытяжки (3-5 дней);</li>
        <li><strong>2. Демонтаж</strong> — снятие старой мебели, плитки, вывоз (1-2 дня);</li>
        <li><strong>3. Черновые</strong> — стяжка, штукатурка, электрика, сантехника (7-10 дней);</li>
        <li><strong>4. Чистовые</strong> — плитка фартука, пол, потолок, малярка (5-7 дней);</li>
        <li><strong>5. Мебель и техника</strong> — доставка, сборка, подключение (3-5 дней);</li>
        <li><strong>6. Финал</strong> — подключение мойки, плиты, приёмка (1 день).</li>
    </ul>
    <p>Общий срок: 18-25 дней. С учётом доставки кухонного гарнитура — до 4 недель.</p>
