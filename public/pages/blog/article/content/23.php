<section id="stage3">
    <h2>Этап 3: Тренды кухонь 2026 — планировка, материалы, фасады</h2>
    <ul>
        <li><strong>Фартук:</strong> керамогранит под мрамор или бетон, стеклянные панели, метлик 7,5×15 см;</li>
        <li><strong>Столешница:</strong> акриловый камень, кварцевый агломерат, не ламинат (博ится влаги);</li>
        <li><strong>Фасады:</strong> матовые крашеные МДФ, шпон, нет глянцевого пластика (через 2 года поцарапается);</li>
        <li><strong>Ручки:</strong> скрытые профили, нажимные механизмы, нет выпирающих ручек;</li>
        <li><strong>Освещение:</strong> подсветка над рабочей зоной — обязательна, светодиодная лента.</li>
    </ul>
