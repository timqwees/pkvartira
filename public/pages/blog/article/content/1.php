<section id="stage1">
    <h2>Этап 1: Замер и техническое обследование (3–5 дней)</h2>
    <p>Перед любыми работами мастер замеряет площадь комнаты, высоту потолков, толщину стен и проверяет состояние электрики, сантехники и вентиляции. Без замеров нельзя составить точную смету — ошибка в 1 м² при цене 8 000 ₽/м² означает переплату на 8 000 ₽ и больше.</p>
    <p>Что проверяем на этом этапе:</p>
    <ul>
        <li>Фактическая площадь и геометрия комнат;</li>
        <li>Состояние стяжки, электропроводки и сантехники;</li>
        <li>Вентиляция и дымоходы (в многоквартирных домах);</li>
        <li>Несущие конструкции — какие стены нельзя сносить.</li>
    </ul>
    <p>Результат этапа — дефектная ведомость и черновик сметы. С этим документом можно переходить к согласованию цены.</p>
    <p>Если вы ещё не выбрали подрядчика, рекомендуем начать с <a href="/calculator" rel="nofollow">онлайн-калькулятора ремонта</a>, чтобыOrientироваться в бюджете ещё до замеров.</p>
</section>

<section id="stage2">
    <h2>Этап 2: Смета и договор (5–10 дней)</h2>
    <p>Смета должна быть фиксированной: в ней прописываются все виды работ, материалы и их количество, сроки и гарантия. Проект Квартира фиксирует стоимость в договоре — цена не растёт в процессе ремонта.</p>
    <p>На что смотреть в смете:</p>
    <ul>
        <li>Перечень работ с unidadми измерения (м², м.п., шт.);</li>
        <li>Стоимость материалов с разбивкой по позициям;</li>
        <li>График этапов и даты сдачи;</li>
        <li>Срок гарантии (у нас — 3 года на все виды работ).</li>
    </ul>
    <p>Подписанный договор с фиксированной суммой — ваша защита от «скрытых накруток» в процессе ремонта.</p>
</section>

<section id="stage3">
    <h2>Этап 3: Демонтаж и вывоз мусора (2–4 дня)</h2>
    <p>На третьем этапе снимаются старые покрытия, демонтируются перегородки (если они не несущие), выводится старая электротехника и сантехника. В 2026 году вывоз строительного мусора в Москве стоит от 5 000 ₽ за машину, в зависимости от объёма.</p>
    <p>Важное правило: не трогать несущие стены и не нарушать целостность плит перекрытий. Любое изменение несущих конструкций требует согласования в Мосжилинспекции.</p>
    <p>После демонтажа мастер осматривает основание пола и стен — от этого зависит, нужна ли стяжка или достаточно самовыравнивающейся смеси.</p>
</section>

<section id="stage4">
    <h2>Этап 4: Черновая и чистовая отделка (15–35 дней)</h2>
    <p>Это самый длительный этап. Он включает штукатурку стен, стяжку пола, монтаж гипсокартонных конструкций, разводку электрики и сантехники, а затем укладку плитки, поклейку обоев и установку дверей.</p>
    <h3>Черновая отделка</h3>
    <p>Штукатурка и стяжка должны высохнуть полностью — обычно 7–14 дней. Пропуск технологических пауз приводит к трещинам и отслоению покрытия.</p>
    <h3>Чистовая отделка</h3>
    <p>Видимая часть ремонта: полы, стены, потолки, двери, освещение. На этом этапе определяются эстетика и срок службы интерьера.</p>
    <p>Для подбора материалов и расчёта их количества полезно использовать <a href="/kalkulyator-ploshchadi" rel="nofollow">калькулятор площади ремонта</a> — так вы купите ровно столько, сколько нужно, без лишних остатков.</p>
</section>

<section id="stage5">
    <h2>Этап 5: Финальный осмотр и сдача объекта (2–3 дня)</h2>
    <p>После завершения работ проводится совместный осмотр объекта с подрядчиком и заказчиком. Составляется акт приёмки работ — в нём фиксируются все замечания и сроки их устранения.</p>
    <p>Гарантия 3 года начинается с даты подписания акта. В течение этого периода вы можете обратиться за устранением любых дефектов, связанных с качеством работ.</p>
</section>

