<section id="stage4">
    <h2>Этап 4: Чек-лист проверки сметы за 10 минут</h2>
    <ul>
        <li>☐ Есть разбивка работа/материал с брендом и расходом?</li>
        <li>☐ Нет двойных строк (грунтовка×2, доставка×2)?</li>
        <li>☐ Коэффициенты обоснованы фото перепадов?</li>
        <li>☐ Цена смеси = Леруа/Петрович + 5-10%, не ×2?</li>
        <li>☐ Вывоз — контейнер, не мешки по 500 ₽?</li>
        <li>☐ Гарантия бесплатно, не 3% от сметы?</li>
        <li>☐ Итог фиксируется в договоре без слова «ориентировочно»?</li>
    </ul>
    <p>Если 2+ пункта — нет, просите переделать. Или пришлите смету в Telegram — проверим бесплатно за 30 минут.</p>
</section>

<section id="stage5">
    <h2>Этап 5: Где чаще всего накручивают</h2>
    <div data-type="compare">
        <h3>Накрутка vs Честно</h3>
        <article data-variant="bad">
            <h4>Накрутка</h4>
            <p>«Подготовка основания» без расшифровки — 1200 ₽/м². Коэффициент сложности ×1,5 без обоснования. Доставка отдельной строкой, хотя уже в цене материалов.</p>
        </article>
        <article data-variant="good">
            <h4>Честно</h4>
            <p>Каждая строка: «Штукатурка стен Ротбанд 10 мм — 580 ₽/м² (работа 350 + материал 230)». Коэффициент — только с фото перепадов. Доставка — одна строка.</p>
        </article>
    </div>
    <ul>
        <li>Двойная грунтовка — считают два раза, хотя грунт один;</li>
        <li>Завышенный расход смеси на 30% выше нормы Кнауф;</li>
        <li>«Накладные расходы 10%» без расшифровки — 120 000 ₽ на 60 м²;</li>
        <li>Коэффициент 1,3-1,5 «за стеснённость» в пустой новостройке;</li>
        <li>Вывоз мусора мешками по 500 ₽ вместо контейнера 8000 ₽ на 20 м³;</li>
        <li>Гарантия за деньги — 3% от сметы, хотя по закону бесплатна.</li>
    </ul>
</section>

