<section id="what">
    <h2>Что такое смета простыми словами</h2>
    <p>Смета = список всех работ + количество × цена + материалы. Каждая строка отвечает на 3 вопроса: что делаем, сколько, почём.</p>
    <div data-type="box" data-color="gray">
        <h3>Как выглядит строка сметы</h3>
        <p>«Штукатурка стен Ротбанд 10 мм — 162 м² × 580 ₽ = 93 960 ₽ (работа 350 ₽ + материал 230 ₽)». Видно объём, цену и состав. Если видите только «Штукатурка — 100 000 ₽» без метров и цены — это не смета, а «цифра с потолка».</p>
    </div>
    <p>Зачем нужна: фиксирует цену до старта, защищает от «ой, тут доплата 200 тысяч» в середине ремонта и позволяет сравнить 2–3 подрядчиков построчно, а не по итогу.</p>
</section>

<section id="structure">
    <h2>Из чего состоит: 5 разделов</h2>
    <p>Хорошая смета на квартиру — 15–25 страниц. 5 обязательных частей:</p>
    <ul>
        <li><strong>1. Демонтаж:</strong> снятие старого, вывоз мусора (мешки, контейнер).</li>
        <li><strong>2. Черновые работы:</strong> штукатурка, стяжка, электрика, сантехника — около 45% бюджета.</li>
        <li><strong>3. Чистовые работы:</strong> плитка, ламинат, покраска, двери — около 35%.</li>
        <li><strong>4. Материалы:</strong> отдельно черновые (смеси, кабель) и чистовые (плитка, ламинат) с брендом и расходом.</li>
        <li><strong>5. Логистика:</strong> доставка, подъём, уборка — 5–7%.</li>
