<section id="faq">
    <h2>FAQ</h2>
    <p><strong>Смета и договор — это одно и то же?</strong> Нет. Смета — приложение с ценами, договор — юридический документ. Цена из сметы должна быть продублирована в договоре как «фиксированная».</p>
    <p><strong>Смета может вырасти в процессе?</strong> Только по допсоглашению с вашей подписью (например, вы сами добавили тёплый пол). Без допсоглашения рост незаконен.</p>
    <p><strong>Сколько стоит составление сметы?</strong> У нас замер + смета — бесплатно за 24 часа. Отдельно у сметчиков — 5 000–15 000 ₽, но эти деньги обычно «отбиваются» найденными накрутками.</p>
    <p><strong>Чем смета отличается от калькуляции?</strong> Ничем по сути — «калькуляция» чаще называют укрупнённый расчёт (цена за м²), а «смета» — детальный построчный документ.</p>
