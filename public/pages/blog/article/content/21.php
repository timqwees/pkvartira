<section id="stage1">
    <h2>Этап 1: Что такое смета простыми словами</h2>
    <p>Смета — это таблица с тремя колонками: работа, материал, цена. Сумма по всем строкам — итоговая стоимость ремонта. Если в смете только одна цифра «1 200 000 ₽» — это не смета, а коммерческое предложение. Настоящая смета — 15-30 страниц с разбивкой по каждой комнате.</p>
    <div data-type="box" data-color="gray">
        <h3>Почему смету нужно читать</h3>
        <p>Без детализации подрядчик может заменить Ротбанд на дешёвую штукатурку, уложить ламинат без подложки, или посчитать вывоз мусора дважды. Смета защищает от этого — всё фиксировано ценою.</p>
    </div>
</section>

<section id="stage2">
    <h2>Этап 2: Состав сметы — 5 разделов</h2>
    <div data-type="box" data-color="gray">
        <h3>5 обязательных разделов сметы</h3>
        <p><strong>1. Демонтаж</strong> — снятие старой отделки, вывоз мусора;<br>
        <strong>2. Черновые работы</strong> — стяжка, штукатурка, электрика, сантехника (до 45% бюджета);<br>
        <strong>3. Чистовые работы</strong> — плитка, ламинат, покраска, двери (до 35%);<br>
        <strong>4. Материалы</strong> — черновые и чистовые отдельно, с брендом и расходом;<br>
        <strong>5. Логистика</strong> — доставка, подъём, уборка (5-7%).</p>
    </div>
    <p>Если в смете нет разделения «работа + материал» — требуйте переделки. Иначе вы купите мешок Ротбанда за 800 ₽ при цене 400 ₽ в магазине.</p>
</section>

