<section id="stage1">
    <h2>Этап 1: Где разместить рабочую зону — 4 сценария</h2>
    <p>Не у всех есть отдельный кабинет. Четыре реалистичных варианта:</p>
    <ul>
        <li><strong>У окна в гостиной</strong> — естественный свет, зона не мешает проходу. Минус: если телевизор работает, сложно сосредоточиться;</li>
        <li><strong>В спальне</strong> — тихо и уединённо. Главное — отделить рабочую зону от кровати;</li>
        <li><strong>На лоджии</strong> — утеплённая лоджия становится идеальным кабинетом. Самый популярный тренд 2026;</li>
        <li><strong>За шкафом-купе</strong> — откидной стол в нише шкафа. Решение для микроквартир до 30 м².</li>
    </ul>
    <div data-type="box" data-color="gray">
        <h3>Исследование 2026</h3>
        <p>Владельцы квартир с выделенной рабочей зоной на 35% реже жалуются на выгорание и на 50% — на боли в спине.</p>
    </div>
</section>

<section id="stage2">
    <h2>Этап 2: Эргономика — стол, стул, экран</h2>
    <p>Правильная эргономика повышает продуктивность на 20%. Золотые стандарты 2026:</p>
    <div data-type="compare">
        <h3>Правильная эргономика vs Вредные привычки</h3>
        <article data-variant="good">
            <h4>Эргономичное решение</h4>
            <p>Стол высотой 72–76 см. Кресло с поддержкой поясницы и подлокотниками. Монитор на уровне глаз. Ноги стоят на полу под 90°.</p>
        </article>
        <article data-variant="bad">
            <h4>Вредные привычки</h4>
            <p>Работа лёжа на диване с ноутбуком на животе. Стул без спинки. Монитор ниже уровня глаз — нагрузка на шею.</p>
        </article>
    </div>
    <div data-type="box" data-color="dark">
        <h3>Стол-трансформер — тренд 2026</h3>
        <p>Столы с электроприводом (sit-stand) от 25 000 ₽. Чередование сидячего и стоячего положения снижает нагрузку на позвоночник на 40%.</p>
    </div>
</section>

<section id="stage3">
    <h2>Этап 3: Зонирование без стен</h2>
    <p>Отделить рабочую зону от жилой помогут приёмы без капитальных стен:</p>
    <ul>
        <li><strong>Стеллаж-перегородка</strong> — с одной стороны книги, с другой — растения;</li>
        <li><strong>Шторы-нити</strong> — визуально отделяют зону, не съедая пространство;</li>
        <li><strong>Разный цвет стен</strong> — акцентная стена в рабочей зоне (глубокий синий или тёмно-зелёный);</li>
        <li><strong>Ковёр-граница</strong> — ковёр на полу визуально выделяет зону.</li>
    </ul>
</section>

<section id="stage4">
    <h2>Этап 4: Освещение для продуктивности</h2>
    <p>Правила освещения рабочей зоны:</p>
    <ul>
        <li>Основной свет — потолочный светильник с холодной температурой 4000–5000K;</li>
        <li>Настольная лампа слева (для правшей) или справа (для левшей);</li>
        <li>Избегайте бликов на экране — не ставьте стол напротив окна;</li>
        <li>LED-лента по периметру монитора снижает нагрузку на глаза.</li>
    </ul>
</section>

