<section id="stage1">
    <h2>Этап 1: Палитра 2026 — 5 главных цветов</h2>
    <p>По версии ведущих дизайн-бюро, 2026 год — время тёплой нейтральной палитры. Пять цветов в топе:</p>
    <ul>
        <li><strong>«Тёплая слоновая кость»</strong> — базовый стеновой цвет, заменяет холодный белый;</li>
        <li><strong>«Пыльная роза»</strong> — приглушённый розово-серый, идеален для спальни и гостиной;</li>
        <li><strong>«Шалфей»</strong> — серо-зелёный оттенок, хорош для кухни и кабинета;</li>
        <li><strong>«Глиняный»</strong> — терракотовый с серым подтоном, для акцентных стен и текстиля;</li>
        <li><strong>«Графит»</strong> — глубокий тёмно-серый, для кухонных фасадов, рам окон, дверей.</li>
    </ul>
</section>

<section id="stage2">
    <h2>Этап 2: Натуральные материалы — дерево, камень, микробетон</h2>
    <p>Использование натуральных материалов улучшает микроклимат и тактильные ощущения:</p>
    <div data-type="compare">
        <h3>Натуральный vs Искусственный</h3>
        <article data-variant="good">
            <h4>Трендовые материалы</h4>
            <p>Микробетон на стенах и полу (индустриальный шик). Массивная доска маслом без лака. Натуральный камень в столешницах. Льняной текстиль. Керамогранит под мрамор.</p>
