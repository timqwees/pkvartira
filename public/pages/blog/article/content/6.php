        </article>
    </div>
</section>

<section id="stage3">
    <h2>Этап 3: Как сочетать тренды в одном интерьере</h2>
    <p>Главный навык современного дизайна — миксование текстур. Работающее правило 60-30-10:</p>
    <ul>
        <li><strong>База (60%)</strong> — нейтральные стены и пол (тёплая слоновая кость + дерево);</li>
        <li><strong>Акценты (30%)</strong> — цветная мебель, текстиль, декор (пыльная роза или шалфей);</li>
        <li><strong>Детали (10%)</strong> — металл, стекло, керамика (латунь, состаренная бронза, рифлёное стекло).</li>
    </ul>
</section>

<section id="stage4">
    <h2>Этап 4: Антитренды 2026 — от чего отказаться</h2>
    <p>Чтобы интерьер не выглядел устаревшим, избегайте:</p>
    <ul>
        <li>Серый ламинат с серыми стенами («серая паника» 2010-х);</li>
        <li>Глянцевые кухонные фасады — каждый отпечаток пальца виден;</li>
        <li>Однотонные белые двери без фрезеровки — выглядят как больничные;</li>
        <li>Искусственные цветы и растения — пылесборники.</li>
    </ul>
</section>

