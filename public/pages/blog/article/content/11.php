<section id="stage1">
    <h2>Этап 1: Планировка кухни — рабочий треугольник</h2>
    <p>Золотое правило кухонной эргономики — рабочий треугольник «плита — мойка — холодильник». Расстояние между вершинами: 1.2–2.7 метра. Сумма сторон — не более 8 метров.</p>
    <p>Три типа планировки в 2026 году:</p>
    <ul>
        <li><strong>Линейная</strong> — для узких кухонь. Всё вдоль одной стены. Плюс: дёшево. Минус: много ходьбы;</li>
        <li><strong>Угловая (L-образная)</strong> — классика. Вмещает уголок для завтраков. Рабочий треугольник оптимален;</li>
        <li><strong>П-образная</strong> — для просторных кухонь от 12 м². Всё под рукой, много хранения.</li>
    </ul>
</section>

<section id="stage2">
    <h2>Этап 2: Тренды кухонь 2026</h2>
    <p>Что в топе в этом году:</p>
    <ul>
        <li><strong>Матовые фасады</strong> — без глянца и отпечатков пальцев. Цвета: графит, шампань, оливковый;</li>
        <li><strong>Кварцевый агломерат в столешнице</strong> — прочнее натурального камня и без пор;</li>
        <li><strong>Фартук из керамогранита</strong> — бесшовный (до 3 м длиной), легко моется;</li>
        <li><strong>Скрытая фурнитура</strong> — ручки-профили или системы push-to-open;</li>
        <li><strong>Остров</strong> — даже на кухне 10 м² можно вписать компактный остров на колёсах.</li>
    </ul>
    <div data-type="compare">
