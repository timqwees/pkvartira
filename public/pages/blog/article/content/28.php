<section id="stage2">
    <h2>Этап 2: Этапы выравнивания стен — штукатурка и шпаклёвка</h2>
    <ul>
        <li><strong>1. Оценка кривизны</strong> — правило 2 м, отклонения mark;</li>
        <li><strong>2. Грунтовка</strong> — бетоноконтакт или универсальная, в зависимости от основания;</li>
        <li><strong>3. Маяки</strong> — профиль 6 или 10 мм, шаг 1 м;</li>
        <li><strong>4. Штукатурка</strong> — Ротбанд, Knauf, Ветонит — слоями до 50 мм;</li>
        <li><strong>5. Шпаклёвка стартовая</strong> — выравнивание после штукатурки;</li>
        <li><strong>6. Шпаклёвка финишная</strong> — под покраску или обои, 1-2 мм.</li>
    </ul>
    <div data-type="box" data-color="gray">
        <h3>Нормативы</h3>
        <p>Отклонение от вертикали — не более 2 мм на 1 м. Под плитку допускается 3 мм, под покраску — 1 мм.</p>
    </div>
</section>

<section id="stage3">
    <h2>Этап 3: Этапы выравнивания пола — стяжка и самовыравниватель</h2>
    <ul>
        <li><strong>1. Очистка основания</strong> — мусор, пыль, масляные пятна;</li>
        <li><strong>2. Грунтовка</strong> — бетоноконтакт для адгезии;</li>
        <li><strong>3. Маяки</strong> — уровень 0, шаг 1-1,5 м;</li>
        <li><strong>4. Стяжка</strong> — цементно-песчаная М300, толщина 50-70 мм;</li>
        <li><strong>5. Сушка</strong> — 28 дней на полную прочность, 7-10 дней для начала работ;</li>
        <li><strong>6. Самовыравниватель</strong> — финишный слой 3-10 мм под ламинат/линолеум.</li>
    </ul>
    <div data-type="box" data-color="gray">
        <h3>Норматив</h3>
        <p>Перепад по полу — не более 2 мм на 2 м. Под плитку — 3 мм, под ламинат — 2 мм.</p>
    </div>
</section>

<section id="stage4">
    <h2>Этап 4: Чек-лист приёмки выравнивания</h2>
    <ul>
        <li>☐ Стены — отклонение не более 2 мм на 1 м (правило + отвес);</li>
        <li>☐ Пол — перепад не более 2 мм на 2 м (уровень или лазер);</li>
        <li>☐ Нет трещин в штукатурке и стяжке;</li>
        <li>☐ Штукатурка не отслаивается — постукивание не даёт глухого звука;</li>
        <li>☐ Маяки удалены, швы замазаны (не оставлены внутри стены);</li>
        <li>☐ Поверхность готова к финишной отделке — нет пыли, масел.</li>
    </ul>
</section>

<section id="stage5">
    <h2>Этап 5: 5 ошибок, которые исправляют переделкой</h2>
    <div data-type="compare">
        <h3>Ошибка vs Правильно</h3>
        <article data-variant="bad">
            <h4>Ошибка</h4>
            <p>1. Штукатурка без грунтовки — отвалится через месяц;<br>
            2. Стяжка без маяков — волна на полу, плитка ляжет криво;<br>
            3. Шпаклёвка на влажную штукатурку — пузыри и трещины;<br>
            4. Слой штукатурки более 50 мм без армирования — обвалится;<br>
            5. Хождение по стяжке через день — вмятины, которые потом не убрать.</p>
        </article>
        <article data-variant="good">
            <h4>Правильно</h4>
            <p>Грунтовка бетоноконтакт, маяки, армирование сеткой при толщине >30 мм, сушка стяжки 28 дней, хождение через 5-7 дней в мягкой обувке.</p>
        </article>
    </div>
