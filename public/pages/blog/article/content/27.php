<section id="stage2">
    <h2>Этап 2: Этапы замены электропроводки</h2>
    <ul>
        <li><strong>1. Проект</strong> — расстановка розеток, выключателей, приборов (2-3 дня);</li>
        <li><strong>2. Штробление</strong> — прорезывание каналов в стенах под кабель (2-4 дня);</li>
        <li><strong>3. Укладка кабеля</strong> — ВВГнг-LS в гофре или коробе (3-5 дней);</li>
        <li><strong>4. Установка щита</strong> — автоматы, УЗО, счётчик (1 день);</li>
        <li><strong>5. Установка розеток и выключателей</strong> (1-2 дня);</li>
        <li><strong>6. Закрытие штроб</strong> — штукатурка, шпаклёвка (2-3 дня).</li>
    </ul>
    <p>Общий срок: 10-15 дней. Электрика делается до чистовой отделки — после укладки плитки или ламината штробить нельзя.</p>
</section>

<section id="stage3">
    <h2>Этап 3: Кабель, щит, автоматы — что выбрать</h2>
    <ul>
        <li><strong>Кабель:</strong> ВВГнг-LS 3×2,5 мм² для розеток, 3×1,5 мм² для освещения, не алюминий;</li>
        <li><strong>Автоматы:</strong> Schneider Electric, Legrand, ABB — не безымянные;</li>
        <li><strong>УЗО:</strong> обязательно на группы розеток и ванную (ток утечки 30 мА);</li>
        <li><strong>Щит:</strong> пластиковый, с запасом мест на 2-3 автомата больше, чем нужно;</li>
        <li><strong>Розетки:</strong> с защитными шторками, на кухне и в ванной — влагозащищённые IP44.</li>
    </ul>
    <div data-type="box" data-color="red">
        <h3>Красный флаг</h3>
        <p>Алюминиевый провод — в домах старше 20 лет. Оксидируется, греется, пожароопасен. Только медный.</p>
    </div>
</section>

<section id="stage4">
    <h2>Этап 4: Чек-лист приёмки электрики</h2>
    <ul>
        <li>☐ Все розетки работают — проверены тестером;</li>
        <li>☐ Автоматы отключаются при коротком замыкании (тест кнопкой «TEST»);</li>
        <li>☐ УЗО срабатывает при утечке тока;</li>
        <li>☐ Никаких скруток — только клеммы Wago или сварка/пайка;</li>
        <li>☐ Кабель не лежит поверх штукатурки — в штробе или коробе;</li>
        <li>☐ Розетки на кухне — отдельная линия 2,5 мм², не общая с комнатами;</li>
        <li>☐ В ванной — розетки с IP44, на отдельном УЗО.</li>
    </ul>
</section>

<section id="stage5">
    <h2>Этап 5: 5 признаков, что проводку нужно менять</h2>
    <ul>
        <li>Автоматы выбиваются при включении нескольких приборов;</li>
        <li>Розетки и выключатели греются или искрят;</li>
        <li>Свет моргает без причины;</li>
        <li>Запах горелого près щитка или розеток;</li>
        <li>Дом старше 25 лет, проводка алюминиевая (не менялась).</li>
    </ul>
</section>

