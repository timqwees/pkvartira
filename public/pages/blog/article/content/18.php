<section id="stage3">
    <h2>Этап 3: Что входит в каждую цену</h2>
    <div data-type="compare">
        <h3>Косметический vs Капитальный</h3>
        <article data-variant="good">
            <h4>Косметический 8 000 ₽/м²</h4>
            <p>Демонтаж обоев, грунтовка, шпаклёвка 1 слой, покраска 2 слоя, ламинат на подложку, натяжной потолок, розетки. Без стяжки и штукатурки. Подходит, если стены ровные.</p>
        </article>
        <article data-variant="bad">
            <h4>Капитальный 13 000 ₽/м²</h4>
            <p>Всё из kosметического + демонтаж, штукатурка по маякам, стяжка 50 мм, электрика 35 точек, сантехника (Rehau), гидроизоляция. Для вторички и бетона.</p>
        </article>
    </div>
    <p>Дизайнерский + дизайн-проект, премиум-материалы, скрытые двери, теневые швы — +5 000 ₽/м² к капитальному.</p>
</section>

<section id="stage4">
    <h2>Этап 4: Наценка по типу дома</h2>
    <ul>
        <li><strong>Панелька (хрущевка/брежневка):</strong> +5% — кривые стены, тонкие перегородки, надо штробить аккуратно;</li>
        <li><strong>Монолит/кирпич:</strong> база — ровнее, но штробление бетона дороже +7%;</li>
        <li><strong>Сталинка:</strong> +10% — высокие потолки 3,2 м, лепнина, паркет, мусор;</li>
        <li><strong>Новостройка бетон:</strong> −5% — нет демонтажа, но стяжка и штукатурка с нуля.</li>
    </ul>
</section>

<section id="stage5">
    <h2>Этап 5: Где сэкономить 15% без потери качества</h2>
    <ul>
        <li>Черновые — не экономьте (Ротбанд, ВВГнг). Чистовые — экономьте (Cersanit vs Italon — минус 40%);</li>
        <li>Делайте «под ключ» одной бригадой — дешевле на 15% чем по-отделочке;</li>
        <li>Закупайте материалы через подрядчика со скидкой 12% — отдаем вам;</li>
        <li>Не платите за «дизайн-проект» если не нужен — базовая планировка у нас бесплатно.</li>
    </ul>
