<section id="stage1">
    <h2>Этап 1: Особенности сталинки — что учитывать</h2>
    <ul>
        <li><strong>Потолки 3,2-3,5 м</strong> — пространство, но нужно больше материалов и сил;</li>
        <li><strong>Кирпичные стены</strong> — тёплые, ровные, но толстые (до 60 см);</li>
        <li><strong>Лепнина на потолках и стенах</strong> — историческая ценность, реставрация или аккуратное обход;</li>
        <li><strong>Паркетная доска</strong> — можно отцикловать и покрыть лаком;</li>
        <li><strong>Высокие дверные проёмы</strong> — нестандартные размеры дверей;</li>
        <li><strong>Старые коммуникации</strong> — электрика, сантехника, отопление требуют замены;</li>
        <li><strong>Перекрытия междуэтажные</strong> — бетонные или железобетонные, прочные.</li>
    </ul>
