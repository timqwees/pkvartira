<section id="stage3">
    <h2>Этап 3: Сохранение лепнины и паркета — рекомендации</h2>
    <div data-type="compare">
        <h3>Реставрировать vs Заменить</h3>
        <article data-variant="good">
            <h4>Реставрировать</h4>
            <p>Лепнина на потолке — очистка, зачистка, окраска; паркет — циклевка, лак; старинные двери — реставрация фурнитуры.</p>
        </article>
        <article data-variant="bad">
            <h4>Заменить</h4>
            <p>Если лепнина разрушена на 70%+, паркет гнилый — заменяем на аналогичные по стилю материалы.</p>
        </article>
    </div>
    <ul>
        <li><strong>Лепнина:</strong> аккуратное обход при прокладке коммуникаций, реставрация специалистами;</li>
        <li><strong>Паркет:</strong> циклевка без удаления více чем 1 мм слоя дерева;</li>
        <li><strong>Двери:</strong> подбор под старинные проёмы или изготовление на заказ.</li>
    </ul>
</section>

<section id="stage4">
    <h2>Этап 4: Этапы ремонта сталинки под ключ</h2>
    <ul>
        <li><strong>1. Замер и проект</strong> — учёт нестандартных размеров, лепнины, высоты (3-5 дней);</li>
        <li><strong>2. Демонтаж</strong> — старые покрытия, при сохранении лепнины и паркета аккуратно (3-5 дней);</li>
        <li><strong>3. Реставрация лепнины и паркета</strong> — очистка, окраска, циклевка (5-10 дней);</li>
        <li><strong>4. Электрика и сантехника</strong> — замена на современные (7-10 дней);</li>
        <li><strong>5. Стены и потолки</strong> — штукатурка, шпаклёвка, покраска с учётом лепнины (8-14 дней);</li>
        <li><strong>6. Пол</strong> — стяжка или ремонт паркета (5-10 дней + сушка);</li>
        <li><strong>7. Окна и двери</strong> — подбор под высокие проёмы (2-3 дня);</li>
        <li><strong>8. Финальная уборка</strong> (1-2 дня).</li>
    </ul>
    <p>Общий срок: 6-12 недель.</p>
</section>

<section id="stage5">
    <h2>Этап 5: 5 ошибок при ремонте сталинки</h2>
    <div data-type="compare">
        <h3>Ошибка vs Правильно</h3>
        <article data-variant="bad">
            <h4>Ошибка</h4>
            <p>1. Демонтаж лепнины без попытки реставрации — теряем историческую ценность;<br>
            2. Низкие двери в высокие проёмы — визуально уменьшают пространство;<br>
            3. Экономия на электрике — старая проводка не выдерживает нагрузку;<br>
            4. Ламинат вместо паркета — теряем дух сталинки и стоимость;<br>
            5. Штукатурка потолка без учёта лепнины — портят декоративные элементы.</p>
        </article>
        <article data-variant="good">
            <h4>Правильно</h4>
            <p>Реставрация лепнины, высокие двери, новая электрика, паркет или аналоги, аккуратная работа с декоративными элементами.</p>
        </article>
    </div>
</section>

