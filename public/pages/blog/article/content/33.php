<section id="stage2">
    <h2>Этап 2: Натуральные материалы — что выбрать</h2>
    <ul>
        <li><strong>Стены:</strong> глина, известь,	glina, казеиновые краски — дышат, не накапливают статику;</li>
        <li><strong>Пол:</strong> массив дуба/ясеня, пробковое покрытие, линолеум на натуральной основе (не ПВХ);</li>
        <li><strong>Мебель:</strong> массив дерева без ламинатной плёнки, мебельная фанера ФК (низкий формальдегид);</li>
        <li><strong>Клей:</strong> на клееве basis (крахмал, казеин), не на растворителях;</li>
        <li><strong>Затирка:</strong> на цементной основе без эпоксидных смол.</li>
    </ul>
    <div data-type="box" data-color="gray">
        <h3>Маркировка, на которую смотреть</h3>
        <p>ECO Label, Blue Engel, Nordic Swan, E1 (для ДСП — минимальный формальдегид). Сертификаты проверяем у продавца.</p>
    </div>
</section>

<section id="stage3">
    <h2>Этап 3: От чего отказаться — список вредных материалов</h2>
    <div data-type="box" data-color="red">
        <h3>Не использовать</h3>
        <p>• Ламинат высокой плотности с формальдегидом выше E1;<br>
        • ПВХ-пленка натяжных потолков в спальне (фенол при нагреве);<br>
        • Клеи на основе растворителей (толуол, ксилол);<br>
        • Акриловые краски с летучими органическими соединениями (ЛОС) > 50 г/л;<br>
        • Пенополистирол (п penoplex) внутри жилых помещений без вентиляции;<br>
        • ДСП и ЛДСП класса E2/E3 — высокий формальдегид.</p>
    </div>
</section>

