<section id="stage5">
    <h2>Этап 5: 5 ошибок при эко-ремонте</h2>
    <div data-type="compare">
        <h3>Ошибка vs Правильно</h3>
        <article data-variant="bad">
            <h4>Ошибка</h4>
            <p>1. «Эко» ламинат без сертификата — маркетинг, формальдегид остался;<br>
            2. Натяжной потолок в детской — ПВХ выделяет вещества при нагреве;<br>
            3. Экономия на вентиляции — натуральные материалы нуждаются в воздухообмене;<br>
            4. Краска без сертификата — «акриловая» с ЛОС выше нормы;<br>
            5. Пробковое покрытие без защитного слоя — стирается за год.</p>
        </article>
        <article data-variant="good">
            <h4>Правильно</h4>
            <p>Сертифицированные материалы, деревянные окна, массив, вентиляция, защитные слои, проветривание после ремонта.</p>
