<section>
    <h2>Подводные камни (чек-лист при заказе)</h2>
    <ol>
        <li><strong>Замер:</strong> Только после завершения черновика (штукатурка стен). Замерщик — от производителя/дилера, НЕ от монтажной бригады.</li>
        <li><strong>Демонтаж старых рам:</strong> Кто вывозит мусор? (должна быть монтажная бригада). Куда вывозить? (мусоропровод/контейнер).</li>
        <li><strong>Согласование перепланировки:</strong> Если объединяете балкон с комнатой (сносите дверь/окно) — нужно согласование в Мосжилинспекции (проект, акт скрытых работ). Без согласования — штраф + привод к исходному виду.</li>
        <li><strong>Цвет ламинации:</strong> Смотрите образец ВЖИВУЮ (на солнце/в тени), а не в каталоге. Белый жёлтеет на солнце через 5–7 лет (качественный — через 15+).</li>
        <li><strong>Подоконники:</strong> ПВХ (дешёвый, жёлтеет) / МДФ ламинированный (тёплый, цвет под пол) / Камень (агломерат/кварц — дорогой, вечный, холодный).</li>
        <li><strong>Откосы:</strong> Пенопласт 50 мм + штукатурка (бюджет) / Гипсокартон влагоустойчивый + шпаклевка (стандарт) / Сандвич-панели ПВХ (быстро, тёпло, не трескаются).</li>
        <li><strong>Гарантия:</strong> 5 лет на монтаж (герметичность, работа фурнитуры, откосы), 10 лет на профиль/стеклопакет (пrosaчество газа, разделёк). Читайте мелкий шрифт: что НЕ входит (удар, хим. воздействие, неправильная эксплуатация).</li>
        <li><strong>Приёмка:</strong> Проверьте: створка закрывается без усилий, микровентиляция работает, нет сквозняков (свеча/запальная спичка), откосы ровные/без щёлок, подоконник с наклоном наружу, фурнитура не царапается, пена не видна (подрезана/заштукатурена). Подписывайте акт только после проверки.</li>
    </ol>
</section>