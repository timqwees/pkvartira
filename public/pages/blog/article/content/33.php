<section>
    <h2>Стеклопакеты: формула «3 камеры + 2 i-покрытия + аргон»</h2>
    <p>Стандарт 2026: <strong>4M2-16Ar-4M2-16Ar-4M2</strong> (3 камеры, 2 стекла с i-покрытием, аргон в камерах). Коэффициент теплопередачи Rо >0.75 м²К/Вт (СПб/Москва требует >0.70).</p>
    <ul>
        <li><strong>i-покрытие (Low-E):</strong> Невидимый металлический слой, отражает ИК-тепло обратно в комнату. 2 стекла с покрытием = 2× эффективнее.</li>
        <li><strong>Аргон:</strong> Инертный газ, теплопроводность в 1.4 раза ниже воздуха. Не выходит (герметичность 99% за 10 лет).</li>
        <li><strong>Мультифункциональное стекло (SunGuard, Guardian, Saint-Gobain):</strong> i-покрытие + солнцезащита (отражает 60–70% солнечной энергии). Обязательно для южных фасадов, панорам, верхних этажей.</li>
        <li><strong>Триплекс (33.1 / 44.2):</strong> 2 стекла + плёнка между ними. Безопасность (не разлетается), шумоизоляция +3–5 дБ. Для 1–2 этажей, детских, панорам.</li>
    </ul>
    <p><strong>Формула заказа:</strong> Профиль (бренд, серия, цвет) + Стеклопакет (формула, толщина стекол, газ, покрытия) + Фурнитура (бренд, микровентиляция, детский замок) + Цвет (белый / ламинация под дерево / RAL) + Откосы (пенопласт/гипсокартон/сандвич-панели) + Подоконник (ПВХ/камень/МДФ) + Монтаж (пена/пена+клей, анкерное крепление, пароизоляция).</p>
</section>

<section>
    <h2>Фурнитура: невидимый герой</h2>
    <p>Рукоятка, петли, замки, микровентиляция, детский замок, привод для моторизации. Бренды: <strong>Roto NT</strong> (стандарт, надёжность), <strong>Maco Multi-Matic</strong> (плавность, регулировка), <strong>Siegenia TITAN</strong> (жёсткость, защита от взлома RC2).</p>
    <ul>
        <li><strong>Микровентиляция (щель 5–10 мм):</strong> Обязательно для спален — проветривание без сквозняка и холода.</li>
        <li><strong>Детский замок на рукоятке:</strong> Обязательно для детских комнат.</li>
        <li><strong>Антивзломный пакет (RC2):</strong> Усиленные замочные штыри, закаленные пластины под рукояткой, закладки «гриф-блок». Для 1–2 этажей, панорам.</li>
        <li><strong>Моторизация (Somfy, Roto E-Tec):</strong> Управление пультом/приложением, датчик дождя/ветра. Для высоких/труднодоступных окон.</li>
    </ul>
</section>

