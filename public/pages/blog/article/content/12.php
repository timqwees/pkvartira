<section id="stage2">
    <h2>Этап 2: Умный дом — что реально нужно в 2026</h2>
    <p>Технологии перестали быть игрушкой. В 2026 году умный дом — это практичные решения, которые экономят время и деньги:</p>
    <ul>
        <li><strong>Датчики протечки воды</strong> — самые востребованные. Стоят 3000–8000 ₽ за комплект, перекрывают воду автоматически при аварии;</li>
        <li><strong>Умные замки</strong> — открытие по отпечатку пальца или коду. Удобно для семьи и сдачи квартиры посуточно;</li>
        <li><strong>Свет с управлением</strong> — сценарии «Утро», «Кино», «Ночь» меняют яркость и температуру освещения;</li>
        <li><strong>Роботы-пылесосы</strong> — в 2026 году норма иметь автоуборку. Планируйте розетки и свободное пространство под базовую станцию.</li>
    </ul>
    <div data-type="box" data-color="dark">
        <h3>Важно</h3>
        <p>Всю «умную» проводку закладывайте на этапе черновой отделки. Проложить кабель к датчикам после ремонта — значит штробить свежие стены. Планируйте ниши для блоков управления заранее.</p>
    </div>
</section>

<section id="stage3">
    <h2>Этап 3: Экоматериалы и осознанный подход</h2>
    <p>В 2026 году экологичность — не маркетинг, а осознанный выбор. Покупатели всё чаще обращают внимание на состав красок, клеев и покрытий. Материалы с низким содержанием летучих органических соединений становятся стандартом.</p>
    <p>Гипоаллергенные покрытия, натуральные масла для дерева, водные лаки — это не только безопасно, но и долговечно. Пробковые полы и стены возвращаются как шумоизоляционное и экологичное решение.</p>
