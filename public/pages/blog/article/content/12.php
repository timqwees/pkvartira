<section id="stage4">
    <h2>Этап 4: Цветовая гамма и акценты</h2>
    <p>Чистый минимализм отходит на второй план. В 2026 году интерьеры становятся теплее и выразительнее. Базовая палитра — молочные, нюдовые и песочные оттенки. Акцентные цвета — терракотовый, оливковый, глубокий синий и приглушённый оранжевый.</p>
    <p>Текстиль с принтами, мебель необычных форм, арки и ниши с подсветкой — всё это добавляет интерьеру характера. Главное правило: один яркий акцент на комнату, чтобы не перегрузить пространство.</p>
    <div data-type="box" data-color="blue">
        <h3>Идея для вдохновения</h3>
        <p>Попробуйте сочетание: молочные стены + терракотовый текстиль + деревянная мебель + оливковые акценты в декоре. Такая палитра выглядит дорого, уютно и точно не устареет через год.</p>
    </div>
</section>

