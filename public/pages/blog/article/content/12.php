<section id="stage1">
    <h2>Этап 1: Природные фактуры — бетон, дерево, камень, терракота</h2>
    <p>Главный тренд 2026 года — тактильность. Люди устали от стерильных глянцевых поверхностей и возвращаются к природным текстурам. В отделке стен набирают популярность декоративная штукатурка с эффектом бетона и микроцемент. Дерево используется не только для пола — им отделывают акцентные стены, потолки и даже мебель.</p>
    <p>Камень (натуральный или агломерат) появляется на кухонных столешницах, в ванных комнатах и на фасадах шкафов. Терракотовая плитка переживает второе рождение — её используют в прихожих, на кухнях и в зонах барбекю на балконах.</p>
