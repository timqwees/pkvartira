    <h2>Цветовая гамма и акценты</h2>
    <p>Чистый минимализм отходит на второй план. В 2026 году интерьеры становятся теплее и выразительнее. Базовая палитра — молочные, нюдовые и песочные оттенки. Акцентные цвета — терракотовый, оливковый, глубокий синий и приглушённый оранжевый.</p>
