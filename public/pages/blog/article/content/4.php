<section id="stage3">
    <h2>Этап 3: Экосистемы — Яндекс vs Apple vs Home Assistant</h2>
    <p>Разрозненные устройства от разных брендов — это не умный дом, а зоопарк. Три основных экосистемы 2026:</p>
    <ul>
        <li><strong>Яндекс.Алиса</strong> — самая популярная в России. Совместима с Xiaomi, Philips, Tuya. Подходит для 90% задач;</li>
        <li><strong>Apple HomeKit</strong> — для фанатов Apple. Закрытая, но безопасная;</li>
        <li><strong>Home Assistant</strong> — open-source для гиков. Объединяет любые устройства, но требует настройки.</li>
    </ul>
    <div data-type="box" data-color="gray">
        <h3>Совет новичкам</h3>
        <p>Начинайте с одной экосистемы (рекомендуем Яндекс). Покупайте устройства с логотипом «Работает с Алисой» — они гарантированно дружат между собой.</p>
    </div>
