<section id="stage4">
    <h2>Этап 4: Этапы ремонта под аренду</h2>
    <ul>
        <li><strong>1. Оценка</strong> — что нужно обновить (1 день);</li>
        <li><strong>2. Демонтаж</strong> — старые обои, плинтусы (1 день);</li>
        <li><strong>3. Стены и потолок</strong> — шпаклёвка, моющиеся обои (4-6 дней);</li>
        <li><strong>4. Пол</strong> — ламинат или линолеум, плинтусы (2-3 дня);</li>
        <li><strong>5. Сантехника и электрика</strong> — ремонт течи, новые розетки (1-2 дня);</li>
        <li><strong>6. Мебель и техника</strong> — доставка и сборка (2-3 дня);</li>
        <li><strong>7. Генеральная уборка</strong> (1 день).</li>
    </ul>
    <p>Общий срок: 2-3 недели.</p>
</section>

<section id="stage5">
    <h2>Этап 5: 5 ошибок при ремонте под сдачу</h2>
    <div data-type="compare">
        <h3>Ошибка vs Правильно</h3>
        <article data-variant="bad">
            <h4>Ошибка</h4>
            <p>1. Дорогая мебель и техника — арендаторы могут испортить;<br>
            2. Светлые ковры и textiles — быстро загрязняются;<br>
            3. Нет стиральной машины — арендаторы уходят;<br>
            4. Старая сантехника с течью — жалобы и скидки;<br>
            5. Светлые шторы на кухне — впитывают запахи готовки.</p>
        </article>
        <article data-variant="good">
            <h4>Правильно</h4>
            <p>Практичная мебель, тёмные текстильные покрытия, стиральная машина обязательно, рабочая сантехника, тканевые шторы без светлых оттенков на кухне.</p>
        </article>
    </div>
