<section>
    <h2>Почему пластиковые окна «убили» вентиляцию</h2>
    <p>Герметичные окна + входная металлическая дверь = замкнутый объём. CO₂ в спальне к утру 1500–2500 ppm (норма <800), влажность 60–70% → плесень в углах, конденсат на окнах, аллергии, сонливость днём. Естественная вентиляция через щели больше не работает. В 2026 году решение — принудительная вентиляция с рекуперацией тепла. Сравниваем 3 класса решений.</p>
</section>

<section>
    <h2>Бризеры: простота монтажа, автономность</h2>
    <p>Компактный прибор в стене (отверстие 100–130 мм), втягивает уличный воздух, фильтрует (G4 + F7 + HEPA опционально), обогревает керамическим/ПЭН элементом до комфортной температуры, подаёт в комнату. Вытяжка работает через естественные вентиляционные каналы (кухня/санузел) или парный бризер.</p>
    <p><strong>Плюсы:</strong> Монтаж 2–3 часа, не нужен проект вентиляции, не требует воздуховодов, управление пультом/приложением, компактен.</p>
    <p><strong>Минусы:</strong> Обслуживает 1 комнату (нужен в каждой спальне/гостиной), расход электричества на обогрев (0.5–1.5 кВт), шум 30–40 дБ (на мин. скорости тихо), фильтры менять раз в 3–6 мес.</p>
    <p><strong>Бренды 2026:</strong> <em>Tion 3S/4S</em> (18–25 тыс. ₽ + монтаж 5–8 тыс.), <em>Ballu BAX-ECO</em> (12–18 тыс. ₽), <em>Vents Mikra</em> (15–22 тыс. ₽), <em>Airnanny A7</em> (25–30 тыс. ₽ — с CO₂ датчиком и рекуперацией).</p>
    <p><strong>Цена «под ключ» за квартиру 60 м² (3 спальни + гостиная):</strong> 4 бризера × 20 тыс. + монтаж 4×6 тыс. = ~104 000 ₽.</p>
</section>

<section>
    <h2>Рекуператоры: эффективность 85–95%, центральная система</h2>
    <p>Блок в потолке/на балконе/в кладовке, сеть воздуховодов (прямоугольные/круглые Ø125–200 мм) ко всем комнатам. Приточка в жилые (спальни, гостиная), вытяжка из мокрых (кухня, санузлы, прихожая). Тепло от вытяжки передаётся приточному воздуху через пластинчатый/роторный рекуператор (эффективность 85–95%). Зимой приток +18...+20°C при -25°C за окном.</p>
    <p><strong>Плюсы:</strong> Вентиляция всей квартиры одной системой, высокая эффективность (экономия на отоплении 30–40%), тишина (блок в нежилом помещении), фильтрация всего воздуха, контроль влажности/CO₂, летом байпас (охлаждение ночным воздухом).</p>
    <p><strong>Минусы:</strong> Нужен проект, монтаж 2–3 дня, воздуховоды снижают потолки на 10–15 см (коробки/пеньки), цена выше, обслуживание фильтров раз в 3–6 мес.</p>
    <p><strong>Бренды:</strong> <em>Mitsubishi Lossnay VL-100/220</em> (85–120 тыс. ₽), <em>Systemair SAVE VTC</em> (60–100 тыс. ₽), <em>Vents VUT R</em> (40–70 тыс. ₽), <em>Blauberg KOMFORT</em> (35–60 тыс. ₽).</p>
    <p><strong>Цена «под ключ» за 60 м²:</strong> Блок 60 тыс. + воздуховоды 40 тыс. + монтаж 50 тыс. + проектирование 15 тыс. = ~165 000 ₽.</p>
</section>

<section>
    <h2>Вентиляционные клапаны на окнах: бюджетный вход</h2>
    <p>Устанавливаются в раму окна (сверху или сбоку), работают за счёт разности давлений/температур. Не требуют электричества. Классические (KIV-125, Aereco) — просто отверстие с клапаном. С гигростатом — открываются при влажности >60%. С рекуперацией (тепла нет, просто меньше замораживания).</p>
    <p><strong>Плюсы:</strong> Дешево (1.5–4 тыс. ₽/шт. с монтажом), быстро, невидимы, без электричества.</p>
    <p><strong>Минусы:</strong> Нет обогрева (зимой холодный приток), нет фильтрации (пыль, пух, шум улицы), зависят от ветра/температуры, в сильные морозы замерзают/не работают, не закрывают потребность в вентиляции полностью.</p>
    <p><strong>Цена за 4 окна:</strong> ~10 000 ₽. Подходит как дополнение к бризерам/рекуператорам или для бюджетного варианта.</p>
</section>

