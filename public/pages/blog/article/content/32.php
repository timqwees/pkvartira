<section>
    <h2>Схемы для типовых квартир</h2>
    <ul>
        <li><strong>1-комнатная (35–45 м²):</strong> 1 бризер в спальне/гостиной + клапан на кухне/в санузле. ИТОГО: ~30 000 ₽.</li>
        <li><strong>2-комнатная (50–60 м²):</strong> 2 бризера (спальня + гостиная) + клапан на кухне/санузле. Или 1 рекуператор (если бюджет позволяет). ИТОГО: 60–100 тыс. ₽ / 160 тыс. ₽.</li>
        <li><strong>3-комнатная (70–90 м²):</strong> 3 бризера (каждая спальня + гостиная) или рекуператор. ИТОГО: 90–130 тыс. ₽ / 180–220 тыс. ₽.</li>
        <li><strong>Студия:</strong> 1 бризер (зона сна) + мощная вытяжка на кухне + клапан в санузле. Важно: зонирование притока/вытяжки.</li>
    </ul>
</section>

<section>
    <h2>Эксплуатация: фильтры, настройки, лайфхаки</h2>
    <ul>
        <li>Фильтры G4 (грубая) — менять раз в 3 мес. (промыть/пропылесосить). F7 (тонкая) — раз в 6 мес. (заменить). HEPA — раз в 12 мес.</li>
        <li>Зимой: ставьте температуру притока +18...+20°C, скорость 30–50%. Летом: байпас (обход рекуператора) + ночная проветриваемость.</li>
        <li>CO₂ датчик (встроенный или отдельный Xiaomi/Aqara 1500 ₽) — цель <800 ppm в спальне к утру.</li>
        <li>Влажность 40–60% — если >65% включайте вытяжку/бризер на макс., <35% — увлажнитель (зимой).</li>
        <li>Лайфхак: Запланируйте замену фильтров на сезонные часы (март/сентябрь) — совпадает с часовым поясом.</li>
    </ul>
</section>