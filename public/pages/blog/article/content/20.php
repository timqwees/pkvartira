        <li>Комната 15 м² (стены 35 м²) — <strong>~210 000 ₽</strong> под ключ.</li>
    </ul>
    <p>Цена без чистовой отделки. Сравните с ценами на ремонт — шумоизоляция = +30% к капитальному.</p>
