<section id="noise">
    <h2>Что шумит в панельке: виды шума</h2>
    <p>Панель — самый громкий тип дома. 3 вида шума:</p>
    <ul>
        <li><strong>Воздушный</strong> (речь, ТВ, музыка) — 30–45 дБ. Решается обшивкой 50–80 мм.</li>
        <li><strong>Ударный</strong> (топот, падение) — 60–75 дБ. Только через пол/потолок соседа. Ваша изоляция потолка даст -8 дБ максимум.</li>
        <li><strong>Структурный</strong> (перфоратор, лифт) — идет по бетону. Поможет только комплекс: стены+потолок+пол.</li>
    </ul>
    <div data-type="box" data-color="yellow">
        <h3>Важно</h3>
        <p>Тонкая «шумоизоляция» 10 мм из Леруа (подложка, пробка) — маркетинг. Реальная прибавка — 2–3 дБ, ухо не заметит. Нужна масса + развязка.</p>
    </div>
</section>

