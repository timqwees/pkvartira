<section id="stage5">
    <h2>Этап 5: 5 ошибок, которые убивают эффект</h2>
    <div data-type="compare">
        <h3>Ошибка vs Правильно</h3>
        <article data-variant="bad">
            <h4>Ошибка</h4>
            <p>1. Розетка сквозная — дыра в шумоизоляции (−5 дБ);<br>
            2. Жесткое крепление профиля к стене — звук по металлу;<br>
            3. Щель 1 мм по периметру — весь эффект в щель;<br>
            4. Один слой ГКЛ — надо 2 с разбежкой швов;<br>
            5. Пена вместо герметика — со временем трескается.</p>
        </article>
        <article data-variant="good">
            <h4>Правильно</h4>
            <p>Накладные розетки, виброподвесы/лента, герметик Вибросил по периметру, 2×ГКЛ 12,5 мм, акустический герметик. Каждый стык — герметично.</p>
        </article>
    </div>
    <div data-type="box" data-color="red">
        <h3>Тест</h3>
        <p>После монтажа — тест шумомером: до 62 дБ, после 45 дБ = −17 дБ (речь не слышна). Требуйте протокол.</p>
    </div>
</section>

