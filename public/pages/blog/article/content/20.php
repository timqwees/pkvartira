<section id="stage3">
    <h2>Этап 3: Схемы монтажа</h2>
    <p><strong>Стена (ЗИПС):</strong> стена → виброузлы → ЗИПС-панель → ГКЛ 12,5 мм → шпаклевка. Без каркаса, толщина 42 мм, быстро. Важно: герметик по периметру, не крепить розетки сквозняком.</p>
    <p><strong>Потолок:</strong> плита → виброподвесы → профиль → Шуманет → ГКЛ 2 слоя. Теряете 80 мм высоты, но топот сверху −12 дБ.</p>
    <p><strong>Пол:</strong> плита → СтопЗвук → стяжка 60 мм (плавающая, без связи со стенами) → подложка → ламинат. Лента по периметру обязательна.</p>
    <div data-type="box" data-color="blue">
        <h3>Где заказать?</h3>
        <p>Делаем шумоизоляцию под ключ от 4 900 ₽/м² с замером шума до/после шумомером.</p>
