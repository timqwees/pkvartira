<section id="stage2">
    <h2>Этап 2: Этапы ремонта балкона под ключ</h2>
    <ul>
        <li><strong>1. Остекление</strong> — рамы, стеклопакеты, отлив (1-2 дня);</li>
        <li><strong>2. Утепление</strong> — пол, стены, потолок пеноплексом или минеральной ватой (2-3 дня);</li>
        <li><strong>3. Гидроизоляция</strong> — пол и примыкания к стенам (1 день);</li>
        <li><strong>4. Стяжка пола</strong> — тёплый пол или обычная (3-5 дней + сушка);</li>
        <li><strong>5. Отделка стен и потолка</strong> — пластиковые панели, вагонка, штукатурка (2-3 дня);</li>
        <li><strong>6. Электрика</strong> — розетки, освещение, выключатель (1 день);</li>
        <li><strong>7. Мебель и аксессуары</strong> — шкаф, полки, сушилка (1 день).</li>
    </ul>
    <p>Общий срок: 10-18 дней в зависимости от объёма.</p>
</section>

<section id="stage3">
    <h2>Этап 3: Что можно, а что запрещено на балконе</h2>
    <div data-type="compare">
        <h3>Можно vs Запрещено</h3>
        <article data-variant="good">
            <h4>Можно</h4>
            <p>Остекление, утепление, отделка, электрика, тёплый пол (электрический), мебель, шкаф-купе, сушилка для белья.</p>
