<section id="stage4">
    <h2>Этап 4: Чек-лист приёмки балкона</h2>
    <ul>
        <li>☐ Окна открываются/закрываются плотно, нет дутья;</li>
        <li>☐ Отлив установлен, вода не затекает под раму;</li>
        <li>☐ Пол утеплён, нет холодных зон;</li>
        <li>☐ Розетки работают, автомат в щите не выбивается;</li>
        <li>☐ Нет щелей между стенами и окном;</li>
        <li>☐ При дожде нет течи под окном и по углам;</li>
        <li>☐ Мебель не касается окон и не мешает их открыванию.</li>
    </ul>
</section>

<section id="stage5">
    <h2>Этап 5: 5 ошибок, которые ведут к протечке</h2>
    <div data-type="compare">
        <h3>Ошибка vs Правильно</h3>
        <article data-variant="bad">
            <h4>Ошибка</h4>
            <p>1. Отлив установлен под углом к комнате — вода затекает внутрь;<br>
            2. Шов между рамой и проемом не замазан герметиком — продув;<br>
            3. Гидроизоляция только на полу, не заведена на стены — протечка внизу;<br>
            4. Кондиционер без дренажа — вода стекает по фасаду;<br>
            5. Утепление без пароизоляции — конденсат, плесень на стенах.</p>
        </article>
        <article data-variant="good">
            <h4>Правильно</h4>
            <p>Отлив с уклоном от комнаты, герметик по периметру, гидроизоляция пол+стены, дренаж кондиционера, пароизоляция под утеплителем.</p>
        </article>
    </div>
</section>

