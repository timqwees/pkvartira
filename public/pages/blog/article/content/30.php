<section>
    <h2>Хранение — не коробки, а система</h2>
    <p>В 2026 году главный тренд — невидимое хранение. Гардеробная за смежными дверями, прихожая с вертикальным каркасом, ниша под стирку/сушилку/пылесос, кухонные шкафы до потолка с лифтами. Главная ошибка — покупать мебель «под вещи», а не проектировать хранение под сценарии жизни. Разбираем по зонам.</p>
</section>

<section>
    <h2>Гардеробная: от 1.5 м² до отдельной комнаты</h2>
    <p><strong>Минимум (1.5–2 м²):</strong> Угловая схема — штанга + 2 полки + ящик для белья. Каркас: Elfa / IKEA Boaxel / металлопрофиль (5–8 тыс. ₽/м пог.) или ЛДСП/МДФ кастом (12–18 тыс. ₽/м пог.).</p>
    <p><strong>Стандарт (3–4 м²):</strong> П-образная: штанги по бокам (длинная/короткая), полки посередине, верхние секции для сезонного, ящики для белья/носков, полка для обуви снизу. Дверь: раздвижная (экономит место) или распашная с зажимом (герметичнее).</p>
    <p><strong>Максимум (5+ м²):</strong> Остров с ящиками/аксессуарами, зона проглаживания, зеркало в пол, встроенная доска для сумок/шапок. Вентиляция: зазор под дверью 15 мм + клапан в стене.</p>
    <p><strong>Эргономика:</strong> Штанга — 160–170 см от пола (для пальто/платьев), 105–110 см (для рубашек/брюк). Полки: глубина 40–45 см (верхние 30–35 см). Выкатные корзины — для нижних ярусов. Межсекционный зазор 3–5 см.</p>
</section>

<section>
    <h2>Прихожая: входная группа без хаоса</h2>
    <p><strong>Каркасные системы (Elfa, IKEA Boaxel, Raumplus, кастом):</strong> Вертикальные стойки в потолок/пол — вешают всё: штанги, полки, крючки, корзины, сушилки для обуви. Модульность — добавляете/убираете за 5 минут. Цена 5–12 тыс. ₽/м пог. (металл) / 12–20 тыс. ₽/м пог. (ЛДСП/МДФ под цвет стен).</p>
    <p><strong>Зонирование:</strong> Верх — шапки/перчатки/сезонное (корзины с подписями). Середина — верхняя одежда на штангах (длинная/короткая). Низ — обувь на наклонных полках/выкатных корзинах (вент. отверстия). У входа — крючки для сумок/ключей/ремней (на уровень глаз).</p>
    <p><strong>Скрытые фишки:</strong> Выкатная сушилка для обуви (электрическая/пассивная), встроенный пылесос (централизованный или робот-база), ниша для мокрой зонтики/ботинок (поддон + вентиляция).</p>
</section>

<section>
    <h2>Кухня: шкафы до потолка + лифты</h2>
    <p><strong>Верхние шкафы до потолка</strong> — +30% объёма, нет пыли сверху. Доступ: газ-лифты (поднимаются вверх, не мешают голове) или механизм «подъём-поворот» (серво-драйв). Бренды: Blum Aventos, Hettich, Grass.</p>
    <p><strong>Нижние шкафы:</strong> Только выкатные корзины (тяжёлые кастрюли, бытовая химия, запасы). Глубина 55–58 см, корзина на весь объём. Разделители для ножей/крышек/досок.</p>
    <p><strong>Угловые:</strong> Карусель (LeMans, Magic Corner) или выкатные полки-трансформеры. Не оставляйте «мёртвые зоны».</p>
    <p><strong>Пенопласт/органайзеры для посуды/приборов</strong> — стандарт в 2026 году. Вставляете в корзину — всё на месте.</p>
</section>

<section>
    <h2>Ниши и нестандартные зоны</h2>
    <ul>
        <li><strong>Под стиралкой/сушилкой:</strong> Шкаф-колонна (высота 185–220 см) — сверху полки для порошков/полотенец, сбоку выкатная корзина для грязного белья.</li>
        <li><strong>Под лестницей (если есть):</strong> Гардероб, кладовка, домашний офис, винный погреб.</li>
        <li><strong>Балкон/лоджия (утеплённая):</strong> Стеллажи для сезонного, велосипедов, инструментов. Полки 40×40 см, шаг 40 см.</li>
        <li><strong>Накладные ниши в стенах (толщина 120+ мм):</strong> Полки для книги/декора, встроенное зеркало, зарядная станция для гаджетов.</li>
    </ul>
</section>

