<section id="stage1">
    <h2>Этап 1: Приёмка у застройщика — чек-лист из 30 пунктов</h2>
    <p>Первый и самый важный этап. Приёмка занимает 1-2 дня и защищает от скрытых дефектов, которые дорого исправлять после ремонта.</p>
    <ul>
        <li>Проверка окон и входной двери;</li>
        <li>Измерение геометрии комнат (перепады стен и пола);</li>
        <li>Проверка электрики ( автоматы, розетки, освещение);</li>
        <li>Проверка сантехники ( universal, счётчики, трубы);</li>
        <li>Проверка вентиляции и дымоходов;</li>
        <li>Фотофиксация всех дефектов в акте приёмки.</li>
    </ul>
    <div data-type="box" data-color="blue">
        <h3>Срок: 1-2 дня</td>
        <p>Бесплатный выезд инженера для приёмки — входит в сервис Проект Квартира.</p>
    </div>
</section>

<section id="stage2">
    <h2>Этап 2: Проект и сметы — планировка и инженерные решения</h2>
    <ul>
        <li><strong>Планировка:</strong> расстановка мебели, зонирование, Location точек воды и электроники;</li>
        <li><strong>Электрический проект:</strong> розетки, выключатели, освещение, щиток, мощность;</li>
        <li><strong>Сантехнический проект:</strong> разводка труб, установка сантехники, тёплый пол;</li>
        <li><strong>Смета:</strong> детализация по работам и материалам с фиксированной ценой.</li>
    </ul>
    <div data-type="box" data-color="gray">
        <h3>Срок: 3-7 дней</td>
        <p>Проект позволяет избежать переделок и сэкономить до 15% бюджета.</p>
    </div>
</section>

<section id="stage3">
    <h2>Этап 3: Черновые работы — стяжка, штукатурка, электрика, сантехника</h2>
    <ul>
        <li><strong>Стяжка пола:</strong> цементно-песчаная М300, толщина 50-70 мм, сушка 28 дней;</li>
        <li><strong>Штукатурка стен:</strong> Ротбанд, выравнивание по маякам;</li>
        <li><strong>Электрика:</strong> кабель ВВГнг, розетки, автоматы, УЗО, щит;</li>
        <li><strong>Сантехника:</strong> трубы Rehau, счётчики, смесители, унитаз, раковина;</li>
        <li><strong>Гидроизоляция:</strong> санузел, кухня, балкон.</li>
    </ul>
    <div data-type="box" data-color="red">
        <h3>Красный флаг</h3>
        <p>Пропуск гидроизоляции в санузле — залив соседей и дорогой ремонт через год.</p>
    </div>
    <div data-type="box" data-color="blue">
        <h3>Срок: 2-4 недели + сушка стяжки до 28 дней</td>
        <p>Хождение по стяжке можно через 5-7 дней, укладку плитки — через 14.</p>
    </div>
</section>

<section id="stage4">
    <h2>Этап 4: Чистовая отделка — пол, стены, потолок, двери</h2>
    <ul>
        <li><strong>Пол:</strong> ламинат, керамогранит, паркет, плинтусы;</li>
        <li><strong>Стены:</strong> шпаклёвка, покраска или обои;</li>
        <li><strong>Потолок:</strong> штукатурка и покраска или натяжной;</li>
        <li><strong>Двери:</strong> межкомнатные и входная, фурнитура;</li>
        <li><strong>Освещение:</strong> люстры, бра, светодиодная подсветка.</li>
    </ul>
    <div data-type="box" data-color="gray">
        <h3>Срок: 2-4 недели</td>
        <p>Чистовые можно начинать только после полного высыхания черновых.</p>
    </div>
</section>

<section id="stage5">
    <h2>Этап 5: Финальная приёмка и сдача объекта</h2>
    <ul>
        <li>☐ Все розетки и выключатели работают;</li>
        <li>☐ Сантехника без течи, унитаз и раковина крепятся;</li>
        <li>☐ Двери открываются и закрываются без усилий;</li>
        <li>☐ Пол без трещин и вмятин;</li>
        <li>☐ Вентяляция работает, нет дутья от окон;</li>
        <li>☐ Генеральная уборка и вывоз мусора.</li>
    </ul>
    <div data-type="box" data-color="green">
        <h3>Готово к жизни</td>
        <p>Объект сдаётся с актом приёмки и гарантией 3 года на все работы.</p>
    </div>
</section>

