<section id="stage1">
    <h2>Этап 1: 5 вещей, которые обязательно менять во вторичке</h2>
    <div data-type="box" data-color="red">
        <h3>Обязательная замена</h3>
        <p>1. Электропроводка — алюминий на медь;<br>
        2. Сантехника — старые трубы и стояки;<br>
        3. Окна — однокамерные стеклопакеты;<br>
        4. Входная дверь — старые замки и коробка;<br>
        5. Пол — изношенная стяжка и покрытие.</p>
    </div>
    <p>Экономия на этих пяти пунктах — переплата в 30-50% через 2-3 года на аварийный ремонт.</p>
</section>

<section id="stage2">
    <h2>Этап 2: Электрика — замена алюминия на медь</h2>
    <p>В домах старше 20 лет проводка алюминиевая и выдерживает максимум 5 кВт. Современная техника (кондиционер, бойлер, посудомойка) сжигает её за 3-5 лет.</p>
    <ul>
        <li>Замена на кабель ВВГнг-LS 3×2,5 мм² для розеток;</li>
        <li>Замена на 3×1,5 мм² для освещения;</li>
        <li>Новый щиток с автоматикой и УЗО;</li>
        <li>Замена всех розеток и выключателей.</li>
    </ul>
    <div data-type="box" data-color="red">
        <h3>Красный флаг</h3>
        <p>Автоматы выбиваются при включении нескольких приборов — проводка не выдерживает нагрузку.</p>
    </div>
</section>

<section id="stage3">
    <h2>Этап 3: Сантехника — трубы, стояки, счётчики</h2>
    <ul>
        <li><strong>Трубы:</strong> замена чугунных и стальных труб на полипропилен или металлопластик;</li>
        <li><strong>Стоянки:</strong> замена общих стояков в санузле и на кухне;</li>
        <li><strong>Счётчики:</strong> установка новых приборов учёта воды;</li>
        <li><strong>Смесители и сантехника:</strong> замена изношенных унитаза, раковины, ванны.</li>
    </ul>
    <div data-type="box" data-color="blue">
        <h3>Срок службы</td>
        <p>Новые трубы служат 25-50 лет, старые чугунные — 15-20 лет и уже выработали ресурс.</p>
    </div>
</section>

<section id="stage4">
    <h2>Этап 4: Окна и входная дверь — тепло и безопасность</h2>
    <ul>
        <li><strong>Окна:</strong> замена однокамерных стеклопакетов на двухкамерные с энергосбережением;</li>
        <li><strong>Входная дверь:</strong> замена старой коробки и замков на современную с терморазрывом;</li>
        <li><strong>Уплотнение:</strong> замена уплотнителей на окнах и двери.</li>
    </ul>
    <div data-type="box" data-color="gray">
        <h3>Экономия на отоплении</td>
        <p>Новые окна и дверь снижают теплопотери на 15-25% и экономят до 5 000 ₽ в месяц зимой.</p>
    </div>
</section>

<section id="stage5">
    <h2>Этап 5: Пол — стяжка и чистовое покрытие</h2>
    <ul>
        <li><strong>Снятие старого покрытия:</strong> линолеум, паркет, плитка;</li>
        <li><strong>Новая стяжка:</strong> цементно-песчаная М300, толщина 50 мм;</li>
        <li><strong>Чистовое:</strong> ламинат, керамогранит, паркет или линолеум;</li>
        <li><strong>Плинтусы:</strong> установка новых.</li>
    </ul>
    <div data-type="box" data-color="red">
        <h3>Красный флаг</h3>
        <p>Укладка чистового пола на старую стяжку без выравнивания — волны и скрип через год.</p>
    </div>
</section>

<div data-type="box" data-color="blue" id="expert">
    <h3>Мнение эксперта Проект Квартира</h3>
    <p>Во вторичке главное — неconomить на скрытых коммуникациях. Электрика и сантехника скрыты под отделкой, и их замена после ремонта обойдётся в 2-3 раза дороже.</p>
