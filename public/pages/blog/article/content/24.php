<section id="faq">
    <h2>FAQ</h2>
    <div data-type="box" data-color="gray">
        <h3>Что обязательно менять при ремонте вторички?</h3>
        <p>Электрику — всегда: алюминий и скрутки в стенах 30+ лет не рассчитаны на современную нагрузку. Остальное — по состоянию: сантехника, стяжка и геометрия стен определяются на замере.</p>
    </div>
    <div data-type="box" data-color="gray">
        <h3>Можно ли не менять стяжку?</h3>
        <p>Да, если она плотная, без трещин и с перепадами до 2–3 мм. Тогда ламинат кладут прямо на неё с подложкой. Но проверьте простукиванием и осмотром трещин — по звуку и глубине.</p>
    </div>
    <div data-type="box" data-color="gray">
        <h3>Нужно ли согласовывать перепланировку во вторичке?</h3>
        <p>Если не меняете назначение помещений и не трогаете несущие конструкции — согласование не требуется. Перенос санузла, расширение проёма, объединение кухни с гостиной — нужно. Подробности: <a href="/blog/pereplanirovka-kvartiry-soglasovanie" style="color:#2563eb;font-weight:600;">что можно без согласования</a>.</p>
    </div>
    <div data-type="box" data-color="gray">
        <h3>Сколько длится ремонт вторичной квартиры?</h3>
        <p>Косметический — 14–21 день, капитальный — 35–50 дней для однокомнатной. С заменой электрики и сантехники и выравниванием стен — от 45 дней.</p>
    </div>
    <div data-type="box" data-color="gray">
        <h3>Стоит ли переплачивать за ремонт вторички перед продажей?</h3>
        <p>Как правило, нет: вложения в отделку сверх «косметики на выход» при продаже возвращаются не полностью. Разумнее вложиться в электрику, сантехнику и выравнивание стен — это то, что проверяют и покупатель, и оценщик.</p>
    </div>
    <div data-type="box" data-color="gray">
        <h3>Как понять, что квартира «убитая»?</h3>
        <p>Признаки: деревянные полы по лагам, штукатурка с отваливающимися слоями, старая проводка в пластиковых коробках 90-х, стояк чугунный с ржавчиной. Если два признака из трёх — считайте ремонт капитальным.</p>
    </div>
</section>
