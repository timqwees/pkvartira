<section id="stage2">
    <h2>Этап 2: Способы укладки — шов в шов, диагональ, елочка</h2>
    <ul>
        <li><strong>Шов в шов</strong> — классика, меньше отходов, быстрее укладывать, дешевле на 15%;</li>
        <li><strong>Диагональ</strong> — визуально расширяет пространство, больше отходов (до 15%), дороже;</li>
        <li><strong>Елочка (паркетная)</strong> — для керамогранита под дерево, сложная резка, дороже на 30%;</li>
        <li><strong>Кирпичом (смещение 1/2)</strong> — скрывает кривизну стен, выглядитmodern.</li>
    </ul>
    <div data-type="box" data-color="blue">
        <h3>Совет</h3>
        <p>Для маленькой ванной (до 5 м²) — шов в шов светлой плиткой. Диагональ «съедает» пространство визуально в узком помещении.</p>
    </div>
</section>

<section id="stage3">
    <h2>Этап 3: Материалы — клей, затирка, крестики</h2>
    <ul>
        <li><strong>Клей:</strong> Ceresit CM11 или Knauf Fliesen — для керамогранита и плитки, не экономить;</li>
        <li><strong>Затирка:</strong> эпоксидная для швов в ванной (не почернеет), цементная для сухих зон;</li>
        <li><strong>Крестики:</strong> 2-3 мм для пола, 1-2 мм для стен, обязательны для ровных швов;</li>
        <li><strong>Гидроизоляция:</strong> цементная масса под плитку в ванной и на кухне.</li>
    </ul>
    <div data-type="box" data-color="red">
        <h3>Красный флаг</h3>
        <p>Клей «Универсал» вместо специализированного для плитки — плитка отвалится через 1-2 года.</p>
    </div>
</section>

<section id="stage4">
    <h2>Этап 4: Чек-лист приёмки укладки плитки</h2>
    <ul>
        <li>☐ Швы ровные, одинаковой толщины (крестики убраны);</li>
        <li>☐ Плитка без сколов, трещин, царапин;</li>
        <li>☐ Нет пустот под плиткой — постукивание не даёт глухого звука;</li>
        <li>☐ Углы под 90°, плитка не «ведёт»;</li>
        <li>☐ Плинтус прилегает плотно, без зазоров;</li>
        <li>☐ Затирка без пустот и трещин, цвет равномерный;</li>
        <li>☐ Уклон пола к сифону в ванной — вода не стоит лужами.</li>
    </ul>
</section>

<section id="stage5">
    <h2>Этап 5: 5 ошибок, из-за которых плитка отваливается</h2>
    <div data-type="compare">
        <h3>Ошибка vs Правильно</h3>
        <article data-variant="bad">
            <h4>Ошибка</h4>
            <p>1. Укладка на старую плитку без грунтовки контактной;<br>
            2. Клей наносится только по краям плитки («по пяти точкам»);<br>
            3. Нет гидроизоляции в ванной под плитку;<br>
            4. Затирка цементная в зоне душа — потемнеет через полгода;<br>
            5. Шов между плиткой и ванной не замазан силиконом.</p>
        </article>
        <article data-variant="good">
            <h4>Правильно</h4>
            <p>Грунтовка контактная, клей по всей площади плитки зубчатым шпателем, гидроизоляция, эпоксидная затирка, силиконовый шов у ванны.</p>
        </article>
    </div>
</section>

<div data-type="box" data-color="blue" id="expert">
    <h3>Мнение эксперта Проект Квартира</h3>
    <p>Плитка держится на клее и базе. Если пол или стена не выровнена, клей не выдержит нагрузку — плитка отвалится. Выравнивание основания — обязательный этап перед укладкой.</p>
