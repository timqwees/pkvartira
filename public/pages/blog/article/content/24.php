<section id="electric">
    <h2>Электрика: менять всегда</h2>
    <p>Это единственная система, которую в квартире 20+ лет мы меняем <strong>всегда</strong>, без исключений. Причины технические:</p>
    <ul>
        <li>Алюминиевая проводка 1970–1990-х годов имеет ресурс, подходящий к концу: она греется в розетках под нагрузкой и плавится в местах соединений.</li>
        <li>Проводка 90-х и 2000-х часто выполнена алюминием с пластиковыми скрутками, которые со временем рассыпаются.</li>
        <li>Количество розеток не рассчитано на современную нагрузку: чайник, стиральная машина, микроволновка, ноутбук — на одном удлинителе или в одной группе.</li>
        <li>Заземление в старых домах часто отсутствует или выполнено на металлическую трубу, а не на отдельный проводник.</li>
    </ul>
    <div data-type="box" data-color="yellow">
        <h3>Цена вопроса</h3>
        <p>Замена электрики в однокомнатной квартире — от 45 000 до 90 000 ₽. Это 10–15% бюджета косметического ремонта. Но замена электрики после чистовой отделки — это штробление готовых стен: та же работа, но дороже в 2–3 раза. Поэтому электрика идёт до штукатурки, всегда.</p>
    </div>
</section>

<section id="plumbing">
    <h2>Сантехника и стояки: по состоянию</h2>
    <p>Здесь важно отличать <strong>стояк</strong> (общий для дома, менять нельзя без согласования) и <strong>внутриквартирную разводку</strong> (её можно и нужно).</p>
    <h3>Меняем обязательно</h3>
    <ul>
        <li>Разводку внутри квартиры: стальные трубы на резьбе, залитые в стены, заменяем на полипропилен или коллекторную разводку.</li>
        <li>Стояк горячей воды в старых домах — если он проходит по квартире и выполнен из стали с коррозией.</li>
        <li>Смесители, гибкие подводки, сифоны старше 7 лет.</li>
    </ul>
    <h3>Оставляем, если исправно</h3>
    <ul>
        <li>Чугунный стояк канализации — он служит десятилетиями и разбирать его дорого и бессмысленно.</li>
        <li>Полипропиленовую разводку 2005–2010-х годов, если трубы не свистяли и не течи.</li>
    </ul>
    <div data-type="box" data-color="gray">
        <h3>Как проверить стояк</h3>
        <p>Откройте кран и посмотрите, есть ли ржавый налёт на стыках и вокруг крана. Стояк, который течёт или зарос отложениями, меняют. Рабочий стояк оставляют: замена стояка — это работа с согласованием в управляющей компании и УК.</p>
    </div>
</section>

<section id="walls">
    <h2>Стены и геометрия: главный вопрос бюджета</h2>
    <p>Здесь решается, во сколько обойдётся ремонт. Три варианта:</p>
    <div data-type="compare">
        <h3>Что делать со стенами</h3>
        <article data-variant="good">
            <h4>Вариант 1. Выровнять (рекомендуем)</h4>
            <p>Штукатурка по маякам, гладкая стена под покраску или обои. Дороже на старте, но красиво и долговечно. Это единственный вариант, который тянет дизайнерский ремонт.</p>
        </article>
        <article data-variant="bad">
            <h4>Вариант 2. Оставить как есть</h4>
            <p>Дёшево и быстро, но только если стены ровные и вертикальные. Проверяется уровнем 2 м и правилом откоса. Кривые стены потом всё равно придётся выравнивать — но уже с чистовой отделкой.</p>
        </article>
        <article data-variant="good">
            <h4>Вариант 3. Частичное выравнивание</h4>
            <p>Компромисс: выравниваем только видимые плоскости и места под мебель, остальное закрываем шпаклёвкой. Экономит 30–40% бюджета на штукатурке.</p>
        </article>
    </div>
    <p>Отдельно про <strong>«эффект 2 см»</strong> в панельных домах: перепад между плитами 1–3 см — заводской. Выравнивание одной стены даёт разницу в плоскости с соседней. В панельных домах это несущая стена — трогать нельзя, и застройщик не согласует.</p>
</section>

<section id="floor">
    <h2>Полы: ламинат на стяжку или замена стяжки</h2>
    <p>Вторичка почти всегда требует замены стяжки: под старым финишным покрытием — цементно-песчаная стяжка 60–70-х годов, местами с трещинами и пустотами.</p>
    <ul>
        <li><strong>Стяжку меняем</strong>, если при простукивании звучит пусто, есть трещины, перепады больше 5 мм на метр или дом 1970-х годов.</li>
        <li><strong>Стяжку оставляем</strong>, если она звучит плотно, трещин нет, а перепады в пределах 2–3 мм — тогда поверх кладём новую стяжку тонким слоем или настилаем ламинат прямо на старую (с подложкой и пенополистирольной плиты).</li>
    </ul>
    <p>Замена стяжки в однокомнатной — от 35 000 ₽, в двухкомнатной — от 55 000 ₽. Настил ламината поверх готовой стяжки — от 1 200 ₽/м² с материалом, полный цикл со стяжкой — от 3 500 ₽/м².</p>
</section>

<section id="windows">
    <h2>Окна: менять или ремонтировать</h2>
    <p>Не все окна требуют замены. Критерий простой: <strong>деревянные 90-х и старше — менять, пластиковые 2005-х — ремонтировать.</strong></p>
    <ul>
        <li><strong>Меняем</strong> деревянные, старые алюминиевые и пластиковые с дефектами: продувание, конденсат, раздутие профиля, отсутствие нормальной фурнитуры.</li>
        <li><strong>Ремонтируем</strong> пластиковые 2005–2018 годов: замена фурнитуры, утепление откосов, регулировка притвора, замена стеклопакета на двухкамерный.</li>
    </ul>
    <p>Замена окна в кирпичном доме — от 12 000 ₽ за изделие с монтажом и откосами. Замена всех окон в двухкомнатной — от 60 000 ₽.</p>
</section>

<section id="bath">
    <h2>Санузел: точка невозврата</h2>
    <p>Санузел — единственная зона, где ремонт почти всегда идёт под ключ, без вариантов оставить что-то на месте. Причины:</p>
    <ul>
        <li>Гидроизоляция в советских санузлах отсутствовала: трубы шли в стяжке, а под плиткой — мокрый пол без защиты. За 30 лет это причина трещин в перекрытии у соседей снизу.</li>
        <li>Стояк канализации и разводка труб замурованные — их нужно вскрывать.</li>
        <li>Маленькая площадь: каждый элемент планируется заново, и «оставить» нечего.</li>
    </ul>
    <div data-type="box" data-color="dark">
        <h3>Порядок работ в санузле</h3>
        <p>Демонтаж → гидроизоляция → черновая разводка → стяжка с уклоном → штукатурка → чистовая отделка → установка сантехники и двери. Пропуск гидроизоляции — самая дорогая ошибка: переделка пола и потолка соседей снизу.</p>
    </div>
</section>

