<section id="stage2">
    <h2>Этап 2: Этапы работ — от демонтажа до приёмки</h2>
    <ul>
        <li><strong>1. Демонтаж</strong> — снятие старой плитки, сантехники, вывоз мусора (1-2 дня);</li>
        <li><strong>2. Гидроизоляция</strong> — пол и стены до уровня унитаза + 10 см (2 дня);</li>
        <li><strong>3. Электрика</strong> — розетки в защищённом контуре, освещение IP44 (1 день);</li>
        <li><strong>4. Сантехника</strong> — трубы Rehau, счётчики, смесители, унитаз, душ (2 дня);</li>
        <li><strong>5. Укладка плитки</strong> — пол, стены, плинтус (3-4 дня);</li>
        <li><strong>6. Финал</strong> — затирка, установка мебели, приёмка (1 день).</li>
    </ul>
    <p>Общий срок: 10-14 дней. Без сушки стяжки — быстрее, но риск трещин.</p>
</section>

