<section id="factors">
    <h2>Что меняет итоговую сумму</h2>
    <ul>
        <li><strong>Состояние квартиры на старте.</strong> Новостройка без отделки, новостройка с чистовой отделкой и новостройка с черновой — три разных бюджета при одной площади.</li>
        <li><strong>Состояние инженерии от застройщика.</strong> Если трубы и щиты уже проложены по нормам, капитальный пакет дешевле; если нет — считаем замену полностью.</li>
        <li><strong>Тип дома.</strong> В панельных домах штукатурка толще и сложнее работа с геометрией; в монолите стены ровнее, и объём выравнивания меньше.</li>
        <li><strong>Геометрия.</strong> Скосы, эркеры, нестандартные проёмы требуют отдельных решений и отдельной сметы.</li>
        <li><strong>Класс отделки.</strong> Дизайнерский пакет стоит в 2,25 раза дороже косметического по работам — и это нормально.</li>
        <li><strong>Инженерные требования.</strong> Слабые электросети застройщика, «умный дом», климат-контроль добавляют объём, который окупается при продаже или сдаче.</li>
    </ul>
</section>

<section id="novostroyka-vs-vtorichka">
    <h2>Новостройка против вторички</h2>
    <p>В новостройке вы платите за ремонт «с нуля»: демонтаж, выравнивание, инженерия, отделка. Во вторичке часть работ уже сделана — нужно обновлять, а не создавать. Разница в чеке на сопоставимых площадях обычно 20–35%.</p>
    <p>Взамен новостройка даёт чистую геометрию и новое состояние стен, что критично, если в квартире планируется дизайнерский ремонт с кривыми стенами. Подробное сравнение — в гайде <a href="/blog/remont-novostroyki-2026" style="color:#2563eb;font-weight:600;">«Ремонт в новостройке: с чего начать»</a>.</p>
