<section id="stage5">
    <h2>Этап 5: 5 ошибок, которые ведут к протечке</h2>
    <div data-type="compare">
        <h3>Ошибка vs Правильно</h3>
        <article data-variant="bad">
            <h4>Ошибка</h4>
            <p>1. Гидроизоляция только на полу, не заведено на стены 10 см;<br>
            2. Швы между плиткой и ванной заделаны силиконом, а не эпоксидной затиркой;<br>
            3. Трубы замурованы в стену без доступа к клапанам;<br>
            4. Розетка над раковиной без влагозащиты;<br>
            5. Нет лючка для доступа к счётчикам и фильтрам.</p>
        </article>
        <article data-variant="good">
            <h4>Правильно</h4>
            <p>Гидроизоляция пол+стены, зазор 5 мм между ванной и плиткой, ревизионные лючки, розетки IP44, доступ к клапанам.</p>
        </article>
    </div>
