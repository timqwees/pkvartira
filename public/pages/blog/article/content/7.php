<section id="stage1">
    <h2>Этап 1: Что можно без согласования</h2>
    <p>Эти работы не меняют план БТИ — делайте без похода в Мосжилинспекцию:</p>
    <ul>
        <li>Косметический ремонт — обои, краска, ламинат, натяжной потолок;</li>
        <li>Замена сантехники/плиты на аналогичную без переноса;</li>
        <li>Остекление балкона без изменения фасада (без выноса);</li>
        <li>Установка кондиционера (согласование с УК, но не с МЖИ);</li>
        <li>Замена дверей, встроенная мебель.</li>
    </ul>
</section>

<section id="stage2">
    <h2>Этап 2: Что по эскизу (уведомление в МЖИ)</h2>
    <p>Красные линии на плане БТИ, но без затрагивания несущих. Подаете эскиз через mos.ru — ответ 20 дней:</p>
    <ul>
        <li>Демонтаж ненесущей перегородки (гипсокартон, пазогребень);</li>
        <li>Устройство проёма в ненесущей стене;</li>
        <li>Объединение ванной и туалета (если не несущая);</li>
        <li>Перенос дверного проёма в ненесущей стене.</li>
    </ul>
    <div data-type="box" data-color="yellow">
        <h3>Важно</h3>
        <p>Даже ненесущую стену нельзя сносить «на глаз» — в панельках 80% перегородок — несущие. Закажите техзаключение (5 000 ₽).</p>
    </div>
</section>

<section id="stage3">
    <h2>Этап 3: Что по проекту + техзаключение</h2>
    <p>Любое затрагивание несущих, мокрых зон, газа, фасада — только проект от СРО + техзаключение от автора дома:</p>
    <ul>
        <li><strong>Проём в несущей стене</strong> — проект + усиление металлом, согласование 1,5 месяца;</li>
        <li><strong>Объединение кухни с гостиной</strong> (если газ — только с раздвижной перегородкой, не проём);</li>
        <li><strong>Расширение санузла на коридор</strong> — гидроизоляция + проект;</li>
        <li><strong>Перенос кухни/санузла</strong> — только на нежилую площадь (коридор), не над жилой комнатой соседей;</li>
        <li><strong>Объединение балкона с комнатой</strong> — по проекту, с французским окном (сносить подоконный блок без двери — нельзя).</li>
    </ul>
    <div data-type="box" data-color="blue">
        <h3>Цена проекта 2026</h3>
        <p>Техзаключение — 15 000–30 000 ₽, проект перепланировки — 25 000–45 000 ₽, согласование под ключ — 60 000–90 000 ₽. Делаем за 14–45 дней.</p>
    </div>
</section>

