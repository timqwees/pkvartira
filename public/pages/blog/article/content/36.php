    <h2>Этап 5: 5 ошибок при ремонте брежневки</h2>
    <div data-type="compare">
        <h3>Ошибка vs Правильно</h3>
        <article data-variant="bad">
            <h4>Ошибка</h4>
            <p>1. Экономия на шумоизоляции — слышно соседей сквозь стены;<br>
            2. Старая электрика остаётся — техника сгорает;<br>
            3. Окна не меняются — дует, счета за отопление растут;<br>
            4. Натяжной потолок — теряем высоту без необходимости;<br>
            5. Утепление только изнутри без вентиляции — конденсат и плесень.</p>
        </article>
        <article data-variant="good">
            <h4>Правильно</h4>
            <p>Шумоизоляция, медная электрика, новые окна, штукатурка потолка, грамотная вентиляция при утеплении.</p>
