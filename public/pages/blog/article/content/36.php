    <h2>Этап 3: Основные проблемы брежневки и их решение</h2>
    <div data-type="compare">
        <h3>Проблема vs Решение</h3>
        <article data-variant="bad">
            <h4>Проблема</h4>
            <p>Тонкие стены — слышно соседей;<br>
            Холодные панельные стены — промерзание угла;<br>
            Алюминиевая проводка — выбивает автоматы;<br>
            Старые окна — дует и промерзает;<br>
            Высота потолков 2,7 м — ограничение для дизайна.</p>
        </article>
        <article data-variant="good">
            <h4>Решение</h4>
            <p>Шумоизоляция стен ЗИПС или каркас;<br>
            Утепление фасада или внутренняя изоляция;<br>
            Замена электрики на медную кабелем ВВГнг;<br>
            Замена окон на ПВХ с двухкамерным стеклопакетом;<br>
            Штукатурка потолка вместо натяжного.</p>
        </article>
