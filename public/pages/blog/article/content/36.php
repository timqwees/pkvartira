<section>
    <h2>Подрядчик — решение, от которого зависит 80% результата</h2>
    <p>В 2026 году рынок перенасыщен: от одиночек «мастер на час» до крупных компаний с штатом 50+ человек. Цены за м²: косметический 8–12 тыс. ₽, капитальный 13–20 тыс. ₽, дизайнерский 25–40 тыс. ₽. Разбираем алгоритм выбора: где искать, 10 красных флагов на первой встрече, 15 вопросов на собеседовании, как проверить портфолио и отзывы. Чек-лист безопасности для подписания договора.</p>
</section>

<section>
    <h2>Где искать подрядчика (по убыванию надёжности)</h2>
    <ol>
        <li><strong>Рекомендации знакомых / коллег</strong> — видели результат, могут сказать про характер, сроки, скрытые проблемы. Лучший источник.</li>
        <li><strong>Профильные сайты-агрегаторы</strong> — Профи.ру, YouDo, Авито Услуги, Ремонтник.ру. Есть отзывы, портфолио, рейтинг. Фильтруйте: «только с отзывами», «только компании», «гарантия».</li>
        <li><strong>Архитекторы / дизайнеры</strong> — у них есть проверенные бригады, они знают, кто как работает. Часто рекомендуют 2–3 варианта.</li>
        <li><strong>Выезд на объекты в работе</strong> — если видите ремонт в соседнем подъезде / ЖК — подойдите, поговорите с заказчиком, посмотрите качество, спросите про подрядчика.</li>
        <li><strong>Соцсети / YouTube / Telegram-каналы</strong> — многие прорабы ведут блоги. Смотрите: показывают ли процесс / ошибки / чистовик, или только «до/после».</li>
    </ol>
</section>

<section>
    <h2>10 красных флагов на первой встрече (убегайте сразу)</h2>
    <ol>
        <li><strong>Нет договора-оферты / образца договора</strong> — «работаем по честному слову», «договор только для банка». Без договора — нет ответственности.</li>
        <li><strong>Просит >30% предоплаты</strong> до начала работ / до привозу материалов. Норма: 10–20% аванс на закупку первых материалов, далее — по этапам после приёмки.</li>
        <li><strong>Работает «на чёрную» / самозанятый без чеков</strong> — нет юрлица/ИП, платит налоги «по возможности». При проблеме — исчезнет.</li>
        <li><strong>Нет штатных электриков / сантехников</strong> — «зову знакомых по необходимости». Инженерия — 40% бюджета и 80% рисков. Нужен штат или проверенные субподрядчики с договорами.</li>
        <li><strong>Не показывает объекты в работе</strong> — «заказчики против», «нет времени». Только фото «до/после» в портфолио. Езжайте на 2–3 объекта лично.</li>
        <li><strong>Цена за м² без замеров и сметы</strong> — «у нас 12 000 ₽/м² под ключ». Реальная цена считается после замеров и ТЗ. Фиксированная цена без сметы = доп. соглашения.</li>
        <li><strong>Гарантия только на материалы</strong> — «на работы гарантии нет, материалы от производителя». Гарантия должна быть на работы 3 года (в договоре).</li>
        <li><strong>Нет графика платежей / календарного плана</strong> — «работаем до победного». Без плана — нет контроля сроков.</li>
        <li><strong>Отрицательное отношение к приёмке этапов / актам</strong> — «подпишем в конце». Приёмка каждого этапа (инженерия, стяжка, чистовик) — обязательна.</li>
        <li><strong>Давление / манипуляции / спешка</strong> — «подпишите сегодня, завтра подорожает», «места в графике одно». Нормальный подрядчик даёт время на обдумывание (3–5 дней).</li>
    </ol>
</section>

<section>
    <h2>15 вопросов на собеседовании (записывайте ответы)</h2>
    <ol>
        <li>Какой у вас штат? (электрики, сантехники, штукатуры, плиточники, плинтусники — свои или субподрядчики?)</li>
        <li>Какой график платежей предлагаете? (аванс %, этапы, приёмка, постоплата)</li>
        <li>Как оформляете дополнительные работы? (доп. соглашение, цена, сроки, подписи)</li>
        <li>Кто закупает материалы? (вы привозите / я заказываю / смешанно). Как подтверждаете цены (чеки/накладные)?</li>
        <li>Какая гарантия на работы? (3 года стандарт). Что входит, что нет? Как обращаться при проблеме?</li>
        <li>Какой у вас календарный план? (покажите Гантт: этапы, длительность, зависимости, контрольные точки)</li>
        <li>Как работаете с закупкой материалов? (смета позиционная → заказ → чек → приёмка на складе/объекте)</li>
        <li>Есть ли у вас проектировщик/архитектор в штате? (если нужна перепланировка/дизайн)</li>
        <li>Как решаете конфликты/споры? (доп. соглашение → переговоры → медиация → суд). Есть ли прецеденты судов?</li>
        <li>Какие штрафы за просрочку в договоре? (0.1–1% в день от стоимости этапа/договора)</li>
        <li>Как организована безопасность на объекте? (Охрана труда, СРО, страховка ответственности перед третьими лицами)</li>
        <li>Есть ли страховка ответственности перед заказчиком/соседями? (полис 1–5 млн ₽)</li>
        <li>Как organiseте уборку/вывоз мусора? (ежедневно/еженедельно, контейнер/газоль, вывоз за свой счёт)</li>
        <li>Могу ли я прийти на объект в любое время? (доступ по ключу/кодовому замку, уведомление прораба)</li>
        <li>Пришлите контакты 3 последних заказчиков (позвольте мне с ними поговорить).</li>
    </ol>
</section>

<section>
    <h2>Как проверить портфолио и отзывы (алгоритм)</h2>
    <ol>
        <li><strong>Выберите 2–3 объекта</strong> похожих по типу (квартира/дом, площадь, бюджет, стиль).</li>
        <li><strong>Поезжайте лично</strong> (не фото/видео). Проверьте: щёлочки ламината/плитки, швы краски, регуляровка дверей/окон, работа розеток/смесителей, чистота штукатурки (проволока/лазер).</li>
        <li><strong>Поговорите с заказчиком</strong> (без прораба): сроки (сдали в срок?), бюджет (уложились?), качество (были проблемы?), коммуникация (как реагировали на правки?), гарантия (обращались ли после сдачи?).</li>
        <li><strong>Проверьте отзывы в агрегаторах</strong> (Профи.ру, Яндекс Карты, Google Maps, Авито): ищите паттерны («не уложились в срок», «добавляли работы в счёт», «грязь после уборки», «недоступен по телефону»). 1–2 негатива из 20 — норма, 5+ — тревога.</li>
        <li><strong>Проверьте юрлицо/ИП</strong> через ФНС (nalog.gov.ru — проверка контрагента): статус (действует), дата регистрации (>3 лет — хорошо), ОКВЭД (43.32 — строительные работы), суды/ИП (kad.arbitr.ru — нет иски от заказчиков).</li>
        <li><strong>Страховка ответственности</strong> — попросите полис (ОСГОП / ДОГО / профессиональная ответственность). 1–5 млн ₽ покрытия. Если нет — риск на вас.</li>
    </ol>
</section>

