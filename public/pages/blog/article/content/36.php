<section id="stage4">
    <h2>Этап 4: Этапы ремонта брежневки под ключ</h2>
    <ul>
        <li><strong>1. Замер и проект</strong> — учёт несущих стен, ниш, расположения коммуникаций (2-3 дня);</li>
        <li><strong>2. Демонтаж</strong> — старые покрытия, сантехника, электрика (2-3 дня);</li>
        <li><strong>3. Шумоизоляция</strong> — стены, потолок, пол (3-5 дней);</li>
        <li><strong>4. Электрика</strong> — замена на медную, новые розетки (4-6 дней);</li>
        <li><strong>5. Стены и потолки</strong> — штукатурка, шпаклёвка, покраска (6-10 дней);</li>
        <li><strong>6. Пол</strong> — стяжка, ламинат или линолеум (5-7 дней + сушка);</li>
        <li><strong>7. Сантехника</strong> — замена труб, унитаза, раковины, ванны (3-5 дней);</li>
        <li><strong>8. Окна и двери</strong> — установка (1-2 дня);</li>
        <li><strong>9. Финальная уборка</strong> (1 день).</li>
    </ul>
    <p>Общий срок: 4-8 недель.</p>
</section>

