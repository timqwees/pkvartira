<section id="stage1">
    <h2>Этап 1: Особенности брежневки — что учитывать</h2>
    <ul>
        <li><strong>Потолки 2,7 м</strong> — можно позволить себе натяжной потолок, но штукатурка практичнее;</li>
        <li><strong>Тонкие стены</strong> — звукоизоляция обязательна, особенно между квартирами;</li>
        <li><strong>Панельные или кирпичные стены</strong> — панели холодные, нужно утепление;</li>
        <li><strong>Отдельный санузел</strong> — удобно, но требует отдельной гидроизоляции;</li>
        <li><strong>Балкон или лоджия</strong> — часто требуют остекления и утепления;</li>
        <li><strong>Старая электрика</strong> — алюминий, замена обязательна для современной техники.</li>
    </ul>
