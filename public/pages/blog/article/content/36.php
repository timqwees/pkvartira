    <h2>Чек-лист безопасности перед подписанием договора</h2>
    <ul>
        <li>[ ] Юрлицо/ИП проверено (ФНС, kad.arbitr.ru, ОКВЭД 43.32)</li>
        <li>[ ] Договор: предмет (ссылка на смету/чертежи), фиксированная цена или механизм индексации, календарный план с контрольными точками, график платежей (этапы + %), приёмка этапов (акты), гарантия 3 года на работы, штрафы за просрочку (0.1–1%/день), порядок изменений (доп. соглашения), ответственность сторон, разрешение споров</li>
        <li>[ ] Приложение 1: Позиционная смета (позиция, ед., кол-во, цена, сумма, материал/работа)</li>
