        <li>[ ] Прораб назначен (ФИО, телефон, ответственность за график/качество/безопасность)</li>
        <li>[ ] Ключи/доступ: как вы будете заходить на объект (кодовый замок, ключ у прораба, агентство)</li>
    </ul>
