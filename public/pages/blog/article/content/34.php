<section>
    <h2>Цвет — не декор, а инструмент управления состоянием</h2>
    <p>В 2026 году уходят от «бежевого по умолчанию» к осознанным палитрам. Нейробиология подтверждает: цвет влияет на пульс, давление, выработку кортизола/мелатонина/дофамина, аппетит, концентрацию. Разбираем, как подобрать палитру под задачу каждой зоны: сон, аппетит, развитие, фокус, релакс.</p>
</section>

<section>
    <h2>Спальня: цель — глубокий сон и восстановление</h2>
    <p><strong>Лучшие оттенки:</strong> Холодные и глухие — снижают пульс и давление, стимулируют мелатонин.</p>
    <ul>
        <li><strong>Синий / голубой (RAL 5024, 5014, 5007):</strong> Наиболее сонный цвет. Пульс -5–10 уд/мин. Идеально для стен за кроватью (акцентная стена) или текстиля.</li>
        <li><strong>Зелёный / сажовый / мховый (RAL 6021, 6019, 6013):</strong> Цвет природы, баланс нервной системы. Работает мягче синего, подходит на все стены.</li>
        <li><strong>Серый / графит (RAL 7015, 7016, 7043):</strong> Нейтральный, не стимулирует. В сочетании с тёплым деревом/текстилем — уютно, не больнично.</li>
        <li><strong>Лавандовый / пудровый (RAL 4009, 4005):</strong> Мягкий переход к сну, снижает тревожность.</li>
    </ul>
    <p><strong>Ошибки:</strong> Чистый белый (больничный вид, отражает уличный свет), яркий жёлтый/оранжевый/красный (стимулируют кортизол), неоновые акценты в зоне головы. Тёмный пол в малой северной спальне — «яма», визуально давит.</p>
    <p><strong>Готовые палитры (RAL/NCS):</strong> 1) Стены: RAL 7044 (Silk Grey) + акцент RAL 5014 (Pigeon Blue). 2) Стены: NCS S 4010-G10Y (Sage) + текстиль RAL 5024 (Pastel Blue). 3) Стены: RAL 7015 (Slate Grey) + декор RAL 4009 (Pastel Violet).</p>
</section>

<section>
    <h2>Кухня-гостиная: цель — аппетит, общение, энергия</h2>
    <p><strong>Лучшие оттенки:</strong> Тёплые и натуральные — стимулируют аппетит, дофамин, социализацию.</p>
    <ul>
        <li><strong>Терракота / охра / глина (RAL 3012, 3014, 8023):</strong> Цвет еды, уюта, камина. Работает на всех стенах или кухонном фартуке/островке.</li>
        <li><strong>Оливковый / хаки / моккий хвоя (RAL 6013, 6021, 7033):</strong> Природа, свежесть, гармония с деревом. Идеален для кухонных фасадов.</li>
        <li><strong>Горчичный / заваренный сахар / карамель (RAL 1024, 1011, 8001):</strong> Тепло, сладость, уют. Акценты: стулья, текстиль, керамика.</li>
        <li><strong>Тёплый бежевый / песок / льняной (RAL 1019, 1013, 1001):</strong> Нейтральная база, не устаревает. Для стен при тёплом полу/дереве.</li>
    </ul>
    <p><strong>Ошибки:</strong> Холодный синий/зелёный в кухне — снижает аппетит (диетический эффект, но не для семейных ужинов). Чистый белый — пятна жира/вина видны мгновенно, стерильный вид. Всё тёмное (графит/черный) в малой кухне — визуально ужимает.</p>
    <p><strong>Готовые палитры:</strong> 1) Фасады: RAL 6013 (Reed Green) + стены RAL 1013 (Oyster White) + акценты RAL 8023 (Orange Brown). 2) Стены: RAL 3012 (Beige Red) + фасады RAL 7032 (Pebble Grey) + топ RAL 1024 (Ochre Yellow).</p>
</section>

<section>
    <h2>Детская: цель — развитие, безопасность, адаптивность</h2>
    <p><strong>Принцип:</strong> База нейтральная (стены/потолок/пол), акценты возрастные и легко меняемые (текстиль, ковры, наклейки, плакаты). Не красьте стены в «розовый для девочки / синий для мальчика» — через 2 года перерисуете.</p>
    <ul>
        <li><strong>0–3 года (младенец):</strong> Контрастные ч/б/красный (развитие зрения), мягкие пастельные (спокойствие мамы). Стены: RAL 9010 (Pure White) + акценты RAL 3015 (Light Pink) / RAL 5012 (Light Blue).</li>
        <li><strong>3–7 лет (дошкольник):</strong> Яркие, но не неоновые. Жёлтый (интеллект), оранжевый (творчество), зелёный (природа), синий (спокойствие). Стены: RAL 1018 (Zinc Yellow) + RAL 6019 (Pastel Green) + декор RAL 2003 (Pastel Orange).</li>
        <li><strong>7–12 лет (младший школьник):</strong> Фокус и отдых. Синий/зелёный у стола (концентрация), тёплые акценты в зоне игр/сна. Стены: RAL 5014 (Pigeon Blue) + зонирование коврами/текстилем.</li>
        <li><strong>12+ (подросток):</strong> Дать выбрать самим. База нейтральная (серый/бежевый/белый), акценты — постеры, LED-лента, ковер, одеяло. Стены: RAL 7044 (Silk Grey) + персонализация.</li>
    </ul>
    <p><strong>Универсальная формула:</strong> Стены — NCS S 0502-Y / RAL 9002 (Grey White) + 1 акцентная стена (возрастной цвет) + текстиль/декор 30% насыщенности.</p>
</section>

<section>
    <h2>Кабинет / Home Office: цель — фокус, продуктивность, снижение усталости</h2>
    <p><strong>Лучшие оттенки:</strong> Глубокие, насыщенные, низкой яркости — не отвлекают, создают «туннель фокуса».</p>
    <ul>
        <li><strong>Графит / антрацит (RAL 7016, 7021, 9004):</strong> Максимальный фокус, минимум визуального шума. Для акцентной стены за монитором.</li>
        <li><strong>Тёмно-синий / индиго (RAL 5004, 5011, 5013):</strong> Интеллектуальный цвет, стимулирует когнитивные функции. Для стен или фасадов шкафов.</li>
        <li><strong>Бордово / вишнёвый (RAL 3004, 3005, 4004):</strong> Энергия, решительность. Для акцентов (стул, лампа, ковер).</li>
        <li><strong>Оливковый / хаки (RAL 6014, 6022, 7034):</strong> Баланс, снижение усталости глаз. Для стен при большом окне.</li>
    </ul>
    <p><strong>Правило 60-30-10:</strong> 60% база (стены/пол/потолок — нейтрал), 30% второстепенный (мебель/шкафы/двери — глубокий тон), 10% акцент (декор/лампа/стул/ковер — насыщенный).</p>
</section>

<section>
    <h2>Ванная: цель — свежесть, чистота, пробуждение</h2>
    <ul>
        <li><strong>Белый / молочный / ледяной (RAL 9010, 9016, 9003):</strong> Классика, визуально расширяет, показывает чистоту.</li>
        <li><strong>Аква / ментол / морская волна (RAL 5018, 6027, 6034):</strong> Прохлада, вода, СПА-эффект.</li>
        <li><strong>Песок / беж / кремовый (RAL 1013, 1014, 1015):</strong> Тепло, уют, маскирует водяные разводы.</li>
        <li><strong>Графит / антрацит (RAL 7016, 7021):</strong> Только для больших ванных (>6 м²) с хорошим светом. Дорогой, люксовый вид.</li>
    </ul>
    <p><strong>Лайфхак:</strong> Плитка 2-х цветов (зонирование): пол — тёмный (прячет волосы/пыль), стены — светлый (расширяет). Шов эпоксидный (не пожелтеет, не погрибнеет).</p>
</section>

<section>
    <h2>Ошибки подбора цвета (топ-7)</h2>
    <ol>
        <li><strong>Выбор цвета в магазине под их светом (4000–6500K)</strong> — дома при 2700–3000K оттенок другой. Берите образец домой, смотрите утром/днём/вечером/при свете ламп.</li>
        <li><strong>Игнорирование ориентации окна</strong> — северная комната «съедает» тепло (нужны тёплые подтоны), южная — «перегревает» холодные (нужны глухие/холодные).</li>
        <li><strong>Покраска потолка в цвет стен (не белый)</strong> — визуально снижает потолок, давит. Потолок всегда белый / на 1–2 тона светлее стен.</li>
        <li><strong>Слишком насыщенный цвет на большой площади</strong> — утомляет глаза за 20 мин. Насыщенность стены <30% (NCS S 3020-R90B, не S 6030-R90B).</li>
        <li><strong>Неучёт подтонов (undertones)</strong> — бежевый может быть розоватым, жёлтоватым, зелёноватым. Сравнивайте с эталонным серым (RAL 7044).</li>
        <li><strong>Цвет пола не в палитре</strong> — тёмный ламинат «съедает» светлые стены, светлый — мерцает при ярком свете. Пол = 3-й цвет палитры (база).</li>
        <li><strong>Купля краски без пробы (тестера 100 мл)</strong> — покрасьте лист А4, приклейте на стену, смотрите 3 дня в разное время.</li>
    </ol>
</section>

