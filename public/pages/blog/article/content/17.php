<section id="stage4">
    <h2>Этап 4: Чек-лист проверки сметы за 10 минут</h2>
    <ul>
        <li>☐ Есть разбивка работа/материал с брендом и расходом?</li>
        <li>☐ Нет двойных строк (грунтовка×2, доставка×2)?</li>
        <li>☐ Коэффициенты обоснованы фото перепадов?</li>
        <li>☐ Цена смеси = Леруа/Петрович + 5–10%, не ×2?</li>
        <li>☐ Вывоз — контейнер, не мешки по 500 ₽?</li>
        <li>☐ Гарантия бесплатно, не 3%?</li>
        <li>☐ Итог фиксируется в договоре без «ориентировочно»?</li>
    </ul>
    <p>Если 2+ пункта — нет, просите переделать. Или пришлите нам смету в Telegram — проверим бесплатно за 30 минут.</p>
