<section id="stage1">
    <h2>Этап 1: Из чего состоит смета: 5 разделов</h2>
    <p>Профессиональная смета — не «лист А4 с итогом», а 15–30 страниц с детализацией. 5 обязательных разделов:</p>
    <div data-type="box" data-color="gray">
        <h3>Структура сметы Проект Квартира</h3>
        <p><strong>1. Демонтаж:</strong> снятие старого, вывоз мусора (мешки, контейнер);<br>
        <strong>2. Черновые работы:</strong> штукатурка, стяжка, электрика, сантехника — около 45% бюджета;<br>
        <strong>3. Чистовые:</strong> плитка, ламинат, покраска, двери — около 35%;<br>
        <strong>4. Материалы:</strong> отдельно черновые (смеси, кабели) и чистовые (плитка, ламинат) — раздельно;<br>
        <strong>5. Логистика:</strong> доставка, подъем, уборка — 5–7%.</p>
    </div>
    <p>Если в смете нет разбивки «работа/материал» — требуйте детализацию. Иначе вам продадут мешок Ротбанда за 800 ₽ при цене 400 ₽ в Леруа.</p>
</section>

<section id="stage2">
    <h2>Этап 2: 12 скрытых накруток — чек-лист</h2>
    <p>Топ-12 где «теряются» деньги. Проверьте каждую строку:</p>
    <div data-type="compare">
        <h3>Накрутка vs Честно</h3>
        <article data-variant="bad">
            <h4>Накрутка</h4>
            <p>«Подготовка основания» без расшифровки — 1200 ₽/м². «Коэффициент сложности» ×1,5 без обоснования. «Доставка» отдельной строкой + уже в цене материалов.</p>
        </article>
        <article data-variant="good">
            <h4>Честно</h4>
            <p>Каждая строка: «Штукатурка стен Ротбанд 10 мм — 580 ₽/м² (работа 350 + материал 230)». Коэффициент — только с фото перепадов. Доставка — одна строка.</p>
        </article>
    </div>
    <ul>
        <li><strong>1. Двойная грунтовка:</strong> считают 2 раза — до и после штукатурки, хотя грунт один;</li>
        <li><strong>2. Завышенный расход:</strong> смеси на 30% больше нормы Кнауф (25 кг на 3 м² при 10 мм);</li>
        <li><strong>3. «Скрытые» 10%:</strong> «Накладные расходы 10%» без расшифровки — 120 000 ₽ на 60 м²;</li>
        <li><strong>4. Коэффициент 1,3–1,5:</strong> «за стесненность» в пустой новостройке;</li>
        <li><strong>5. Вывоз мусора мешками:</strong> 500 ₽/мешок при цене контейнера 8000 ₽ на 20 м³;</li>
        <li><strong>6. Штробление:</strong> считают метры штробы + отдельно «укладка кабеля» — это одна работа;</li>
        <li><strong>7. Плитка:</strong> затирка и крестики отдельной строкой, хотя входит в укладку;</li>
        <li><strong>8. Плинтус:</strong> монтаж + покраска + «подрезка углов» — три строки за одно;</li>
        <li><strong>9. Материалы без чека:</strong> «смесь — 600 ₽» без бренда — кладут самую дешевую;</li>
        <li><strong>10. «Черновой материал premium»:</strong> наценка 40% за «немецкий» Ротбанд из Леруа;</li>
        <li><strong>11. Доставка×2:</strong> доставка + подъем + «разгрузка» — одно и то же;</li>
        <li><strong>12. Гарантия за деньги:</strong> «гарантия 1 год — 3% от сметы» — гарантия по закону бесплатна.</li>
    </ul>
    <div data-type="box" data-color="red">
        <h3>Красный флаг</h3>
        <p>Смета на 1 листе без разбивки по комнатам и без бренда материалов — 99% накрутка. Требуйте 15+ страниц с фото замеров.</p>
    </div>
