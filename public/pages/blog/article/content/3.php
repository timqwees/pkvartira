<section id="stage1">
    <h2>Этап 1: Что входит в косметический ремонт</h2>
    <p>Косметический ремонт — это обновление видимых поверхностей без замены инженерных систем. Всё, что находится «над стяжкой» и «перед трубами»:</p>
    <ul>
        <li>Стены: покраска, поклейка обоев, декоративная штукатурка;</li>
        <li>Потолок: побелка, покраска, натяжные конструкции;</li>
        <li>Пол: замена напольного покрытия (ламинат, линолеум, кварцвинил);</li>
        <li>Двери и плинтусы: замена или обновление;</li>
        <li>Сантехника: замена смесителей, унитаза, раковины (без переноса).</li>
    </ul>
    <div data-type="box" data-color="dark">
        <h3>Граница kosметического ремонта</h3>
        <p>Как только вы начинаете штробить стены, менять трубы или переносить розетки — это уже капитальный ремонт. Для kosметического достаточно «мокрых» процессов: шпаклёвка, штукатурка, покраска.</p>
    </div>
</section>

<section id="stage2">
    <h2>Этап 2: Бюджет 2026 (до 500 000 ₽)</h2>
    <p>В 2026 году цены на материалы выросли на 12–15% относительно 2025 года. Но kosметический ремонт остаётся доступным при грамотном подходе:</p>
    <div data-type="compare">
        <h3>Разумная экономия vs Ложная экономия</h3>
        <article data-variant="good">
            <h4>Разумная экономия</h4>
            <p>Кварцвинил вместо паркета. Краска вместо обоев (дешевле в 2 раза). Мебель с реставрацией. Натяжной потолок — самый бюджетный вариант.</p>
        </article>
        <article data-variant="bad">
            <h4>Ложная экономия</h4>
            <p>Дешёвый клей для плитки — отвалится через полгода. Линолеум за 300 ₽/м² — токсичен и быстро протирается. Экономия на грунтовке — отслоение краски.</p>
        </article>
    </div>
</section>

<section id="stage3">
    <h2>Этап 3: Пошаговый план обновления (5 шагов)</h2>
    <h3>Шаг 1: Оценка состояния</h3>
    <p>Проверьте стены на трещины, пол — на скрипы, потолок — на пятна. Составьте список дефектов. Если стены ровные — хватит шпаклёвки.</p>
    <h3>Шаг 2: Выбор материалов</h3>
    <p>Определите цветовую гамму. В 2026 в тренде тёплые нейтральные оттенки: «латте», «пыльная роза», «шампань».</p>
    <h3>Шаг 3: Демонтаж старого</h3>
    <p>Снимите обои, демонтируйте старый плинтус и двери. Если пол в хорошем состоянии — кварцвинил можно укладывать поверх.</p>
    <h3>Шаг 4: Подготовка поверхностей</h3>
    <p>Грунтовка, шпаклёвка, шлифовка. На этом этапе нельзя экономить — качество финиша напрямую зависит от подготовки.</p>
    <h3>Шаг 5: Финишная отделка</h3>
    <p>Потолок → стены → пол. Именно в такой последовательности, чтобы не испачкать готовые поверхности.</p>
</section>

<section id="stage4">
    <h2>Этап 4: Материалы — что выбрать</h2>
    <p>Для kosметического ремонта рекомендуем:</p>
    <ul>
        <li>Ламинат 32-33 класс — 600–1200 ₽/м²;</li>
        <li>Кварцвинил — 1200–2000 ₽/м²;</li>
        <li>Влагостойкая краска — 300–700 ₽/м²;</li>
        <li>Обои виниловые — 200–600 ₽/рулон.</li>
    </ul>
    <p>Для расчёта количества материалов используйте <a href="/kalkulyator-ploshchadi" rel="nofollow">калькулятор площади ремонта</a> — так вы купите ровно столько, сколько нужно.</p>
</section>

<section id="stage5">
    <h2>Этап 5: Сроки и когда выезжать</h2>
    <p>Косметический ремонт однокомнатной квартиры — 10–14 дней, двухкомнатной — до 3 недель. Желательно выехать, но не обязательно: если ремонт идёт поэтапно, можно оставаться, особенно при использовании быстросохнущих материалов.</p>
</section>

