<section id="stage1">
    <h2>Этап 1: Дизайнерский ремонт vs Евроремонт</h2>
    <p>Чем отличается настоящий дизайнерский ремонт от того, что называют «евроремонтом»?</p>
    <div data-type="compare">
        <h3>Подход к проекту</h3>
        <article data-variant="good">
            <h4>Дизайнерский ремонт</h4>
            <p>Индивидуальный проект с архитектурными решениями (ниши, подсветка, перегородки). Авторский подбор материалов. Авторский надзор на всех этапах. Результат — единственный в своём роде.</p>
        </article>
        <article data-variant="bad">
            <h4>Евроремонт</h4>
            <p>Типовые решения из каталога. Ровные стены, подвесной потолок, стандартная сантехника. «Как у всех». Визуально чисто, но без души и индивидуальности.</p>
        </article>
    </div>
</section>

<section id="stage2">
    <h2>Этап 2: Сколько стоит дизайнерский ремонт в 2026</h2>
    <p>Цены на дизайнерский ремонт в 2026 году стартуют от 35 000 ₽/м² и не имеют верхней границы:</p>
    <ul>
        <li>Дизайн-проект — 3 000–10 000 ₽/м² (в зависимости от сложности);</li>
        <li>Черновые работы — 10 000–15 000 ₽/м²;</li>
        <li>Чистовые материалы — от 15 000 ₽/м²;</li>
        <li>Мебель на заказ — от 1 000 000 ₽ за типовой набор;</li>
        <li>Авторский надзор — 10–15% от бюджета работ.</li>
    </ul>
    <div data-type="box" data-color="gray">
        <h3>Примерно</h3>
        <p>Дизайнерский ремонт квартиры 60 м² в Москве — от 3 до 6 млн ₽. Срок — 4–6 месяцев.</p>
    </div>
</section>

<section id="stage3">
    <h2>Этап 3: Архитектурный подход — что это значит</h2>
    <p>Главный тренд 2026 года — отказ от декора ради декора. Архитектурный подход подразумевает:</p>
    <ul>
        <li><strong>Работу с пространством</strong> — объём, свет, материалы, а не количество деталей;</li>
        <li><strong>Встроенные системы</strong> — скрытые двери, плинтусы невидимки, спрятанная техника;</li>
        <li><strong>Монохромные палитры</strong> — один цвет в разных фактурах создаёт глубину без пёстроты;</li>
        <li><strong>Минимализм с характером</strong> — минимум мебели, максимум качества.</li>
    </ul>
    <div data-type="box" data-color="dark">
        <h3>Умный дом как часть архитектуры</h3>
        <p>В премиум-сегменте умный дом интегрируется на этапе проекта: шторы, свет, климат, безопасность — всё управляется с одной панели и голосом.</p>
    </div>
</section>

<section id="stage4">
    <h2>Этап 4: Материалы премиум-класса</h2>
    <p>В дизайнерском ремонте используют только натуральные материалы:</p>
    <ul>
        <li>Шпон натурального дерева для стен и мебели;</li>
        <li>Мрамор и гранит в столешницах и напольных покрытиях;</li>
        <li>Латунь и состаренная бронза для фурнитуры;</li>
        <li>Текстиль ручной работы (шёлк, лён, кашемир).</li>
    </ul>
</section>

<section id="stage5">
    <h2>Этап 5: Сроки и бюджет по примерам</h2>
    <p>Квартира 60 м², дизайнерский ремонт — от 3 до 6 млн ₽, срок 4–6 месяцев. Квартира 100 м² — от 5 до 9 млн ₽, срок 6–8 месяцев.</p>
</section>

