<section>
    <h2>Гарантийное обслуживание: когда звонить подрядчику</h2>
    <ul>
        <li><strong>Входит в гарантию (3 года):</strong> Протечка труб/смесителей (не механическое повреждение), отслоение плитки/ламината (не по вине эксплуатации), трещины штукатурки/шпаклевки >2 мм, неисправность электрики/сантехники (заводской брак/монтаж), конденсат в окнах (разделёк стеклопакта), скрип дверей/петлей (регулировка), отслоение плинтусов/молдингов.</li>
        <li><strong>НЕ входит в гарантию:</strong> Механические повреждения (сколы плитки, вмятины ламината, царапины паркета от мебели/песка), загрязнения, неудаляемые пятна, естественный износ (потёртость ламината в проходных зонах, потускнение краски на солнце), повреждения от перепадов напряжения (нет УЗИП/стабилизатора), вмешательство посторонних лиц (другой мастер «подкрутил»), форс-мажор (пожар, затопление сверху, землетрясение).</li>
        <li><strong>Процедура вызова:</strong> Фото/видео проблемы → сообщение прорабу (ТГ/WA/звонок) → описание: что, где, когда появилось → прораб приезжает за 3 рабочих дня → акт осмотра → ремонт за 7–14 дней (зависит от запчастей) → акт выполненных гарантийных работ.</li>
    </ul>
</section>

