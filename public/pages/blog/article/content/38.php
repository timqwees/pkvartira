<section id="stage4">
    <h2>Этап 4: Этапы разработки проекта</h2>
    <ul>
        <li><strong>1. Встреча и ТЗ</strong> — пожелания, бюджет, стиль, фото нравится/не нравится (1-2 дня);</li>
        <li><strong>2. Замер объекта</strong> — точные размеры, фот фиксация (1 день);</li>
        <li><strong>3. Планировочные решения</strong> — 2-3 варианта, выбор одного (5-7 дней);</li>
        <li><strong>4. Эскизы и 3D-визуализация</strong> — вид комнат, согласование (5-10 дней);</li>
        <li><strong>5. Рабочие чертежи</strong> — электрика, сантехника, полы, потолки, развёртки (7-14 дней);</li>
        <li><strong>6. Ведомость материалов</strong> — подбор, артикулы, где купить (3-5 дней);</li>
        <li><strong>7. Сдача проекта</strong> — печатный и электронный вариант (1 день).</li>
    </ul>
    <p>Общий срок: 2-6 недель.</p>
</section>

