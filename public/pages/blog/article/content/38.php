<section>
    <h2>Приёмка объекта: чек-лист 50 пунктов (скачайте PDF)</h2>
    <p><strong>Электрика (10 пунктов):</strong></p>
    <ol>
        <li>Щиток: группы подписаны, автоматики/УЗО работают (тест кнопкой), заземление <4 Ом</li>
        <li>Розетки: все работают (проверка индикатором), заземлённые, плотное сидение вилки</li>
        <li>Выключатели: все работают, не кликают, диммеры плавно регулируют</li>
        <li>Светильники: все горят, нет мерцания, димминг работает, цветовая температура верная</li>
        <li>Умный дом: сценарии запускаются, датчики срабатывают, приложение управляет</li>
        <li>Кондиционер/бризер: режимы работают, пульт/приложение, фильтры чистые</li>
        <li>Проводка: нет нагрева розеток/автоматиков под нагрузкой (фен/чайник 2 кВт)</li>
        <li>Счётчики: показания сняты, передаются в Мосгаз/Мосэнерго/УК</li>
        <li>Питание: нет перепадов напряжения (мультиметр 220±10В)</li>
        <li>Заземление бытовой техники: стиралка/ПММ/ холодильник — заземлены</li>
    </ol>
    <p><strong>Сантехника (10 пунктов):</strong></p>
    <ol>
        <li>Напор: 3–4 бар (манометр), одинаковый на всех точках</li>
        <li>Течь: 24-часовой тест под давлением (нет капель на стыках/гибких/кранах)</li>
        <li>Сливы: уклон 2–3 см/м, вода уходит мгновенно, нет запахов (сифоны наполнены)</li>
        <li>Унитазы: слив работает (полная/половинчатая), бачок не течёт, сиденье мягкое закрывание</li>
        <li>Смесители: переключение душ/ванна, термостат держит 38°C, аэрозатор не рабрызгивает</li>
        <li>Душная/ванна: поддон не прогибается, стекло чистое, дверь закрывается, магниты держат</li>
        <li>Полотенцесушитель: нагрев (водяной/электрический), нет течи, клапаны Мейевского</li>
        <li>Счётчики ХВС/ГВС: показания сняты, пломбы целы</li>
        <li>Гидроизоляция: под ванной/душем/унитазом — пролив воды 2 ч (нет протечек у соседей)</li>
        <li>Вентиляция: тяга в санузле (свеча/салфетка прижимается к решётке), бризер/рекуператор работают</li>
    </ol>
    <p><strong>Покрытия и стены (10 пунктов):</strong></p>
    <ol>
        <li>Ламинат/SPC/паркет: щёлочки <0.2 мм, замки защёлкнуты, зазоры к стенам 8–10 мм, плинтуса плотная</li>
        <li>Плитка/керамогранит: швы ровные (кресточки 1.5–2 мм), кроссовер в углах, уклон в слив 2%, нет пустых под плиткой (стук)</li>
        <li>Краска/шпаклевка: нет пробегов/пропусков/бугров, равномерность (освещение 45°), цвет соответствует образцу</li>
        <li>Потолок: натяжной — ровный, без волн/затяжек, люстры centred; ГКЛ — швы невидимы, краска равномерная</li>
        <li>Двери: закрываются без усилий, защёлки срабатывают, петли не скрипят, зазоры равномерные 2–3 мм</li>
        <li>Окна: створки закрываются с микровентиляцией, фурнитура работает, нет сквозняков (свеча)</li>
        <li>Плинтуса/морёнки/угловые: зафиксированы, нет зазоров к полу/стене, цвет соответствует</li>
        <li>Мебель (встроенная): фасады ровные, петли/газ-лифты работают, выкатные корзины плавно</li>
        <li>Декоративные элементы: зеркала/картины/полки — закреплены надёжно, уровень</li>
        <li>Уборка: нет строительной пыли, пятен клея/краски/цемента, стекла чистые (внутри/снаружи)</li>
    </ol>
    <p><strong>Документы и доступ (10 пунктов):</strong></p>
    <ol>
        <li>Акт приёмки-передачи объекта (подписан 2 экз.)</li>
        <li>Акты скрытых работ (электрика, сантехника, вентиляция) — подписаны</li>
        <li>Акты приёмки этапов (стяжка, штукатурка, чистовик) — подписаны</li>
        <li>Гарантийные талоны на всё оборудование (кондиционер, бризер, стиралка, ПММ, холодильник, смесители, унитазы, двери, окна, натяжной потолок)</li>
        <li>Инструкции по эксплуатации (бумажные/QR-коды на PDF в облаке)</li>
        <li>Схемы: электрика (щиток), сантехника (разводка), вентиляция (воздуховоды), тёплый пол (петли)</li>
        <li>Ключи: входная дверь (2 комплекта), межкомнатные, оконные рукоятки, щиток, счётчики</li>
        <li>Контакты: прораб (тел., ТГ), бригады (электрики, сантехники), поставщики материалов</li>
        <li>Чеки на материалы (сканы в облаке/бумажные в папке)</li>
        <li>Доп. соглашения (если были) — подписаны, оплачены</li>
    </ol>
</section>

