<section id="stage2">
    <h2>Этап 2: Что входит в дизайн-проект — состав</h2>
    <ul>
        <li><strong>Техническое задание</strong> — пожелания, бюджет, стиль, площадь;</li>
        <li><strong>Замер и план размещения</strong> — точные размеры, расположение стен, окон, дверей;</li>
        <li><strong>Планировочные решения</strong> — 2-3 варианта расстановки мебели;</li>
        <li><strong>Эскизы интерьера</strong> — визуализация каждой комнаты (3D или коллажи);</li>
        <li><strong>Чертежи расстановки мебели и оборудования</strong> — для монтажников;</li>
        <li><strong>Электрический план</strong> — розетки, выключатели, освещение, щит;</li>
        <li><strong>Сантехнический план</strong> — расположение точек воды, канализации;</li>
        <li><strong>План полов и потолков</strong> — материалы, уровни, зонирование;</li>
        <li><strong>Развёртки стен</strong> — укладка плитки, расположение мебели по стенам;</li>
        <li><strong>Ведомость отделочных материалов</strong> — бренды, артикулы, количество;</li>
        <li><strong>Авторский надзор</strong> — выход дизайнера на объект (опционально).</li>
    </ul>
</section>

