    /** Карточка тарифа */
    private static function card(string $title, string $priceLabel, int $priceNum, string $subtitle, array $features, string $button, bool $recommended = false): array
    {
        $card = [
            'заголовок' => $title,
            'цена' => $priceLabel,
            'цена_число' => $priceNum,
            'подзаголовок' => $subtitle,
            'услуги' => $features,
            'кнопка' => $button,
            'стиль' => $recommended ? 'рекомендуем' : 'обычный',
            'per_m2' => true,
        ];
        if ($recommended) {
            $card['бейдж'] = 'Рекомендуем';
        }

        return $card;
    }

    /** Заголовок для шаблонов, где используется $title */
    public static function title(string $slug): string
    {
        return self::TITLES[$slug] ?? '';
    }

    /** Портфолио в формате, который ждут шаблоны услуг (ключи на русском) */
    public static function portfolio(string $slug): array
    {
        $typeMap = [
            'doma' => ['Дома', 'Коттеджи'],
            'novostroyka' => ['Новостройки'],
            'vtorichka' => ['Вторичка'],
            'pod-klyuch' => [],
            '1room' => ['1-комнатные'],
            '2room' => ['2-комнатные'],
            '3room' => ['3-комнатные'],
            '4room' => ['4-комнатные'],
            'studio' => ['Студии'],
        ];

        $wanted = $typeMap[$slug] ?? [];
        $items = TheFunction::portfolioItems();

        if ($wanted) {
            $filtered = array_values(array_filter($items, static function ($item) use ($wanted) {
                return in_array($item['type'] ?? '', $wanted, true);
            }));
            if ($filtered) {
                $items = $filtered;
            }
        }

        $out = [];
        foreach (array_slice($items, 0, 6) as $item) {
            $out[] = [
                'заголовок' => $item['title'] ?? '',
                'срок' => $item['duration'] ?? '',
                'цена' => $item['price'] ?? '',
                'текущая_папка' => $item['folder_image'] ?? '',
                'площадь' => $item['size'] ?? '',
                'slug' => $item['slug'] ?? '',
            ];
        }

        return $out;
    }

    /** Переменные кейс-блока ($caseCover и др.) для страниц ЖК */
    public static function caseVars(): array
    {
        $items = TheFunction::portfolioItems();
        $item = $items[0] ?? [];

        $cover = '';
        if (!empty($item['folder_image']) && !empty($item['cover'])) {
            $cover = '/' . ltrim((string) $item['folder_image'], '/') . '/' . $item['cover'];
        }

        return [
            'caseCover' => $cover,
            'caseTitle' => $item['title'] ?? '',
            'caseSize' => $item['size'] ?? '',
            'caseDuration' => $item['duration'] ?? '',
            'casePrice' => $item['price'] ?? '',
            'caseUrl' => '/portfolio',
        ];
    }
